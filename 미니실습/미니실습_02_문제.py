import os
import numpy as np
import pandas as pd

# 데이터 읽기는 오늘 연습할 내용이 아니라서 드립니다. 여기서부터가 여러분 몫입니다.
DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "수업용_데이터")
df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i.csv"), encoding="utf-8-sig")
특징이름 = ["공기온도", "회전수", "토크", "공구마모"]


# =====================================================================
# A. 표 만들고, 시작하자마자 금고에 넣기                        (02 §1, §2)
# =====================================================================
# 만들 것 ① X — 센서 4개를 열로 가진 표(200행 4열). y — 정답인 공정온도 200개.
#            01 에서는 입력이 한 줄이었는데, 이제 행 = 설비 한 대, 열 = 센서 하나인 '표' 입니다.
#
# 만들 것 ② 학습용 / 시험용 나누기 — 70% 를 배우는 데 쓰고, 30% 는 금고에 넣습니다.
#            시험용은 학습이 다 끝난 뒤 채점할 때만 꺼냅니다. 중간에 들여다보면 시험의 의미가 없어집니다.
#            섞을 때 np.random.RandomState(42) 로 만든 순서표를 쓰세요. 번호를 붙여야 매번 같은 결과가 나옵니다.
#            ★ 제일 잦은 사고 ★ X 와 y 를 각각 따로 섞으면 안 됩니다. 같은 순서표로 골라야 짝이 유지됩니다.
#            ※ 이름은 X_train, X_test, y_train, y_test 로 해 주세요.
#
# 나와야 하는 것
#     X (200, 4)   학습용 140대 / 시험용 60대
X = df[특징이름].values.astype(float)
y = df["공정온도"].values.astype(float)

rng = np.random.RandomState(42)
순서 = rng.permutation(len(X))
n_train = int(len(X) * 0.7)
tr, te = (순서[:n_train], 순서[n_train:])
X_train, X_test = X[tr], X[te]
y_train, y_test = y[tr], y[te]

print(f"X {X.shape}     학습용 {len(tr)} / 시험용 {len(te)}")


# =====================================================================
# B. 표준화 — 열마다 따로, 그리고 자는 학습용에서만              (02 §3)
# =====================================================================
# 만들 것  Z_train, Z_test — 열별로 표준화한 표.
#            열마다 크기가 제각각입니다 (온도 300, 회전수 1500, 토크 40, 마모 120).
#            자가 다르면 걸음 하나가 어떤 열엔 너무 크고 어떤 열엔 너무 작아 학습이 망가집니다.
#            열마다 따로 (값 − 그 열 평균) ÷ 그 열 표준편차 를 합니다. 평균/표준편차 계산은 axis=0 입니다.
#
#          ★ 여기가 02 의 핵심입니다 ★
#            평균과 표준편차는 **학습용에서만** 구합니다. 시험용도 그 학습용 자로 변환합니다.
#            시험용 자기 평균을 쓰면 시험용 정보가 학습 쪽으로 새어 들어갑니다(누수). 점수가 부풀려져요.
#            게다가 현장에선 새 데이터가 한 줄씩 들어옵니다. 한 줄로는 평균을 낼 수도 없습니다.
#
# 확인할 것  학습용과 시험용의 열별 평균·퍼짐을 각각 찍어 보세요.
#
# 나와야 하는 것
#     학습용 열별 평균 [0. 0. 0. 0.]  퍼짐 [1. 1. 1. 1.]
#     시험용 열별 평균 [-0.267 -0.08   0.047 -0.122]
#
# ★ 생각할 것 ★ 시험용 평균이 0 이 아닙니다. 이건 잘못된 걸까요?
#   (답 → 시험용은 학습용의 평균과 표준편차를 사용했기 때문에 평균이 반드시 0이 되지는 않음)

mu = X_train.mean(axis=0)
sd = X_train.std(axis=0)

Z_train = (X_train - mu) / sd
Z_test = (X_test - mu) / sd

# 학습용 데이터는 자기 자신의 평균과 표준편차로 표준화했기 때문에 열별 평균이 이론적으로 0이 됨
# 그런데 컴퓨터가 소수점을 계산하는 과정에서 아주 작은 오차가 생길 가능성 있음
# np.abs()를 사용해 음수 부호를 없애고 깔끔하게 출력한 것
print(
    f"학습용 열별 평균 {np.abs(Z_train.mean(axis=0)).round(3)}    퍼짐 {Z_train.std(axis=0).round(3)}"
)

# 여기서 음수와 양수는 의미가 있음!
# 예를 들어 -0.267은 시험용 공기온도의 평균이 학습용 평균보다 낮다는 뜻
# 따라서 시험용 평균에는 np.abs()를 사용하지 않고 양수와 음수 부호를 그대로 보여주는 것
print(f"시험용 열별 평균 {Z_test.mean(axis=0).round(3)}")

