# zip() : 센서 이름과 해당 가중치를 하나씩 짝지음
# abs(t[1]) : 각 짝에서 두 번째 값인 가중치의 절댓값
# -abs(t[1]) : 절댓값이 큰 가중치부터 정렬하기 위한 기준
s_result = sorted(zip(특징이름, w), key=lambda t: -abs(t[1]))

for 이름, wi in s_result:
    print(f"{이름}      {wi:+.3f}")


