# 만들 것 ① sigmoid / 확률 — 직선 끝에 sigmoid 를 붙입니다.
#              sigmoid(z) = 1 / (1 + e^(-z))     e^(-z) 는 np.exp(-z)
#            왜 붙이나? 직선은 -50 도 +300 도 뱉습니다. 그런데 우리가 원하는 건 확률이에요.
