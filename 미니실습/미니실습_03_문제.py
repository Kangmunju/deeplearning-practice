#            둘을 한 식으로 쓰면:  -평균( y·log(p) + (1-y)·log(1-p) )
#            ★ p 가 딱 0 이나 1 이면 log 가 터집니다. np.clip(p, 1e-12, 1-1e-12) 으로 살짝 안으로 밀어 두세요.
#            (다른 이름: 이진 교차 엔트로피 / BCE. 05 파이토치에서 이 이름으로 다시 나옵니다)
