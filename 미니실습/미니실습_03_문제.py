#
# 만들 것 ② 손실 — 제곱(MSE) 대신 로그손실을 씁니다. 규칙은 이것뿐입니다:
#              정답이 고장(1)인데 "고장 확률 0.99" → 벌점 0.01  (거의 안 혼남)
#              정답이 고장(1)인데 "고장 확률 0.5"  → 벌점 0.69
#              정답이 고장(1)인데 "고장 확률 0.01" → 벌점 4.6   (자신 있게 틀리면 크게 혼남)
