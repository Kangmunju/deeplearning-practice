# =====================================================================
# B. 어느 쪽이 내리막인가 — 밟아보기                              (01 §3)
# =====================================================================
# 만들 것  기울기 — 안개 속에서 발로 땅을 톡톡 밟아 보는 것과 같습니다.
#            손잡이 하나를 아주 조금(+h) 키운 자리의 손실과 조금(−h) 줄인 자리의 손실을 재서,
#            그 차이를 둘 사이 거리(2h)로 나눕니다. h 는 0.0001 쯤이면 됩니다.
#            w 를 잴 땐 b 를 그대로 두고, b 를 잴 땐 w 를 그대로 둡니다. 한 번에 하나씩.
#            w 방향과 b 방향, 두 개를 같이 돌려주세요.
#            ※ 미분 공식은 이 수업에서 한 번도 쓰지 않습니다. 밟아 보고 재는 게 전부입니다.
#
# 부호 읽는 법   양수 = 오른쪽이 오르막 → 그 손잡이를 줄여라
#                음수 = 오른쪽이 내리막 → 그 손잡이를 키워라
#
# 확인할 것  w=1.0, b=9.0 자리에서 두 방향 기울기를 찍어 보세요.
#
# 나와야 하는 것
#     w 방향   -580.548    b 방향     -1.934
#
# ★ 생각할 것 ★ 둘 다 음수인데(= 둘 다 키워라) 크기가 300배 차이 납니다.
#   왜 w 쪽만 이렇게 클까요? x 에 들어 있는 숫자가 몇 근처인지 보세요.
#   (답 → 공기온도 x가 약 300이므로 w를 조금만 바꿔도 w*x가 크게 변한다.
#         반면 b는 바꾼 만큼만 예측값이 변하므로 w 방향 기울기가 약 300배 크다.                                                              )
#   이 차이가 바로 다음 [C] 에서 사고를 칩니다.

h = 0.0001


def 기울기(x, y, w, b):
    gw = (손실(x, y, w + h, b) - 손실(x, y, w - h, b)) / (2 * h)
    gb = (손실(x, y, w, b + h) - 손실(x, y, w, b - h)) / (2 * h)
    return gw, gb


gw, gb = 기울기(x, y, 1.0, 9.0)

# print(f"w 방향 {round(gw, 3)}   b 방향 {round(gb, 3)}")
# w 방향 -580.548   b 방향 -1.934


# =====================================================================
# C. 일부러 실패시키기 — 발산                                     (01 §5)
# =====================================================================
# 할 것  w=1.0, b=9.0 에서 출발해 보폭 0.001 로 딱 20걸음만 걸어 보세요.
#          한 걸음 규칙은 한 줄입니다:   새 값 = 지금 값 − 보폭 × 기울기
#          더하기가 아니라 빼기입니다. 기울기가 음수면 빼기가 곧 더하기가 되어 방향이 알아서 맞습니다.
#          w 와 b 둘 다 갱신해야 합니다. 20걸음 뒤 손실을 지수 표기(.4e)로 찍으세요.
#
#          숫자가 폭발하면 numpy 가 경고를 뱉습니다. 아래로 감싸면 경고만 조용해집니다(계산은 그대로):
#              with np.errstate(over="ignore", invalid="ignore"):
#
# 나와야 하는 것
#     손실 = 3.7917e+31          (3.79 뒤에 0 이 31개)
#
# ★ 이건 버그가 아닙니다 ★ 오늘 보여 주려던 장면입니다.
#   골짜기 바닥을 향해 너무 크게 걸으면 반대편 벽으로 튕기고, 거기서 또 크게 걸으면 더 높이 튕깁니다.
#   이걸 '발산' 이라고 합니다. 보폭을 100배 키운 것뿐인데 이렇게 됩니다.

w = 1.0
b = 9.0

with np.errstate(over="ignore", invalid="ignore"):
    for _ in range(20):
        gw, gb = 기울기(x, y, w, b)
        w, b = w - 0.001 * gw, b - 0.001 * gb

# print(f"손실 {round(손실(x, y, w, b), 4)}")
# 손실 3.7917438348264583e+31

# B 파트의 h는 기울기를 계산하기 위해 임시로 값을 바꿔보는 크기(실제 w, b를 변경하지 않음)
# C 파트의 0.001(lr, 보폭)은 계산한 기울기를 이용해 실제 w, b를 변경할 때 사용하는 학습률


# =====================================================================
# D. 눈금을 바꿔서 해결 — 표준화                              (01 §5, §6)
# =====================================================================
# 만들 것 ① z — x 를 표준화한 것.   z = (x − 평균) ÷ 표준편차
#            300 근처의 큰 숫자들이 −3 ~ +3 사이의 얌전한 숫자가 됩니다.
#            정보는 하나도 안 없어집니다. "평균이면 0, 평균보다 한 칸 위면 1" 이라는 새 눈금일 뿐이에요.
#            경사하강 전에는 거의 항상 합니다.
#            ※ 변수 이름은 z, 평균은 m, 표준편차는 s 로 해 주세요 (자체 점검이 이 이름을 씁니다).
#
# 만들 것 ② 학습 — [C] 의 그 한 걸음을 정해진 횟수만큼 반복하는 함수.
#            w=0, b=0 에서 출발합니다. 아무 데서나 출발해도 결국 바닥으로 갑니다.
#            보폭(lr)과 걸음 수(epochs)를 밖에서 정할 수 있게 만드세요. [E] 에서 바꿔 가며 쓸 겁니다.
#
# 할 것 ③  z 로 lr=0.1, 300걸음 학습하세요. 나온 w, b 는 'z 눈금' 위의 직선입니다.
#           현장에서 쓰려면 원래 온도 눈금으로 되돌려야 합니다. 되돌리는 두 줄은 01 §6 에 있습니다.
#           외울 식이 아니니 거기서 가져다 쓰고, 이름은 w_gd, b_gd 로 두세요.
#
# 확인할 것  평균/표준편차, 되돌린 직선, 그 직선의 (원래 눈금에서의) 손실.
#
# 나와야 하는 것
#     평균 300.24  표준편차 1.91
#     공정온도 = 0.9840 x 공기온도 + 14.7799
#     손실 = 0.8921
#
# 우리가 알려 준 건 '틀린 정도를 재는 법' 하나뿐인데 컴퓨터가 직선을 스스로 찾았습니다.
# [A] 에서 감으로 넣은 (1, 10) 이 0.8941 이었죠. 감도 좋았지만, 센서가 10개가 되면 감으론 못 합니다.

m = x.mean()
s = x.std()
z = (x - m) / s


def 학습(z, y, lr=0.1, epochs=300):

    # w : 현재 학습 중인 가중치
    # b : 현재 학습 중인 절편
    w, b = 0.0, 0.0

    for _ in range(epochs):
        # gw : 현재 w에서 손실이 얼마나 변하는지 나타내는 기울기
        # gb : 현재 b에서 손실이 얼마나 변하는지 나타내는 기울기
        gw, gb = 기울기(z, y, w, b)

        w = w - lr * gw
        b = b - lr * gb

    return w, b


# w_z : 표준화한 입력값 z로 학습을 끝낸 가중치
# b_z : 표준화한 입력값 z로 학습을 끝낸 가중치
w_z, b_z = 학습(z, y, lr=0.1, epochs=300)
# 표준화 덕분에 경사하강법이 안정적으로 진행되어, C 파트에서는 찾지 못했던 손실이 작은 직선을 찾은 것

# w_gd : 학습 결과를 원래 공기온도 x에 맞게 변환한 가중치
# b_gd : 학습 결과를 원래 공기온도 x에 맞게 변환한 절편
w_gd = w_z / s
b_gd = b_z - w_z * m / s

# print(f"평균 {round(m, 2)}    표준편차 {round(s, 2)}")
# print(f"공정온도 = {round(w_gd, 4)} x 공기온도 + {round(b_gd, 4)}")
# print(f"손실 = {round(손실(x, y, w_gd, b_gd), 4)}")
# 평균 300.24    표준편차 1.91
# 공정온도 = 0.984 x 공기온도 + 14.7799
# 손실 = 0.8921

# 표준화는 좋은 직선을 찾기 위한 방법이고, 되돌리는 과정은 찾은 직선을 원래 단위로 사용하기 위한 방법


# =====================================================================
# E. 보폭은 얼마가 맞나                                           (01 §7)
# =====================================================================
# 할 것  표준화한 z 로 lr 을 0.001 / 0.1 / 1.05 로 바꿔 가며 300걸음씩 학습하고,
#          손실과 판정을 한 줄씩 찍으세요.
#          판정 규칙:  nan 이거나 1e6 보다 크면 "발산" / 1.0 보다 크면 "굼벵이" / 아니면 "좋음"
#          nan 은 '숫자가 아님(폭발)' 입니다. 크기 비교로는 절대 안 걸러지니 np.isnan 을 먼저 보세요.
#
# 나와야 하는 것
#     lr=0.001  -> 손실     28950.6776   굼벵이
#     lr=0.1    -> 손실         0.8921   좋음
#     lr=1.05   -> 손실   2.289...e+22   발산
#
# ★ 생각할 것 ★ 정답 공식은 없습니다. 이렇게 몇 개 넣어 보고 고르는 겁니다.
#   0.001 은 왜 '틀린 것' 이 아니라 '굼벵이' 일까요? 300 이 아니라 30000 걸음이면 어떻게 될까요?
#   (답 → 표준화는 입력값의 크기를 조정해 학습을 안정적으로 만드는 데 도움을 주지만,
#         적절한 학습률을 자동으로 정해 주지는 않는다.
#         학습률이 너무 작으면 정해진 반복 횟수 안에 손실을 충분히 줄이지 못하고,
#         너무 크면 손실이 작은 지점을 지나쳐 발산할 수 있다.
#         따라서 표준화한 뒤에도 학습률을 적절히 설정해야 한다.)

for lr in [0.001, 0.1, 1.05]:
    w, b = 학습(z, y, lr=lr, epochs=300)
    loss = 손실(z, y, w, b)
    if np.isnan(loss) or loss > 1e6:
        result = "발산"
    elif loss > 1.0:
        result = "굼벵이"
    else:
        result = "좋음"
    print(f"lr={lr}  -> 손실    {round(loss, 4)}    {result}")
# lr=0.001  -> 손실    28950.6776    굼벵이
# lr=0.1  -> 손실    0.8921    좋음
# lr=1.05  -> 손실    2.289457796788011e+22    발산


