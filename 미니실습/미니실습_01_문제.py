# 만들 것 ② 손실 — 200대가 각각 얼마나 틀렸는지를 '점수 하나' 로 요약합니다. 작을수록 좋습니다.
#            틀린 정도는 (실제 − 예측) 입니다.
#            그냥 평균 내면 안 됩니다. −3 틀림과 +3 틀림이 상쇄돼 0 이 되니까요.
#            제곱하면 그 문제가 사라지고, 크게 틀린 것에 더 큰 벌점이 갑니다. (이게 MSE 입니다)
#
# 확인할 것  w=1.0 로 고정하고 b 를 0 / 10 / 11 로 바꿔 가며 손실을 찍어 보세요.
#
# 나와야 하는 것
#     b=0.0   -> 손실   100.2341
#     b=10.0  -> 손실     0.8941
#     b=11.0  -> 손실     1.9601
#   b=10 근처가 바닥이라는 뜻입니다. 아직 컴퓨터가 찾은 게 아니라, 우리가 감으로 넣어 본 겁니다.
