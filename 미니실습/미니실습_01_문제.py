# 만들 것 ① 예측 — 직선 하나로 공정온도를 맞힙니다. 숫자 두 개(w, b)로 결정됩니다.
#            w 는 "공기온도가 1 오를 때 공정온도가 얼마나 오르나", b 는 그냥 더해 주는 값.
