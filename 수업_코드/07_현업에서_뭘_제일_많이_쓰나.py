import os
import warnings
import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")          # 수업 화면을 깨끗하게. 실무에선 경고를 읽으세요
DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "수업용데이터")

from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import make_pipeline
from sklearn.linear_model import LinearRegression, LogisticRegression
from sklearn.tree import DecisionTreeClassifier, DecisionTreeRegressor, export_text
from sklearn.ensemble import (RandomForestClassifier, RandomForestRegressor,
                              HistGradientBoostingClassifier, HistGradientBoostingRegressor)
from sklearn.metrics import recall_score, precision_score, f1_score

df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i.csv"), encoding="utf-8-sig")
특징이름 = ["공기온도", "회전수", "토크", "공구마모"]
X = df[특징이름].values
y_온도 = df["공정온도"].values
y_고장 = df["고장여부"].values


# =====================================================================
# 0. 오늘 새로 꺼내는 도구들 — 미리 한눈에
# =====================================================================
# 04 §0 의 표에 트리 서랍 두 개가 더해집니다. 나머지(train_test_split, StandardScaler,
# make_pipeline, 채점 함수들)는 04 에서 쓰던 그대로예요.
#
#   sklearn.tree       트리 한 그루
#   sklearn.ensemble   트리 여러 그루를 합친 것
#
#  [트리 한 그루]
#   DecisionTreeClassifier(max_depth=2)   종류를 맞히는 트리 (분류)
#   DecisionTreeRegressor(max_depth=3)    숫자를 맞히는 트리 (회귀)
#     max_depth = 질문을 몇 단계까지 할까. ★ 이걸 안 걸면 통째로 외웁니다 (§2) ★
#     class_weight="balanced" = 드문 쪽을 무겁게 세라 (03 에서 배운 불균형 처방)
#   export_text(트리, feature_names=...)  학습된 트리를 사람이 읽는 글로 뽑아 줍니다 (§1)
#
#  [트리 여러 그루 = 앙상블]
#   RandomForestClassifier(n_estimators=200)   트리를 200그루 만들어 투표시킵니다 (분류)
#   RandomForestRegressor(n_estimators=200)    같은 방식으로 숫자 맞히기 (회귀)
#     n_estimators = 몇 그루 만들까. 많을수록 안정적이고 느립니다. 보통 100~500
#   HistGradientBoostingClassifier / Regressor  부스팅. 틀린 것만 다음 트리가 고쳐 나갑니다
#     XGBoost, LightGBM 과 같은 방식인데 사이킷런에 들어 있어 따로 설치가 필요 없습니다
#
#  [트리만 주는 것]
#   모델.feature_importances_   어느 특징이 답을 가르는 데 많이 쓰였나 (§4-1)
#     02 에서 가중치 크기로 읽던 것과 같은 목적인데, 트리는 이렇게 바로 줍니다
#
# 트리 쪽 규칙 두 가지
#   1) 표준화가 필요 없습니다. "얼마보다 큰가" 만 보니까요 (§1-1 에서 확인)
#   2) 만들기 → fit → predict 는 04 의 모델들과 똑같습니다. 바꿔 끼우기만 하면 됩니다


# =====================================================================
# 1. 결정트리 — 스무고개를 코드로 옮긴 것
# =====================================================================
# ★ 용어 ★ 결정트리(Decision Tree) = "이 값이 얼마보다 크면 이쪽, 작으면 저쪽" 을
#           반복해서 답을 좁혀 가는 모델. 스무고개, 또는 병원 문진표와 똑같습니다.
#
# 02 의 선형모델은 이렇게 답했습니다:  공정온도 = 1.79 x 공기온도 + ... + 310
# 트리는 이렇게 답합니다:            공구마모가 211 보다 크면? 그럼 공기온도가 301 보다 작나? -> 고장
#
# 진짜로 글로 뽑아 볼 수 있습니다. 이게 트리의 제일 큰 장점이에요.
트리 = DecisionTreeClassifier(max_depth=2, class_weight="balanced", random_state=0)
트리.fit(X, y_고장)
print("[1] 학습된 트리를 글로 뽑기 (class 1 = 고장)")
print(export_text(트리, feature_names=특징이름))
# 위 규칙을 그대로 읽으면 이렇게 됩니다:
#   "공구마모가 211 을 넘고, 공기온도가 301 이하면 고장 위험"
#   "공구마모가 211 이하라도, 회전수가 1740 을 넘으면 고장 위험"
# 이걸 그대로 현장 반장님께 보여 드릴 수 있습니다. 선형모델의 '가중치 1.79' 보다 훨씬 잘 통해요.
# 현업에서 트리를 좋아하는 첫 번째 이유가 이겁니다. 설명이 됩니다.

# ★ 트리의 두 번째 장점: 표준화가 필요 없다 ★
# 트리는 "값이 얼마보다 큰가" 만 보지, 값의 크기를 더하거나 곱하지 않습니다.
# 그래서 회전수 1500 과 토크 40 이 섞여 있어도 아무 문제가 없어요. 직접 확인합니다.
Xc_tr, Xc_te, yc_tr, yc_te = train_test_split(X, y_고장, test_size=0.3, random_state=3, stratify=y_고장)
숲_생 = RandomForestClassifier(n_estimators=200, random_state=0).fit(Xc_tr, yc_tr)
숲_표준화 = make_pipeline(StandardScaler(), RandomForestClassifier(n_estimators=200, random_state=0)).fit(Xc_tr, yc_tr)
print(f"\n[1-1] 트리는 표준화가 필요 없다")
print(f"    표준화 안 하고  정확도 {숲_생.score(Xc_te, yc_te):.4f}")
print(f"    표준화 하고     정확도 {숲_표준화.score(Xc_te, yc_te):.4f}   <- 똑같음")
# 01 에서 표준화 안 하면 발산했던 거 기억하시죠? 트리는 그런 일이 아예 없습니다.
# 전처리가 줄어드니 편합니다. 이것도 현업에서 트리를 쓰는 이유예요.

