# |
# | 왜 그런가
# |   질문을 계속 늘리면, 마지막엔 설비 한 대마다 방을 하나씩 만들어 줄 수 있습니다.
# |   '공기온도 302.1 이고 회전수 1454 면 -> 313.2'.
# |   이건 배운 게 아니라 명부를 적어 둔 거예요.
# |
# | 02 와 같은 일입니다
# |   02 에서 5대만 주고 학습했을 때 R2 1.0 나왔던 것과 똑같습니다.
# |   다만 트리는 이걸 훨씬 쉽게 해 버립니다. 그래서 더 위험해요.
# |   그래서 트리를 쓸 땐 max_depth 를 거의 항상 겁니다. 이걸 가지치기라고 합니다.
