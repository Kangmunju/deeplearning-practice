#  [회귀 → 분류, 바뀌는 건 딱 세 줄]
#    ① 순전파 마지막 : p = sigmoid(A @ V + c)        ← 확률로 눌러 담기
#    ② 손실          : MSE → BCE = -(1/n)Σ[y·log p + (1-y)·log(1-p)]
#    ③ 역전파 첫 줄  : 2(ŷ-y)/n  →  (p-y)/n         ← 기적의 단순화
#    나머지(dV, dA, dZ, dW, db)는 09 와 글자 하나 안 다릅니다.
#
#  [평가 — 03 의 지표 그대로]
#    정확도 = 맞춘 비율,  혼동행렬 = TP/TN/FP/FN 네 칸
#    재현율 = TP/(TP+FN) 불량을 놓치지 않는 비율   ← 현장에선 대개 이게 제일 중요
#    정밀도 = TP/(TP+FP) 불량이라 한 것 중 진짜 비율
#    ※ "정확도를 믿지 마라"가 아니라 "불균형일 때 정확도를 믿지 마라"
#
#  [손잡이 세 개]
#    lr      : 작으면 느리고(0.01→0.51) 크면 터진다(80→6.12, 발산)
#    은닉수  : 적으면 표현력 부족, 많으면 과적합. 여기선 4개가 최선
#    epochs  : 충분히 돌려야 하지만, 오래 돌릴수록 외우기 시작함
#
#  [★ 오늘의 핵심 — 자기 시험의 함정 ★]
#    은닉수   train정확도   test정확도
#       1       0.875        0.750
#       2       0.875        0.750
#       4       1.000        0.500      <- train 만점이 되는 지점에서 test 가 꺾임
#       8       1.000        0.500
#      32       1.000        0.500
#    → 손잡이는 반드시 '학습에 안 쓴 데이터'로 고른다. 외운 거지 배운 게 아니다.
#      이건 신경망만의 얘기가 아닙니다. 02 에서 train/test 를 나눈 이유고,
#      04 에서 교차검증을 배운 이유고, 실습3 에서 세션 분할이 폭탄이었던 이유입니다.
#
#  [딥러닝 실전에 필요한 조각, 이제 다 모였습니다]
#    ① 순전파   — 지금 가중치로 확률을 낸다
#    ② 역전파   — 틀린 만큼 각 가중치 기울기를 구한다 (출력 오차 p-y 에서 시작)
#    ③ 경사하강 — 그 기울기 방향으로 조금 갱신한다
#    ④ 튜닝     — lr·은닉수·epochs 를 돌려 최고를 찾는다. 단 test 로 감시하면서.
