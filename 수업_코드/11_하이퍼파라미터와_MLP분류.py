import numpy as np


# =====================================================================
# 1. 회귀 → 분류 — 출력에 sigmoid 하나만 씌운다
# =====================================================================
# 09 MLP 의 뼈대(입력 → 은닉 8개(sigmoid) → 출력)는 그대로 씁니다.
# 회귀를 분류로 바꾸는 데 손대는 곳은 정확히 두 군데뿐이에요.
#
#   ① 출력에 sigmoid 를 한 번 더 씌운다
#      회귀 출력은 ŷ = A·V + c 로 끝나 아무 값(2.7, -3 ...)이나 나왔습니다.
#      분류는 '확률'이 필요하니 그 값을 sigmoid 로 0~1 사이로 눌러 담아요.
#        p = sigmoid(A·V + c)      <- p 는 '불량일 확률'
#      그리고 p >= 0.5 면 불량(1), 아니면 양품(0). ★ 용어 ★ 이 0.5 가 '결정경계'입니다.
#
#   ② 손실을 MSE 대신 BCE(로그손실)로 바꾼다
#      회귀는 (예측-정답)² 인 MSE 를 썼죠. 분류는 확률을 다루므로
#      03 로지스틱 회귀에서 본 그 BCE(이진 교차엔트로피)를 씁니다.
#        BCE = -(1/n) Σ [ y·log(p) + (1-y)·log(1-p) ]
#      정답이 1 인데 p 를 0 가까이 예측하면 -log(p) 가 폭발 → 크게 혼납니다.
#
# ★ 03 을 다시 보세요 ★
#   출력에 sigmoid 씌우고 손실을 BCE 로 바꾼다 — 이거, 03 에서 한 그것과 완전히 같습니다.
#   03 의 로지스틱 회귀는 '직선에 sigmoid 를 씌운 것'이었죠.
#   오늘 만드는 건 '은닉층에 sigmoid 를 씌운 것'입니다.
#   즉 ★ 로지스틱 회귀 앞에 은닉층을 하나 붙인 게 MLP 분류기 ★ 예요.

def sigmoid(z):
    """0~1 S자. 은닉층의 '휘는 부품'이자 출력의 '확률 변환기'. 08 부터 쓴 그것"""
    return 1 / (1 + np.exp(-z))


# 온도가 높을수록 대체로 불량이 늘어나는 데이터입니다. 불량=1, 양품=0.
# 완벽히 딱 갈리지 않고 경계(26~34도) 근처가 살짝 겹칩니다.
온도 = np.array([18, 20, 22, 24, 26, 28, 30, 32, 34, 36, 38, 40], dtype=float)
불량 = np.array([ 0,  0,  0,  0,  1,  0,  1,  1,  0,  1,  1,  1], dtype=float)
#                                 └ 고온 쪽에 불량이 몰림. 단 28=양품, 34=양품 처럼 살짝 섞임
#
#   불량?
#    1 |                 ●     ●  ●     ● ● ●     <- 고온 쪽에 불량(1)이 몰림
#      |
#    0 |  ●  ●  ●  ●        ●        ●            <- 저온 쪽은 대체로 양품(0)
#      +------------------------------------→ 온도
#        18 20 22 24 26 28 30 32 34 36 38 40


def 표준화(x):
    """09 §6 과 같은 이유로 필수입니다. 분류라고 다르지 않아요"""
    m, s = x.mean(), x.std()
    return (x - m) / s, m, s


def 순전파(X, W, b, V, c):
    """09 의 순전파에서 마지막 한 줄만 바뀝니다"""
    A = sigmoid(X @ W + b)      # (n×은닉) 은닉층 출력 — 09 와 같음
    p = sigmoid(A @ V + c)      # (n×1) 최종 '불량일 확률' 0~1  <- ★ 여기가 회귀와 다른 점 ★
    return p, A


def BCE손실(p, Y):
    eps = 1e-9                  # ★ 함정 방지 ★ log(0) = -무한대 이라, 아주 작은 값을 더해 둡니다
    return -np.mean(Y * np.log(p + eps) + (1 - Y) * np.log(1 - p + eps))


def 역전파(X, Y, A, p, V):
    """★ 기적의 단순화 ★
       09 의 역전파 체인을 그대로 가져옵니다. 딱 한 곳만 달라져요 — 맨 앞(출력 오차).
         회귀(MSE)  : 출력 오차 = 2(ŷ - y)/n
         분류(BCE)  : 출력 오차 =  (p - y)/n     <- 더 깔끔!
       sigmoid 와 BCE 를 짝지으면 미분이 서로 상쇄돼서 출력 오차가 그냥 '예측확률 - 정답'이 됩니다.
       이 한 줄만 바꾸면 나머지 되짚기(dV, dA, dZ, dW ...)는 09 와 완전히 똑같아요."""
    n = len(X)
    dlogit = (p - Y) / n                         # ← 09 의 2(ŷ-y)/n 자리. 유일한 변경점
    dV = A.T @ dlogit                            # 이하 09 §5 와 글자 하나 안 다름
    dc = dlogit.sum(axis=0, keepdims=True)
    dA = dlogit @ V.T
    dZ = dA * A * (1 - A)                        # sigmoid 도함수 a(1-a)
    dW = X.T @ dZ
    db = dZ.sum(axis=0, keepdims=True)
    return dW, db, dV, dc


def fit(x, y, 은닉수=6, lr=1.0, epochs=2000, 로그=False):
    """09 의 fit 과 판박이입니다. 은닉수·lr·epochs 를 인자로 받게 해 뒀어요 —
       이 세 개가 곧 오늘 돌려 볼 '손잡이'들입니다."""
    z, m, s = 표준화(x)
    X = z.reshape(-1, 1); Y = y.reshape(-1, 1)
    np.random.seed(0)                            # 시드 고정 → 재현성
    W = np.random.randn(1, 은닉수) * 0.5
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5
    c = np.zeros((1, 1))
    for epoch in range(epochs):
        p, A = 순전파(X, W, b, V, c)                    # ① 확률 예측 한 번
        dW, db, dV, dc = 역전파(X, Y, A, p, V)          # ② 기울기 되짚기
        W -= lr * dW; b -= lr * db                     # ③ 갱신
        V -= lr * dV; c -= lr * dc
        if 로그 and epoch % 400 == 0:
            print(f"      epoch {epoch:5d}   BCE손실 {BCE손실(순전파(X,W,b,V,c)[0], Y):.4f}")
    if 로그:
        print(f"      epoch {epochs:5d}   BCE손실 {BCE손실(순전파(X,W,b,V,c)[0], Y):.4f}")
    return (W, b, V, c, m, s)


def 예측확률(x, 모델):
    """회귀의 predict 는 값을 바로 돌려줬죠. 분류는 확률(0~1)을 돌려줍니다"""
    W, b, V, c, m, s = 모델
    z = (np.asarray(x, dtype=float) - m) / s     # 학습 때와 같은 눈금으로 (04 의 그 원칙)
    p, _ = 순전파(z.reshape(-1, 1), W, b, V, c)
    return p.ravel()


def 예측(x, 모델, 경계=0.5):
    """확률 → 0/1 판정. 경계가 0.5 인 건 약속일 뿐, 바꿀 수 있습니다 (03 의 임계값)"""
    return (예측확률(x, 모델) >= 경계).astype(int)


def 정확도(x, y, 모델):
    return np.mean(예측(x, 모델) == y.astype(int))


