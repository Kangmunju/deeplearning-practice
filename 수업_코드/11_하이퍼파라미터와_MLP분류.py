def 혼동행렬(y_true, y_pred):
    """03 에서 배운 그 네 칸. 이름도 뜻도 완전히 같습니다"""
    y_true = y_true.astype(int)
    TP = int(np.sum((y_pred == 1) & (y_true == 1)))    # 불량을 불량이라 함 (정답)
    TN = int(np.sum((y_pred == 0) & (y_true == 0)))    # 양품을 양품이라 함 (정답)
    FP = int(np.sum((y_pred == 1) & (y_true == 0)))    # 양품인데 불량이라 함 (오검)
    FN = int(np.sum((y_pred == 0) & (y_true == 1)))    # 불량인데 양품이라 함 (놓침 — 위험!)
    return TP, TN, FP, FN


