np.random.seed(42)
# ravel() = (10000,1) 세로 표를 (10000,) 한 줄로 펴기
# np.where(조건)[0] = 조건이 참인 '행 번호'들.  idx0 = 정상 행 번호들, idx1 = 고장 행 번호들
