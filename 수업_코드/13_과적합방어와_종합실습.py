# 오늘은 그걸 '막는 도구' 다섯 개를 손에 넣습니다.
#
#   1) 미니배치 — 전체 대신 몇 개씩 (01 경사하강 변형 회수)
#   2) 학습곡선 — train 손실 vs val 손실을 에폭마다 기록
