# =====================================================================
# 5. L2 정규화 — 큰 가중치에 벌점 (04 Ridge 의 신경망 판)
# =====================================================================
# 과적합은 가중치가 커지면서 곡선이 미친 듯이 출렁일 때 생깁니다.
# 그러니 '가중치가 커지는 것 자체에 벌금'을 물리면 됩니다.
#
#   L = 손실 + λ·Σw²          ← 가중치 제곱합에 비례한 벌금
#     λ(람다) = 벌점 세기. 크면 가중치를 더 세게 억누름
#     Σw²     = 모든 가중치를 제곱해 더한 값
#
# 이 벌점을 미분하면 ∂(λΣw²)/∂w = 2λw.
# 즉 갱신할 때 원래 기울기에 '+2λw'를 더하면 끝입니다.
#   w -= lr·(원래기울기 + 2λw)   →  매 스텝 w 를 조금씩 0 쪽으로 끌어당김
# ★ 그래서 이걸 'weight decay(가중치 감쇠)'라고도 부릅니다 ★
#
# fit 안에 이미 dW += 2λW, dV += 2λV 로 넣어 뒀습니다. λ 만 0 에서 키우면 켜집니다.

print("=" * 60)
print("[5] L2 정규화 — 큰 가중치에 벌점   (배치6, 1500에폭)")
print(f"      {'lam':>8} | {'train':>8} | {'val':>8} | {'격차':>9}")
for lam in [0.0, 0.001, 0.002, 0.01]:
    _, tr, va = fit(X_tr, Y_tr, X_val, Y_val, lam=lam, 드롭율=0.0)
    print(f"      {lam:8.3f} | {tr[-1]:8.4f} | {va[-1]:8.4f} | {va[-1]-tr[-1]:9.4f}")


