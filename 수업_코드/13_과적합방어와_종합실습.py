# ── 데이터: 과적합이 '보이게' 하려면 적어야 합니다 ──
# 많으면 모델이 외울 틈이 없거든요. 그래서 36개만 만듭니다.
# 상황: 설비 온도(x)에 따른 미세 품질편차(y).
#       진짜 규칙은 완만한 U자인데 측정에는 늘 잡음이 섞입니다.
#       모델이 이 '잡음까지 외우면' 과적합이에요.
n_data = 36
온도 = np.linspace(0, 10, n_data)                    # 0 부터 10 까지를 36 칸으로 '균등하게' 나눈 숫자들
                                                    #   → [0.0, 0.29, 0.57, ..., 10.0]  (36개)
진짜곡선 = lambda t: 0.05 * (t - 5) ** 2 + 0.3       # ★ 문법 ★ lambda = 한 줄 함수 (00 §0 ④)
                                                    #   t=5 에서 제일 낮고(0.3) 양쪽으로 올라가는 U자 곡선
                                                    #   ** 2 는 '제곱'입니다
잡음 = np.random.randn(n_data) * 0.15                # randn = 평균 0, 대부분 -1~+1 사이인 무작위 숫자 36개
                                                    #   × 0.15 로 크기를 줄여 '살짝 흔들리는 측정 오차'를 흉내
y = 진짜곡선(온도) + 잡음                              # 관측된 품질편차 = 진짜 규칙 + 잡음
                                                    #   ★ 모델은 '진짜곡선'을 모릅니다. 이 y 만 봅니다.

# ── train / val 나누기 ──
# permutation(36) = 0~35 를 무작위 순서로 섞은 번호표. 예: [27, 3, 15, ...]
# 앞 24개 번호 = 학습용(train), 뒤 12개 번호 = 검증용(val)
#   train = 모델이 보고 배우는 문제집
#   val   = 모델이 한 번도 안 본 모의고사. 진짜 실력은 여기서 잽니다
idx = np.random.permutation(n_data)
train_idx, val_idx = idx[:24], idx[24:]             # [:24] = 처음부터 24개 / [24:] = 24번째부터 끝까지
# ★ 표준화 기준은 반드시 train 만으로 ★ val 값을 미리 쓰면 시험문제를 훔쳐보는 셈입니다 (04·11 §7)
# 표준화 = (값 - 평균) / 표준편차. 숫자를 '평균 0, 퍼진 정도 1' 로 맞춰 학습을 안정시킵니다.
m, s = 온도[train_idx].mean(), 온도[train_idx].std()   # m = 평균, s = 표준편차
# reshape(-1, 1): 1줄짜리 숫자 나열을 '세로 한 줄짜리 표'로 바꿉니다.
#   (36,)  →  (36, 1)   = 36행 1열.  행렬곱(@)을 하려면 이 모양이어야 합니다.
#   -1 은 "개수는 알아서 계산해" 라는 뜻
X_all = ((온도 - m) / s).reshape(-1, 1)
Y_all = y.reshape(-1, 1)
X_tr, Y_tr = X_all[train_idx], Y_all[train_idx]     # 번호표로 골라내기 → 24행
X_val, Y_val = X_all[val_idx], Y_all[val_idx]       # → 12행

print("=" * 60)
print("[1] 데이터 준비 — 과적합이 나게 일부러 적게")
print(f"    전체 {n_data}개  ->  학습 {len(X_tr)}개 / 검증 {len(X_val)}개")
print(f"    표준화 X_tr 앞 3개: {np.round(X_tr[:3].ravel(), 3)}")


# ── MLP 부품: 09 에서 만든 것 '그대로' 회수 ──
# 이 A부의 MLP 모양 (입력 1개 → 은닉 24개 → 출력 1개)
#
#     온도 x ──W,b──▶ [은닉 뉴런 24개, sigmoid] ──V,c──▶ 예측 y_hat
#
#   W : 입력→은닉 가중치   모양 (1, 24)
#   b : 은닉 편향          모양 (1, 24)
#   V : 은닉→출력 가중치   모양 (24, 1)
#   c : 출력 편향          모양 (1, 1)
#   '학습' = 이 네 묶음 숫자를 조금씩 고쳐서 예측이 y 에 가까워지게 만드는 것
#
# ★ 문법 ★  @ = 행렬곱.  (24행,1열) @ (1열,24) → (24행,24열)
#           .T = 전치(행과 열을 뒤집기). (24, 1) → (1, 24)
def sigmoid(z):
    # sigmoid(z) = 1 / (1 + e^(-z)) : 아무 숫자나 넣으면 0~1 사이로 눌러 줍니다.
    #   z 가 크면 → 1 에 가까움,  z 가 작으면(음수로 크면) → 0 에 가까움,  z=0 이면 0.5
    # clip: 표준화·랜덤초기화 조합에서 z 가 아주 커지면 exp 가 넘칠 수 있어 ±30 으로 자릅니다.
    # sigmoid 는 그 밖에선 어차피 0/1 이라 결과는 같습니다.
    return 1 / (1 + np.exp(-np.clip(z, -30, 30)))


def 순전파(X, W, b, V, c):
    """입력 X 를 넣어서 예측값을 계산합니다 (앞에서 뒤로 한 번 흘려보내기).
       돌려주는 것 두 개: (예측값, 은닉층 출력 A).  A 는 역전파 때 다시 쓰려고 같이 돌려줍니다."""
    A = sigmoid(X @ W + b)          # 은닉층: 입력에 가중치 곱하고 편향 더한 뒤 sigmoid 로 휘기
    return A @ V + c, A             # 출력층: 은닉 출력들을 가중합. (회귀라서 출력엔 sigmoid 안 씌움)


def 손실(y_hat, Y):
    # MSE(평균제곱오차) = (예측 - 정답)² 의 평균.  작을수록 잘 맞힌 것.
    #   오차를 제곱하는 이유: 음수·양수 오차가 서로 상쇄되지 않게 + 큰 오차를 더 크게 벌주려고
    return np.mean((y_hat - Y) ** 2)


def 역전파(Xb, Yb, A_sig, A_drop, y_hat, V, 마스크):
    """09 의 역전파에 드롭아웃 처리만 얹은 것입니다.
       ★ 드롭아웃을 쓰면 조심할 자리가 둘 있습니다 ★
         ① sigmoid 도함수는 '마스크 씌우기 전'의 A_sig 로 계산해야 합니다.
            a(1-a) 의 a 는 실제 sigmoid 값이지 '0 으로 꺼진 값'이 아니니까요.
         ② A_drop = A_sig × 마스크 를 거슬러 올라갈 때 마스크를 한 번 더 곱해 줍니다 (연쇄법칙).
       드롭아웃을 안 쓰면 마스크=1, A_drop=A_sig 라 09 의 식과 완전히 같습니다.

       ★ 역전파가 하는 일 (한 줄 요약) ★
         "가중치 W, b, V, c 를 각각 조금 키우면 손실이 얼마나 변하나?" 를 계산합니다.
         그 값(기울기, d○○)을 알면 손실이 줄어드는 방향으로 가중치를 고칠 수 있어요.
         이름 규칙: dW = 'W 에 대한 손실의 기울기'. 모양은 W 와 똑같습니다."""
    n = len(Xb)                                # 이번 배치의 샘플 개수
    dy_hat = 2 * (y_hat - Yb) / n              # MSE 를 예측값으로 미분한 것. (오차가 클수록 큼)
    # ── 출력층부터 거꾸로 ──
    dV = A_drop.T @ dy_hat                     # 순전파가 A_drop 을 썼으니 dV 도 A_drop
    dc = dy_hat.sum(axis=0, keepdims=True)     # 편향 기울기 = 오차들을 세로로 다 더한 것
                                               #   axis=0 = '세로 방향(행들)'으로 더하기
                                               #   keepdims=True = 결과를 (1, 열수) 표 모양으로 유지
    # ── 은닉층으로 한 칸 거슬러 올라가기 ──
    dA_sig = (dy_hat @ V.T) * 마스크             # ② 마스크 재곱 (꺼졌던 뉴런은 기울기도 0)
    dZ = dA_sig * A_sig * (1 - A_sig)          # ① a 는 '마스크 없는' A_sig
                                               #   a(1-a) = sigmoid 의 기울기 (09 에서 유도)
    dW = Xb.T @ dZ
    db = dZ.sum(axis=0, keepdims=True)
    return dW, db, dV, dc


def fit(X_tr, Y_tr, X_val, Y_val, 은닉수=24, lr=0.1, epochs=1500,
        배치크기=6, lam=0.0, 드롭율=0.0, seed=0):
    """★ 용어 ★ 에폭 = 전체를 한 바퀴 / 배치 = 한 스텝에 보는 몇 개 / 셔플 = 매 에폭 순서 섞기
       한 에폭의 스텝 수 = 데이터수 ÷ 배치크기.  24 ÷ 6 = 4 스텝.
       lam(L2)과 드롭율(드롭아웃)을 손잡이로 달아 뒀습니다. 0 이면 꺼진 '맨 모델'입니다.

       매개변수 뜻
         은닉수   : 은닉층 뉴런 개수 (클수록 표현력↑, 외우는 능력도↑)
         lr       : 학습률. 한 번에 가중치를 얼마나 크게 고칠지 (보폭)
         epochs   : 전체 데이터를 몇 바퀴 돌지
         배치크기 : 한 걸음에 몇 개씩 보고 고칠지
         lam      : L2 벌점 세기 (§5)
         드롭율   : 학습 때 은닉 뉴런을 몇 % 끌지 (§6)
         seed     : 초기 가중치 무작위 고정용

       돌려주는 것: (학습된 가중치 묶음, 에폭별 train 손실 목록, 에폭별 val 손실 목록)"""
    np.random.seed(seed)
    # ── 가중치 초기화: 처음엔 작은 무작위 숫자로 시작 ──
    #   전부 0 으로 시작하면 24개 뉴런이 모두 똑같이 움직여서 1개 있는 것과 같아집니다.
    #   그래서 W, V 는 무작위(randn × 0.5), 편향 b, c 는 0 으로 시작합니다.
    W = np.random.randn(1, 은닉수) * 0.5
    b = np.zeros((1, 은닉수))                      # zeros((행, 열)) = 0 으로 채운 표
    V = np.random.randn(은닉수, 1) * 0.5
    c = np.zeros((1, 1))
    n = len(X_tr)                                 # 학습 데이터 개수 (24)
    train_기록, val_기록 = [], []                  # 에폭마다 손실을 하나씩 적어 둘 빈 목록
    for epoch in range(epochs):                   # 바깥 반복: 에폭 (전체를 한 바퀴)
        순서 = np.random.permutation(n)                  # 매 에폭 셔플
        for 시작 in range(0, n, 배치크기):                  # 안쪽 반복: 배치 (0, 6, 12, 18 → 4번)
            골라낸 = 순서[시작:시작 + 배치크기]                # 이번 걸음에 쓸 6개의 번호
            Xb, Yb = X_tr[골라낸], Y_tr[골라낸]                # b = batch. 그 6개의 입력·정답
            A_sig = sigmoid(Xb @ W + b)                 # 마스크 없는 순수 활성화
            if 드롭율 > 0:
                # 드롭아웃: 학습 때만, 은닉 출력 일부를 무작위로 0 으로.
                # ÷(1-드롭율) 은 '역스케일링' — 꺼진 몫만큼 키워 평균 출력 크기를 추론 때와 맞춥니다.
                #
                # 한 줄씩 풀면 (드롭율 0.2 예시)
                #   np.random.rand(...)      : A_sig 와 같은 모양으로 0~1 사이 무작위 숫자
                #   (... > 0.2)              : 0.2 보다 크면 True(켬), 작으면 False(끔)  → 약 80% 켜짐
                #   True/False 는 계산할 때 1/0 으로 바뀝니다
                #   / (1 - 0.2) = / 0.8      : 켜진 칸은 1 → 1.25 로 키움, 꺼진 칸은 0 그대로
                #   예) 마스크 = [1.25, 0, 1.25, 1.25, 0, ...]
                # *A_sig.shape 의 * 은 (6, 24) 같은 모양 튜플을 풀어서 rand(6, 24) 로 넘기는 문법
                마스크 = (np.random.rand(*A_sig.shape) > 드롭율) / (1 - 드롭율)
                A_drop = A_sig * 마스크
            else:
                마스크 = 1.0
                A_drop = A_sig
            y_hat = A_drop @ V + c
            dW, db, dV, dc = 역전파(Xb, Yb, A_sig, A_drop, y_hat, V, 마스크)
            # L2 정규화: 손실에 λΣw² 를 더한 효과 = 기울기에 +2λw
            dW += 2 * lam * W
            dV += 2 * lam * V
            # ★ 경사하강 한 걸음 (01 에서 배운 그 식) ★
            #   새 가중치 = 옛 가중치 - 학습률 × 기울기
            #   기울기가 '손실이 커지는 방향'이라, 빼 주면 손실이 줄어드는 쪽으로 갑니다.
            #   W -= x 는 W = W - x 의 줄임말.  ; 은 한 줄에 두 문장을 쓰는 구분자
            W -= lr * dW; b -= lr * db                  # 한 스텝 갱신
            V -= lr * dV; c -= lr * dc
        # 에폭 끝: train·val 손실 기록 (★ 추론이므로 드롭아웃 끔 — 순전파() 에는 마스크가 없습니다)
        #   순전파(...)[0] = 돌려준 두 개 중 첫 번째(예측값)만 쓰겠다는 뜻
        #   .append(x) = 목록 맨 뒤에 x 를 추가
        train_기록.append(손실(순전파(X_tr, W, b, V, c)[0], Y_tr))
        val_기록.append(손실(순전파(X_val, W, b, V, c)[0], Y_val))
    return (W, b, V, c), train_기록, val_기록


