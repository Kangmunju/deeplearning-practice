# ── MLP 부품: 09 에서 만든 것 '그대로' 회수 ──
def sigmoid(z):
    # clip: 표준화·랜덤초기화 조합에서 z 가 아주 커지면 exp 가 넘칠 수 있어 ±30 으로 자릅니다.
    # sigmoid 는 그 밖에선 어차피 0/1 이라 결과는 같습니다.
    return 1 / (1 + np.exp(-np.clip(z, -30, 30)))


def 순전파(X, W, b, V, c):
    A = sigmoid(X @ W + b)
    return A @ V + c, A


def 손실(y_hat, Y):
    return np.mean((y_hat - Y) ** 2)


def 역전파(Xb, Yb, A_sig, A_drop, y_hat, V, 마스크):
    """09 의 역전파에 드롭아웃 처리만 얹은 것입니다.
       ★ 드롭아웃을 쓰면 조심할 자리가 둘 있습니다 ★
         ① sigmoid 도함수는 '마스크 씌우기 전'의 A_sig 로 계산해야 합니다.
            a(1-a) 의 a 는 실제 sigmoid 값이지 '0 으로 꺼진 값'이 아니니까요.
         ② A_drop = A_sig × 마스크 를 거슬러 올라갈 때 마스크를 한 번 더 곱해 줍니다 (연쇄법칙).
       드롭아웃을 안 쓰면 마스크=1, A_drop=A_sig 라 09 의 식과 완전히 같습니다."""
    n = len(Xb)
    dy_hat = 2 * (y_hat - Yb) / n
    dV = A_drop.T @ dy_hat                     # 순전파가 A_drop 을 썼으니 dV 도 A_drop
    dc = dy_hat.sum(axis=0, keepdims=True)
    dA_sig = (dy_hat @ V.T) * 마스크             # ② 마스크 재곱
    dZ = dA_sig * A_sig * (1 - A_sig)          # ① a 는 '마스크 없는' A_sig
    dW = Xb.T @ dZ
    db = dZ.sum(axis=0, keepdims=True)
    return dW, db, dV, dc


def fit(X_tr, Y_tr, X_val, Y_val, 은닉수=24, lr=0.1, epochs=1500,
        배치크기=6, lam=0.0, 드롭율=0.0, seed=0):
    """★ 용어 ★ 에폭 = 전체를 한 바퀴 / 배치 = 한 스텝에 보는 몇 개 / 셔플 = 매 에폭 순서 섞기
       한 에폭의 스텝 수 = 데이터수 ÷ 배치크기.  24 ÷ 6 = 4 스텝.
       lam(L2)과 드롭율(드롭아웃)을 손잡이로 달아 뒀습니다. 0 이면 꺼진 '맨 모델'입니다."""
    np.random.seed(seed)
    W = np.random.randn(1, 은닉수) * 0.5
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5
    c = np.zeros((1, 1))
    n = len(X_tr)
    train_기록, val_기록 = [], []
    for epoch in range(epochs):
        순서 = np.random.permutation(n)                  # 매 에폭 셔플
        for 시작 in range(0, n, 배치크기):                  # 배치크기씩 잘라
            골라낸 = 순서[시작:시작 + 배치크기]
            Xb, Yb = X_tr[골라낸], Y_tr[골라낸]
            A_sig = sigmoid(Xb @ W + b)                 # 마스크 없는 순수 활성화
            if 드롭율 > 0:
                # 드롭아웃: 학습 때만, 은닉 출력 일부를 무작위로 0 으로.
                # ÷(1-드롭율) 은 '역스케일링' — 꺼진 몫만큼 키워 평균 출력 크기를 추론 때와 맞춥니다.
                마스크 = (np.random.rand(*A_sig.shape) > 드롭율) / (1 - 드롭율)
                A_drop = A_sig * 마스크
            else:
                마스크 = 1.0
                A_drop = A_sig
            y_hat = A_drop @ V + c
            dW, db, dV, dc = 역전파(Xb, Yb, A_sig, A_drop, y_hat, V, 마스크)
            # L2 정규화: 손실에 λΣw² 를 더한 효과 = 기울기에 +2λw
            dW += 2 * lam * W
            dV += 2 * lam * V
            W -= lr * dW; b -= lr * db                  # 한 스텝 갱신
            V -= lr * dV; c -= lr * dc
        # 에폭 끝: train·val 손실 기록 (★ 추론이므로 드롭아웃 끔 — 순전파() 에는 마스크가 없습니다)
        train_기록.append(손실(순전파(X_tr, W, b, V, c)[0], Y_tr))
        val_기록.append(손실(순전파(X_val, W, b, V, c)[0], Y_val))
    return (W, b, V, c), train_기록, val_기록


