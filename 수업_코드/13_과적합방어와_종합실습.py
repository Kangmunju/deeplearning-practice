# =====================================================================
# 4. 조기 종료 — val 이 나빠지면 멈춘다
# =====================================================================
# 학습곡선에서 봤듯, val 손실은 어느 지점에서 최저를 찍고 다시 오릅니다.
# 그 최저점 이후는 '과적합만 쌓이는' 구간이에요. 그러니 거기서 멈추면 됩니다.
# ★ 용어 ★ 조기 종료(early stopping). 아주 싸고 효과 좋은 과적합 처방입니다.
#
# 구현 아이디어
#   - 지금까지 본 val 손실 중 '최저값'과 그때의 모델을 기억해 둔다
#   - val 이 최저를 갱신하면 → 기록 갱신 + 그 모델을 저장
#   - val 이 최저보다 나빠진 채로 'patience(참을성) 에폭'이 지나면 → 멈춤
#   - 최종적으로 '멈춘 시점'이 아니라 ★ 저장해 둔 최저 val 모델 ★ 을 쓴다

def fit_조기종료(X_tr, Y_tr, X_val, Y_val, 은닉수=24, lr=0.1,
               epochs=1500, 배치크기=6, patience=50, seed=0):
    np.random.seed(seed)
    W = np.random.randn(1, 은닉수) * 0.5
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * 0.5
    c = np.zeros((1, 1))
    n = len(X_tr)
    # 기록용 변수 네 개
    #   최저val    : 지금까지 본 val 손실 중 최저. float("inf") = 무한대로 시작 → 첫 값이 무조건 갱신
    #   최고모델    : 그 최저였을 때의 가중치 사진 (아직 없으니 None = '비어 있음')
    #   최고에폭    : 그게 몇 번째 에폭이었는지
    #   나빠진횟수  : 최저를 못 깬 에폭이 연속 몇 번인지 (patience 와 비교)
    최저val = float("inf"); 최고모델 = None; 최고에폭 = 0; 나빠진횟수 = 0
    for epoch in range(epochs):
        순서 = np.random.permutation(n)
        for 시작 in range(0, n, 배치크기):
            골라낸 = 순서[시작:시작 + 배치크기]
            Xb, Yb = X_tr[골라낸], Y_tr[골라낸]
            y_hat, A = 순전파(Xb, W, b, V, c)
            dW, db, dV, dc = 역전파(Xb, Yb, A, A, y_hat, V, 1.0)   # 드롭아웃 없음
            W -= lr * dW; b -= lr * db
            V -= lr * dV; c -= lr * dc
        # ★ val 평가와 참을성 카운트는 '에폭이 끝날 때' 한 번씩 ★
        #   배치마다 하면 patience=50 이 50배치가 돼서 텍스트와 코드가 어긋납니다
        현재val = 손실(순전파(X_val, W, b, V, c)[0], Y_val)
        if 현재val < 최저val:                                 # 최저 갱신 → 저장
            최저val = 현재val
            최고모델 = (W.copy(), b.copy(), V.copy(), c.copy())  # ★ .copy() 필수 ★ 안 하면 같은 배열을 가리킵니다
            최고에폭 = epoch + 1
            나빠진횟수 = 0
        else:                                                # 안 좋아짐 → 참을성 소진
            나빠진횟수 += 1
            if 나빠진횟수 >= patience:
                break                                        # break = 반복문을 즉시 빠져나감
    return 최고모델, 최저val, 최고에폭, epoch + 1               # epoch 는 0 부터 세니 +1 해서 '몇 번째'로


모델_es, 최저val, 최고에폭, 실제돈에폭 = fit_조기종료(X_tr, Y_tr, X_val, Y_val)
