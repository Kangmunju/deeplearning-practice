# ── 실전용 MLP: 12 에서 배운 걸 전부 반영 ──
# A부와 달라진 점: 입력 5개 → 은닉 32개(ReLU) → 출력 1개(sigmoid = 고장 확률 0~1)
def 순전파_relu(X, W, b, V, c):
    A = np.maximum(0.0, X @ W + b)          # ReLU (12 C부의 결론): 음수면 0, 양수면 그대로
    return sigmoid(A @ V + c), A            # 출력은 sigmoid (11 — 이진 분류). 0.8 이면 '고장 확률 80%'


def BCE(p, Y):
    # 이진 교차 엔트로피 (11). 정답이 1 인데 p 가 0 에 가까우면 손실이 확 커집니다.
    #   "확신을 갖고 틀리면 크게 혼낸다"
    # e = 1e-9 (0.000000001): log(0) 은 -무한대라 계산이 터지므로 아주 작은 수를 더해 막습니다
    e = 1e-9
    return -np.mean(Y * np.log(p + e) + (1 - Y) * np.log(1 - p + e))


def fit_실전(Xtr, Ytr, Xva, Yva, 은닉수=32, lr=0.1, epochs=60,
           배치크기=64, lam=0.0, 양성가중=1.0, patience=10, seed=0, 로그=False):
    """4단원에서 배운 걸 전부 담은 학습 함수입니다. 어디서 배운 건지 주석으로 달아 뒀어요."""
    np.random.seed(seed)
    n_in = Xtr.shape[1]
    W = np.random.randn(n_in, 은닉수) * np.sqrt(2 / n_in)     # He 초기화        (12 C부)
    b = np.zeros((1, 은닉수))
    V = np.random.randn(은닉수, 1) * np.sqrt(2 / 은닉수)
    c = np.zeros((1, 1))
    n = len(Xtr)
    최저 = float("inf"); 최고 = None; 최고에폭 = 0; 나쁨 = 0
    for ep in range(epochs):
        순서 = np.random.permutation(n)                       # 미니배치 셔플    (13 A부)
        for st in range(0, n, 배치크기):
            g = 순서[st:st + 배치크기]
            Xb, Yb = Xtr[g], Ytr[g]
            A = np.maximum(0.0, Xb @ W + b)                  # ReLU
            p = sigmoid(A @ V + c)
            # ★ 불균형 보정 ★ 고장 샘플의 오차에 가중치를 더 줍니다. 03 의 class_weight 와 같은 발상
            #   np.where(조건, A, B) = 조건이 참인 칸은 A, 거짓인 칸은 B
            #   → 고장(1) 샘플 자리엔 양성가중(예: 10), 정상(0) 자리엔 1.0
            wgt = np.where(Yb == 1, 양성가중, 1.0)
            dlogit = wgt * (p - Yb) / len(Xb)                # (p-y)            (11 · 12)
            dV = A.T @ dlogit; dc = dlogit.sum(axis=0, keepdims=True)
            dZ = (dlogit @ V.T) * (A > 0)                    # ReLU 도함수 = 0 또는 1  (12)
            dW = Xb.T @ dZ; db = dZ.sum(axis=0, keepdims=True)
            dW += 2 * lam * W; dV += 2 * lam * V             # L2               (13 A부)
            W -= lr * dW; b -= lr * db; V -= lr * dV; c -= lr * dc
        va = BCE(순전파_relu(Xva, W, b, V, c)[0], Yva)
        if 로그 and ep % 10 == 0:
            tr = BCE(순전파_relu(Xtr, W, b, V, c)[0], Ytr)
            print(f"      epoch {ep:3d}   train BCE {tr:.4f}   val BCE {va:.4f}")
        if va < 최저:                                          # 조기 종료        (13 A부)
            최저 = va; 최고 = (W.copy(), b.copy(), V.copy(), c.copy()); 최고에폭 = ep + 1; 나쁨 = 0
        else:
            나쁨 += 1
            if 나쁨 >= patience:
                break
    return 최고, 최저, 최고에폭, ep + 1


def 확률(X, 모델):
    # *모델 = (W, b, V, c) 묶음을 풀어서 W, b, V, c 네 칸에 각각 넣어 줍니다
    return 순전파_relu(X, *모델)[0].ravel()


def 평가(Xe, Ye, 모델, 경계=0.5):
    """03 에서 배운 그 네 칸 + 세 지표
       경계=0.5 : 고장 확률이 0.5 이상이면 '고장'이라고 판정"""
    # p = 예측(0/1),  t = 정답(0/1)
    p = (확률(Xe, 모델) >= 경계).astype(int); t = Ye.ravel().astype(int)
    # (p == 1) & (t == 1) → 둘 다 참인 칸만 True. .sum() 하면 True 개수 = 건수
    TP = int(((p == 1) & (t == 1)).sum()); TN = int(((p == 0) & (t == 0)).sum())
    FP = int(((p == 1) & (t == 0)).sum()); FN = int(((p == 0) & (t == 1)).sum())
    acc = (TP + TN) / len(t)
    # 'A if 조건 else 0.0' : 분모가 0 이면 나눗셈 에러가 나니까 그땐 0 으로 처리
    rec = TP / (TP + FN) if TP + FN else 0.0
    pre = TP / (TP + FP) if TP + FP else 0.0
    f1 = 2 * pre * rec / (pre + rec) if pre + rec else 0.0
    return acc, rec, pre, f1, (TP, TN, FP, FN)


