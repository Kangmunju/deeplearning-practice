# 데이터사전 요약 (수업용으로 옮김):
#   설비: P1-CR1-SPM01 = 냉연 1공장 조질압연기(Skin Pass Mill) 1호기. 강판을 마지막으로 살짝 눌러 표면·평탄도를 잡는 설비.
