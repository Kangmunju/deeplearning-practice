import math
import numpy as np


# =====================================================================
# 1. 순전파 — 역전파를 하려면 값이 먼저 있어야 한다
# =====================================================================
# ★ 오늘의 문제 ★
#   01 에서 경사하강은 이거 하나였습니다:  w ← w - lr·(∂L/∂w)
#   기울기 ∂L/∂w 만 있으면 걸어 내려갈 수 있어요. 문제는 '그 기울기를 어떻게 구하나' 입니다.
#
#   직선 하나(ŷ = w·x + b)일 땐 쉬웠습니다. w 가 손실에 미치는 영향이 한 단계였거든요.
#   그런데 은닉층이 끼면 멀어집니다.
#
#     W1 을 흔들면 → z1 이 바뀌고 → (sigmoid 지나) a1 이 바뀌고 → ŷ 가 바뀌고 → L 이 바뀐다
#     W1 ──?──?──?──?──► L        이 '?' 네 개를 어떻게 하나로 잇지?
#
# ★ 용어 ★ 연쇄법칙(chain rule) = 여러 단계로 연결된 영향은, 각 단계의 '지역 기울기'를 곱해서 구한다.
# ★ 용어 ★ 역전파(backpropagation) = 그 연쇄법칙을, 출력 쪽에서 입력 쪽으로 거꾸로 훑으며 구현한 것.
#
#   순전파 (값이 앞으로)   :  x ──► z ──► a ──► ŷ ──► L
#   역전파 (기울기가 뒤로) : ∂L/∂W ◄── ∂L/∂z ◄── ∂L/∂a ◄── ∂L/∂ŷ ◄── L
#                            입력쪽                              출력쪽 ← 여기서 출발!
#
# 오늘 쓸 망입니다. 종이에 그려 놓고 옆에 두세요. 이 파일 내내 여기를 보게 됩니다.
#
#         W1,b1     sigmoid
#   x ───────────► z1 ─────► a1 ┐ V1
#     ───────────► z2 ─────► a2 ┘ V2 → ŷ = V1·a1 + V2·a2 + c → L = (ŷ-y)²
#         W2,b2     sigmoid


def sigmoid(z):
    """08 §2 의 그 활성화 함수 그대로"""
    return 1 / (1 + math.exp(-z))


# 손으로 따라가려면 숫자가 작아야 합니다. 샘플 하나만, 0~1 로 줄여서 씁니다.
# (08 의 온도 30도 / 불량 5 를 눈금만 줄인 값이라고 보시면 됩니다.)
x = 0.30  # 입력 (온도를 0~1 로 줄인 값 하나)
y = 0.50  # 정답 (불량을 0~1 로 줄인 값)

# 초기 가중치도 그냥 손으로 고른 값입니다. 아무 값이나 상관없어요 (§3 에서 확인합니다).
W1, b1 = 0.50, 0.10  # 은닉뉴런1
W2, b2 = -0.40, 0.20  # 은닉뉴런2
V1, V2, c = 0.30, 0.60, 0.10  # 출력층

# ★ 왜 순전파를 먼저 하나 ★
#   역전파의 지역 기울기 식에 a1, a2, x 같은 '값'이 그대로 들어갑니다.
#   그래서 순전파로 z → a → ŷ → L 을 쭉 구해 저장해 둬야 역전파를 할 수 있어요.
#   순서를 바꿀 수 없습니다.
z1 = W1 * x + b1  # 가중합1
z2 = W2 * x + b2  # 가중합2
a1 = sigmoid(z1)  # 가중합1을 활성화함수(시그모이드)에 적용
a2 = sigmoid(z2)  # 가중합2를 활성화함수(시그모이드)에 적용
y_hat = V1 * a1 + V2 * a2 + c
L = (y_hat - y) ** 2  # ★ 용어 ★ 손실 L = (ŷ-y)². 한 샘플 제곱오차 (01·02 의 MSE 한 항)

# 선형회귀에서는 보통 W * x + b가 최종 예측값
# 신경망에서는 z가 첫번째 은닉 뉴런의 중간 계산값
# 여기에 시그모이드를 적용해 a를 만듦
# 두 번째 뉴런에서 만든 또다른 a와 합쳐 최종 예측값 y_hat을 구하는 것

print("=" * 60)
print("[1] 순전파 — 앞으로 흐르며 값부터 계산")
print(f"    z1 = {z1:.6f}   a1 = {a1:.6f}")
print(f"    z2 = {z2:.6f}   a2 = {a2:.6f}")
print(f"    y_hat = {y_hat:.6f}   정답 y = {y}")
print(f"    손실 L = (y_hat - y)^2 = {L:.6f}")

# +-------------------------------------------------------------------------+
# | ^^ 여기까지 치고 실행                                                    |
# +-------------------------------------------------------------------------+
# | [실제 화면]
# |   [1] 순전파 — 앞으로 흐르며 값부터 계산
# |       z1 = 0.250000   a1 = 0.562177
# |       z2 = 0.080000   a2 = 0.519989
# |       y_hat = 0.580647   정답 y = 0.5
# |       손실 L = (y_hat - y)^2 = 0.006504
# |
# | [읽는 법]
