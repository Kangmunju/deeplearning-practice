# 뉴런 수만 바꾸고 나머지 설정은 동일하게 유지하면서 모델을 4번 학습시키는 실험
for 뉴런수 in [2, 4, 8, 16]:
    # 뉴런 수가 바뀌어도 순전파/역전파 함수를 새로 작성할 필요 없음
    # NumPy의 행렬 연산이 달라진 배열 크기에 맞춰 계산함
    m = fit(온도, 불량, 은닉수=뉴런수, lr=0.1, epochs=3000)

    # predict(온도, m) : 방금 학습한 모델의 예측값
    # reshape(-1, 1) : 배열 모양 맞추기
    # 손실() : 실제 불량값과 비교해 손실 계산
    Lm = 손실(predict(온도, m).reshape(-1, 1), 불량.reshape(-1, 1))

    print(f"      {뉴런수:4d}    {Lm:9.4f}")

