# np.polyfit() : 주어진 데이터에 가장 잘 맞는 다항식의 계수를 최소제곱법으로 구해줌
# 그 계수로 만든 모델이 얼마나 데이터를 잘 설명하는지 점수로 매긴 것이 R2
# 08 §1 의 그 최적 직선 (numpy 한 줄판)
기울기, 절편 = np.polyfit(온도, 불량, 1)

