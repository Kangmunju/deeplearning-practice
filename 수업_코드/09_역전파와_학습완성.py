# =====================================================================
# 2. 역전파 — 거꾸로 흐르며 기울기 나눠주기
# =====================================================================
# 순전파 : 입력층에서 출력층으로 계산
# 각 입력값은 각 가중치와 곱해지고 그 가중치의 합들이 계산되어 해당 은닉층 함수의 입력값이 됨

# 역전파 : 순전파로 출력된 값이 출력층에서 다시 입력층 방향으로 계산되며 가중치를 수정
# 인공 신경망의 모든 파라미터들은 역전파를 통해 업데이트됨

# 연쇄법칙 : 각 단계의 기울기를 곱해서 처음 값이 마지막 값에 미치는 영향을 구하는 방법

# 역전파에서 연쇄법칙이 쓰이는 방식
# 출력에서 입력으로 역방향 전달 : 신경망은 순전파로 예측값을 냄 -> 손실(LOSS)을 구함 -> 역방향으로 오차를 보냄
# 직전 노드에서 계산해 둔 미분값(상류에서 넘어온 기울기)에 현재 노드의 미분을 계속 곱해 나가는 방식
# 처음부터 끝까지 전체 식을 다시 미분할 필요 없이 이미 계산된 중간값을 단계별로 재사용하므로 연산 속도 빨라짐

# 연쇄법칙의 뜻을 환율로 비유하면 이렇습니다.
#   원 → 달러 → 유로 → 파운드 로 세 번 갈아탈 때
#   "원이 1 변하면 파운드가 얼마 변하나?" 는 각 환율을 쭉 곱하면 나옵니다.
#   중간 단위(달러·유로)는 곱하는 과정에서 약분되듯 사라지고 처음과 끝만 남죠.
#
#   ∂L      ∂L     ∂ŷ     ∂a1    ∂z1
#   ──── =  ──  ·  ──  ·  ──  ·  ────
#   ∂W1     ∂ŷ     ∂a1    ∂z1    ∂W1
#    ↑      └──────┴──────┴──────┘
#   구하고 싶은 큰 미분        각 마디의 지역 기울기 (작고 쉬운 미분)들
#
# 큰 미분 하나를, 작고 쉬운 미분 여러 개의 곱으로 쪼갠 겁니다.
#
# ★ 아래는 '마디' 하나씩 끊어서 치고 실행하세요 ★
#   씨앗 치고 실행 → 마디1 치고 실행 → 마디2 → 마디3 → 마디4.
#   한 번에 다 치면 '거꾸로 흐른다'는 감각이 안 생깁니다.

print("=" * 60)
print("[2] 역전파 — 거꾸로 흐르며 기울기 나눠주기")

# 손실 L을 줄이기 위해 가중치와 편향 7개를 각각 어느 방향으로 바꿔야 하는지 알아내는 것

# ── 씨앗: 출력 오차 ∂L/∂ŷ ─────────────────────────────────────────────
# L = (ŷ - y)² 를 ŷ 로 미분하면 2(ŷ - y). '예측이 정답보다 얼마나 큰가'의 2배입니다.
# 예측이 정답보다 크면 양수, 작으면 음수. 여기서 출발해 왼쪽으로 퍼뜨립니다.

# dL_dyhat : 예측값 y_hat이 조금 변할 때 손실 L이 얼마나 변하는지 나타내는 기울기
# 제곱오차(L = (ŷ - y)²)를 미분한 결과를 코드로 그대로 작성한 것
dL_dyhat = 2 * (y_hat - y)
print(f"    씨앗   dL/dy_hat = 2(y_hat-y)      = {dL_dyhat:.6f}")

# ── 마디1: 출력 가중치 V1, V2, c ───────────────────────────────────────
# ŷ = V1·a1 + V2·a2 + c 를 각각으로 미분하면 지역 기울기가 a1, a2, 1.
# 여기서 a1, a2는 순전파 때 이미 구한 은닉 뉴런의 출력
# v1이 0.01 증가하면 y_hat은 0.01 * a1만큼 증가
# 따라서 v1이 예측값에 미치는 영향은 a1이라고 할 수 있는 것!

# 우리가 궁금한 것은 v1이 예측값에 미치는 영향이 아님 -> 최종적으로 손실에 미치는 영향을 구하려는 것
# 연쇄법칙 = 씨앗에 그 지역 기울기를 '곱'.
dL_dV1 = dL_dyhat * a1
dL_dV2 = dL_dyhat * a2
dL_dc = dL_dyhat * 1
print(f"    마디1  dL/dV1 = dL/dy_hat x a1     = {dL_dV1:.6f}")
print(f"           dL/dV2 = dL/dy_hat x a2     = {dL_dV2:.6f}")
print(f"           dL/dc  = dL/dy_hat x 1      = {dL_dc:.6f}")

# ── 마디2: 은닉 활성화로 오차 넘기기 ∂L/∂a ─────────────────────────────
# 마디1에서 출력층의 가중치, 편향에 대한 기울기를 구했음
# 이번에는 한 단계 더 거꾸로 가서 은닉 뉴런의 출력인 a1, a2가 손실에 얼마나 영향을 주는지 계산

# ŷ = V1·a1 + ... 이므로 a1 입장에서 지역 기울기는 V1.
# 뜻: "출력 오차를, 그 뉴런이 얼마나 크게 연결됐나(V)에 비례해 되돌려준다"
# a1이 예측값에 미치는 영향(v1) * 예측값이 손실에 미치는 영향(dL_dyhat) = a1이 손실에 미치는 영향(dL_da1)
# 넘어온 기울기에 현재 단계의 지역 기울기를 곱하는 것(마디1과 계산 방식은 동일)
# 다만 마디 1 : v1에 대한 기울기를 구하기 위해 a1을 곱합
#     마디 2 : a1에 대한 기울기를 구하기 위해 v1을 곱함

# 앞에서 구한 씨앗 0.161293
dL_da1 = dL_dyhat * V1
dL_da2 = dL_dyhat * V2
print(f"    마디2  dL/da1 = dL/dy_hat x V1     = {dL_da1:.6f}")
print(f"           dL/da2 = dL/dy_hat x V2     = {dL_da2:.6f}")

# ── 마디3: sigmoid 통과 ∂L/∂z  (08 §5 의 도함수 회수) ──────────────────
# 마디2에서 은닉 뉴런의 출력인 a1, a2에 대한 기울기를 구했음
# 이번에는 한 단계 더 거꾸로 가서 시그모이드를 통과하기 전 값인 z1, z2에 대한 기울기를 구할 것

# 순전파에서는 z1을 시그모이드에 넣어 a1을 만들었음
# 역전파에서는 반대로 a1에 대한 기울기를 z1 쪽으로 전달해야 함

# a = sigmoid(z) 를 지나며 오차를 z 쪽으로 넘깁니다. ∂a/∂z = a·(1-a).
# ★ 08 에서 만들어 둔 그 부품이 여기 쓰입니다. 그때 "09 의 부품"이라고 한 게 이 자리예요.
dL_dz1 = dL_da1 * a1 * (1 - a1)
dL_dz2 = dL_da2 * a2 * (1 - a2)
print(f"    마디3  dL/dz1 = dL/da1 x a1(1-a1)  = {dL_dz1:.6f}")
print(f"           dL/dz2 = dL/da2 x a2(1-a2)  = {dL_dz2:.6f}")

# ── 마디4: 입력 가중치 W1, W2, b1, b2 (드디어 끝) ──────────────────────
# 마디3에서 시그모이드를 거꾸로 통과해 값을 dL_dz의 값을 구했음
# 마지막으로 z1, z2를 만드는 가중치 w1, w2와 편향 b1, b2까지 거슬러 올라갈 것
# w1dl 0.01 증가하면 z1은 0.01 * x만큼 증가
# 따라서 w1이 z1에 미치는 영향(지역 기울기)은 x가 됨
# 반면 b1은 다른 값이 곱해지지 않고 그대로 더해짐 -> 지역 기울기 항상 1

# z = W·x + b 이므로 지역 기울기는 ∂z/∂W = x, ∂z/∂b = 1.
dL_dW1 = dL_dz1 * x
dL_db1 = dL_dz1 * 1
dL_dW2 = dL_dz2 * x
dL_db2 = dL_dz2 * 1
print(f"    마디4  dL/dW1 = dL/dz1 x x         = {dL_dW1:.6f}")
