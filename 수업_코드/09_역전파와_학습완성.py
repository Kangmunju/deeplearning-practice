# 우리가 손으로 만든 게 진짜 신경망이 맞는지, 표준 도구로 대조합니다.
# sklearn 의 MLPRegressor — 은닉 8개, 활성화 sigmoid(logistic). 우리와 같은 구조입니다.
# 값이 완전히 똑같긴 어렵습니다 (초기화·최적화 방식이 달라서). 핵심은 '둘 다 U자를 잡느냐'.

print("=" * 60)
print("[8] sklearn 대조 — 세계 표준 도구도 같은 U자")

# MLPRegressor : sklearn에서 제공하는 회귀용 다층 퍼셉트론(MLP)
#                회귀 모델이므로 불량걊처럼 '숫자'로 된 값을 예측하는 데 사용
try:
    from sklearn.neural_network import MLPRegressor

    # sklearn 에도 표준화 입력
    z = ((온도 - 온도.mean()) / 온도.std()).reshape(-1, 1)

    sk = MLPRegressor(
        hidden_layer_sizes=(8,),  # 은닉층 1개, 그 안의 뉴런 8개
        activation="logistic",  # 은닉층 활성화 함수로 시그모이드 사용
        solver="lbfgs",  # 가중치를 최적화할 때 L-BFGS 방법 사용
        max_iter=5000,  # 최적화의 최대 반복 횟수 설정
        random_state=0,  # 무작위 초기에 사용되는 난수 생태 고정
    )

    # 표준화한 온도 z와 정답인 불량을 전달해 모델을 학습시킴
    sk.fit(z, 불량)

    # 학습된 모델에 z를 입력해 예측값을 구하고 그 결과를 저장
    sk예측 = sk.predict(z)
    print("      온도    실제    우리MLP   sklearn")
    for t, 실, 우, 스 in zip(온도, 불량, 예측, sk예측):
        print(f"      {int(t):4d}    {int(실):2d}    {우:7.2f}   {스:7.2f}")
except ImportError:
    print("    [sklearn 없음 — 건너뜁니다. 위 결과는 정상입니다]")

