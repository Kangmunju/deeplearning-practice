#  [역전파 한 줄 정리]
#    큰 미분(∂L/∂W1) 하나를, 사슬 각 마디의 작은 지역 기울기들의 '곱'으로 쪼갠다.
#    순전파로 값 먼저 → 출력 오차 ∂L/∂ŷ 에서 출발 → 거꾸로 곱하며 앞으로.
#
#  [일곱 기울기 요약 — 이 망 기준]
#    ∂L/∂ŷ  = 2(ŷ - y)                  ← 씨앗
#    ∂L/∂Vj = ∂L/∂ŷ · aj  ,  ∂L/∂c = ∂L/∂ŷ
#    ∂L/∂aj = ∂L/∂ŷ · Vj
#    ∂L/∂zj = ∂L/∂aj · aj(1 - aj)       ← 08 에서 만든 sigmoid 도함수
#    ∂L/∂Wj = ∂L/∂zj · x  ,  ∂L/∂bj = ∂L/∂zj
#
#  [행렬판 — 뉴런이 몇 개든 이 일곱 줄]
#    dŷ = 2(ŷ-Y)/n  /  dV = Aᵀ@dŷ  /  dc = Σdŷ  /  dA = dŷ@Vᵀ
#    dZ = dA ⊙ A(1-A)  /  dW = Xᵀ@dZ  /  db = ΣdZ
#
#  [오늘의 결론 네 줄]
#    1) 역전파는 마법이 아니라 연쇄법칙(곱하기)을 뒤에서 앞으로 돌린 것
#    2) 각 마디에서 하는 일 = '넘어온 값 × 그 마디의 지역 기울기'. 그게 전부
#    3) 수치미분과 대조하면 역전파가 맞는지 눈으로 검산할 수 있다 (gradient check)
#    4) 학습 = 순전파 → 역전파 → 갱신 을 for 로 반복. 01 의 경사하강 그대로
#
#  [오늘의 성취]
#    08 에서 R²=0 이던 U자를, MLP 가 손실 0.0006 으로 맞혔다. 직선보다 14,717배 정확.
#
#  [세 부품으로 줄이면]
#    ① 순전파 — 지금 가중치로 예측한다
#    ② 역전파 — 틀린 만큼 각 가중치의 기울기를 구한다
#    ③ 경사하강 — 그 방향으로 조금 갱신한다
#    이 셋을 for 로 반복한 게 학습이고, 이게 딥러닝의 심장입니다.
#    층을 더 쌓고 뉴런을 더 늘려도 이 세 부품은 그대로예요.
