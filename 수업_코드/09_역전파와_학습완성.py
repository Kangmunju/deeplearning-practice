# 앞에서 역전파를 통해 가중치 w의 기울기를 구했음
# dL_dW는 현재의 W를 아주 조금 증가시키면 손실 L이 얼마나 변할지 나타내는 기울기
# 기울기 검사 : 역전파로 계산한 기울기와 가중치를 실제로 조금 바꿔서 확인한 기울기 비교

# 손으로 짠 역전파가 정말 맞을까요?
# 완전히 다른 방법으로 재서 같은 값이 나오면 '맞다'는 증거입니다.
# 그 다른 방법이 수치미분이에요 (08 §5 에서 활성화 도함수 채점할 때 썼던 그것).
#   ∂L/∂param ≈ ( L(param+h) - L(param-h) ) / (2h)
# 미분 공식을 하나도 안 쓰고 손실을 두 번 계산해 빼기만 합니다. 느리지만 정직해요.


def 손실계산(W1, b1, W2, b2, V1, V2, c):
    """주어진 가중치로 순전파를 다시 돌려 손실 L 만 돌려준다"""
    a1 = sigmoid(W1 * x + b1)
    a2 = sigmoid(W2 * x + b2)
    return (V1 * a1 + V2 * a2 + c - y) ** 2


# 일곱 가중치를 이름:값 으로 묶어 두고, 하나씩만 흔들어 봅니다.
params = {"W1": W1, "b1": b1, "W2": W2, "b2": b2, "V1": V1, "V2": V2, "c": c}


# 가중치 하나를 조금 올린 경우와 조금 내린 경우의 손실을 비교하는 작업
# h : 가중치를 얼마나 조금 바꿀지 정하는 값
def 수치미분(이름, h=1e-5):
    plus = dict(params)
    plus[이름] += h  # ★ 문법 ★ dict(params) = 딕셔너리 복사.
    minus = dict(params)
    minus[이름] -= h  #    이걸 안 하면 원본이 망가집니다

    # w1+h와 w1-h 사이의 거리가 2h이므로 분모는 2h가 됨
    # 가중치를 아주 조금 바꿨을 때 손실이 얼마나 달라지는지를 직접 확인하는 방식
    return (손실계산(**plus) - 손실계산(**minus)) / (2 * h)
    # ★ 문법 ★ **딕셔너리 = 딕셔너리를 키워드 인자로 펼쳐 넣기. 손실계산(W1=..., b1=...) 과 같음
    # 손실계산(**plus)를 풀어쓰면
    # 손실계산(
    # W1=plus["W1"],
    # b1=plus["b1"],
    # W2=plus["W2"],
    # b2=plus["b2"],
    # V1=plus["V1"],
    # V2=plus["V2"],
    # c=plus["c"]
    # )
    # 손실계산(**minus)는 W1을 조금 내렸을 때의 손실을 반환하게 됨
    # 마지막으로 두 손실의 차이를 2*h로 나누면 W1에 대한 수치미분 기울기가 나옴


# params["W1"] : 현재 가중치 W1의 값인 0.50
# 역전파grad["W1"] : W1에 대한 손실의 기울기인 약 0.003573
역전파grad = {
    "W1": dL_dW1,
    "b1": dL_db1,
    "W2": dL_dW2,
    "b2": dL_db2,
    "V1": dL_dV1,
    "V2": dL_dV2,
    "c": dL_dc,
}

print("=" * 60)
print("[3] 킬러 검증 — 역전파 vs 수치미분")
print(f"    {'가중치':6} {'역전파':>12} {'수치미분':>12}   일치?")
모두일치 = True
for 이름 in ["W1", "b1", "W2", "b2", "V1", "V2", "c"]:
    bp, num = 역전파grad[이름], 수치미분(이름)

    # 수치미분은 근삿값이므로 미세한 계산 차이가 생길 수 있어 bp == num으로 비교하지 않음
    # 1e-6dms 0.000001이므로 두 기울기의 차이가 그보다 작으면 True 저장
    일치 = abs(bp - num) < 1e-6
    모두일치 = 모두일치 and 일치
    print(f"    {이름:6} {bp:12.6f} {num:12.6f}   {일치}")
print("    -> 일곱 개 전부 일치?", 모두일치)
