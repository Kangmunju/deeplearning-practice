온도 = np.array([10, 15, 20, 25, 30, 35, 40], dtype=float)
불량 = np.array([9, 5, 2, 1, 2, 5, 9], dtype=float)

# ★ 왜 행렬인가 ★
#   U자처럼 여러 번 휘는 곡선을 그리려면 뉴런이 많아야 합니다 (오늘은 8개).
#   뉴런마다 w1, w2, ... w8 이렇게 따로 쓰면 코드가 지옥이 돼요.
#   02 에서 배운 행렬곱(@)을 쓰면 8개를 한꺼번에 계산하는 게 곱셈 한 줄로 끝납니다.
#
#   온도 x ──┬─→ [은닉1] ─┐
#   (표준화) ├─→ [은닉2] ─┤
#            ├─→   ...    ├─→ (합쳐서) ─→ ŷ 예측
#            └─→ [은닉8] ─┘
#            └── W (1×8) ──┘ └─ V (8×1) ─┘
#
#   순전파가 딱 세 줄이 됩니다. 뉴런이 8개든 800개든 이 세 줄은 안 바뀝니다.
#     Z = X @ W + b      (n×1)·(1×8) → (n×8)   은닉층에 들어가는 값
#     A = sigmoid(Z)                  (n×8)    은닉층 출력 (휘어짐)
#     ŷ = A @ V + c      (n×8)·(8×1) → (n×1)   최종 예측
#
# ★ 아래 함수 여섯 개를 칩니다. 길어 보이지만 새로운 건 하나도 없습니다 ★
#   순전파는 08 에서, 역전파는 방금 §2 에서, 갱신은 §4 에서, 표준화는 02 에서 한 겁니다.
#   다섯 개를 for 로 묶는 게 fit 이에요. 그게 전부입니다.


# np.exp(-z) : e^−z를 계산
#              z에 숫자 하나가 들어오면 숫자 하나에 대해 계산
#              z에 NumPy 배열이 들어오면 배열의 각 원소에 대해 계산
def sigmoid(z):
    """numpy 판. math.exp 와 달리 배열을 통째로 처리합니다"""
    return 1 / (1 + np.exp(-z))


def 순전파(X, W, b, V, c):
    # X : 온도 데이터 n(입력 데이터의 개수)개, 입력 특성 1개 -> 크기 n*1
    # W : 입력 1개에서 은닉층 뉴런 8개로 연결되는 가중치 -> 크기 1*8
    # b : 은닉층 뉴런 8개의 편향 -> 크기 1*8
    # Z : 데이터마다 뉴런 8개가 계산한 값 -> 크기 n * 8
    # 행렬곱 @은 앞 행렬의 열 개수와 뒤 행렬의 행 개수가 같아야 계산할 수 있음
    # 여기서는 두 개수가 모두 1이므로 계산이 가능하고 결과의 크기는 7*8이 됨
    # 그 결과에 b를 더하면 각 데이터에 대해 은닉층 뉴런 8개의 편향이 각각 더해지는 것
    Z = X @ W + b  # (n×1)·(1×8) + (1×8) = (n×8)

    A = sigmoid(Z)  # (n×8) 은닉 출력

    # A : 데이터별 은닉층 뉴런 8개의 출력 -> 크기 7*8
    # V : 은닉층 뉴런 8개에서 출력층으로 연결되는 가중치 -> 크기 8*1
    # c : 출력층 편향 -> 크기 1*1
    # y_hat : 온도 데이터 7개에대한 예측값 -> 크기 7*1
    y_hat = A @ V + c  # (n×8)·(8×1) + (1×1) = (n×1)

    # y_hat은 손실을 계산할 때 필요
    # A는 뒤에서 역전파를 계산할 때 다시 필요
    return y_hat, A


# 예측값 y_hat과 실제 정답 Y를 비교해 평균제곱오차(MSE)를 반환
# 앞에서 온도 데이터가 7개였으므로 예측값도 7개, 실제 정답도 7개
def 손실(y_hat, Y):
    return np.mean((y_hat - Y) ** 2)  # MSE. 01·02 의 그 손실


# X : 입력 데이터(7개)
# Y : 실제 정답
# A : 순전파에서 구한 은닉층 출력
# y_hat : 순전파에서 구한 최종 예측값
# V : 은닉층과 출력층을 연결하는 가중치
# A와 y_hat은 앞에서 만든 순전파()함수가 반환했던 값
def 역전파(X, Y, A, y_hat, V):
    """§2 에서 손으로 구한 그 사슬을, 행렬로 똑같이 쓴 것입니다. 유도는 이미 끝났어요.
    ★ 문법 ★ .T 는 전치(행과 열 뒤집기), @ 는 행렬곱, * 는 같은 자리끼리 곱.
             @ 와 * 를 헷갈리지 마세요. dZ 줄만 * 입니다."""

    # 전체 데이터의 평균 손실에 대한 기울기를 계산할 때 필요
    n = len(X)

    # (n×1)  §2 의 '씨앗'. /n 은 평균이라서
    # y_hat과 Y는 모두 (7*1) 크기의 배열이므로 dy_hat 역시 (7*1) 배열
    dy_hat = 2 * (y_hat - Y) / n

    # (8×1)  §2 마디1
    # A : 데이터 7개에 대한 은닉층 뉴런 8개의 출력 -> 크기 7*8
    # A.T : A의 행과 열을 뒤집은 배열(.T는 전치) -> 크기 8*7
    # dy_hat : 데이터 7개 각각의 예측값에 대한 손실 기울기 -> 크기 7*1
    # dv : 출력층 가중치 8개 각각의 기울기 -> 크기 8*1
    dV = A.T @ dy_hat

    # 출력층 편향 c의 기울기
    # 편향 c는 예측값에 그대로 더해지므로 예측값을 c에 대해 미분한 값 = 1
    # 따라서 데이터 하나에서는 c의 기울기가 dy_hat과 동일 -> 크기 1*1
    # keepdims=True : 합계를 구한 뒤에도 2차원 배열 형태를 유지 -> dc의 크기 1*1
    dc = dy_hat.sum(axis=0, keepdims=True)

    # (n×8)  §2 마디2
    # V : 은닉층 뉴런 8개의 출력층 가중치 -> 크기 8*1
    # V.T : V의 행과 열을 뒤집은 배열
    # V(8*1) 그대로는 dy_hat(7*1)과 행렬곱할 수 없으므로 전치 필요
    # dA : 데이터별 은닉층 뉴런 8개의 기울기 -> 크기 7*8
    dA = dy_hat @ V.T

    # dA를 구해 출력층에서 은닉층의 출력 A까지의 기울기를 전달
    # 그 기울기를 시그모이드 함수의 입력값인 Z까지 전달할 것
    # dZ : 은닉층 출력에 대한 손실 기울기 X 시그모이드의 도함수 -> 크기 (n×8)  §2 마디3
    # 같은 위치에 있는 원소끼리 곱해야 하기 때문에 @이 아니라 *임에 주의!
    dZ = dA * A * (1 - A)

    # 시그모이드 함수를 거슬러 올라가 dZ를 구했음
    # 그 값을 이용해 입력층에서 은닉층으로 연결되는 가중치 W와 편향 b의 기울기를 구할 것
    # X.T : 입력 데이터(7개)의 행과 열을 뒤집은 배열 -> 크기 1*7
    # dZ : 데이터별 은닉 뉴런 8개의 기울기 -> 크기 7*8
    # dW : 은닉층 가중치 8개의 각각의 기울기 -> 크기 (1×8)  §2 마디4
    dW = X.T @ dZ

    # 편향 b는 가중합에 그대로 더해지므로 각 데이터에서 편향에 대한 기울기는 해당 dZ 값과 같음
    # 데이터가 7개 이므로 dZ를 뉴런별로 합쳐야 함
    # keepdims=Trud : 합산한 결과를 1*8 형태의 2차원 배열로 유지
    # db : 은닉층 뉴런 8개 각각의 편향에 대한 기울기 -> 크기 (1×8)
    db = dZ.sum(axis=0, keepdims=True)

    # dW : 입력층 → 은닉층 가중치 (1×8)
    # db : 은닉층 편향 (1×8)
    # dV : 은닉층 → 출력층 가중치 (8×1)
    # dc : 출력층 편향 (1×1)
    return dW, db, dV, dc


def 표준화(x):
    """02·04 에서 배운 그 표준화. z = (x - 평균) / 표준편차"""
    m, s = x.mean(), x.std()

    # (x - m) / s : 표준화된 온도 데이터
    # m : 표준호에 사용한 평균
    # s : 표준화에 사용한 표준편차
    return (x - m) / s, m, s


# x : 입력 데이터인 온도
# y : 정답 데이터인 불량
# 은닉층 뉴런 개수의 기본값 8개(파트 5 시작 부분에서 약속)
# lr=0.1 : 가중치와 편향을 갱신할 때 사용할 학습률
# epochs=3000 : 학습을 반복할 횟수
# 로그=False : 학습 중 손실을 출력할지 결정
# 표준화쓰기=True : 입력 데이터를 표준화할지 결정
def fit(x, y, 은닉수=8, lr=0.1, epochs=3000, 로그=False, 표준화쓰기=True):
    """학습 본체. 하는 일은 01 의 경사하강 루프 그대로입니다.
    1) 가중치 랜덤 초기화  2) epochs 번 반복: 순전파 → 역전파 → 갱신"""

    # 표준화쓰기의 기본값이 True이므로 별도로 바꾸지 않으면 이 부분 실행
    if 표준화쓰기:
        z, m, s = 표준화(x)
    else:
        z, m, s = x, 0.0, 1.0  # §6 함정 시연용

    # .reshape(-1, 정수) : 변환될 배열의 행 수는 알아서 지정
    # (n×1) 세로 표로. 02 에서 한 그 모양 맞추기
    # 데이터를 7*1의 2차원 배열로 바꿔 이후 순전파와 손실 계산에 사용할 모양을 맞추는 것
    X = z.reshape(-1, 1)
    Y = y.reshape(-1, 1)

    np.random.seed(0)  # 시드 고정 → 매번 같은 결과 (04 의 random_state 와 같은 뜻)
    # ★ 왜 랜덤인가 ★ 은닉 뉴런 8개가 서로 다른 곡선을 배우려면 출발점이 서로 달라야 합니다.
    #                 전부 0 으로 시작하면 8개가 똑같이 움직여서 뉴런 1개나 마찬가지가 돼요.

    # np.random.randn() : 평균이 0이고 표준편차가 1인 표준정규분포에서 무작위 실수를 뽑아 배열 생성
    # np.random.randn(1, 은닉수) : 1행 * 은닉수 열 크기의 2차원 가중치 행렬(또는 편향 벡터) 생성
    # W : 은닉층 뉴런 8개가 사용할 서로 다른 초기 가중치
    # 가중치를 랜덤으로 만들되 처음부터 너무 큰 값으로 시작하지 않도록 0.5를 곱해 크기를 줄임
    W = np.random.randn(1, 은닉수) * 0.5

    # np.zeros() : 지정한 모양의 배열을 만들고 모든 원소를 0으로 채움
    # 은닉층 편향 b 8개 모두 0으로 시작
    b = np.zeros((1, 은닉수))

    # V : 은닉층 뉴런 8개에서 나온 출력 각각에 곱할 가중치 만들기
    V = np.random.randn(은닉수, 1) * 0.5

    # 출력층 편향 c 0으로 시작
    c = np.zeros((1, 1))

    for epoch in range(epochs):
        y_hat, A = 순전파(X, W, b, V, c)  # ① 예측 한 번
        dW, db, dV, dc = 역전파(X, Y, A, y_hat, V)  # ② 기울기 되짚기
        W -= lr * dW  # 경사하강법 공식 그대로
        b -= lr * db  # ③ 갱신 (한 스텝)
        V -= lr * dV
        c -= lr * dc
        if 로그 and epoch % 500 == 0:
            print(
                f"      epoch {epoch:5d}   손실 {손실(순전파(X, W, b, V, c)[0], Y):9.4f}"
            )

    if 로그:
        print(
            f"      epoch {epochs:5d}   손실 {손실(순전파(X, W, b, V, c)[0], Y):9.4f}"
        )
    return (W, b, V, c, m, s)  # 학습된 파라미터 묶음 = '학습된 모델'


# fit() : 정답을 보면서 가중치와 편향을 학습하는 함수
# predict() : 이미 학습된 가중치와 편향을 사용해 예측값을 구하는 함수
# 따라서 predict() 안에는 역전파나 가중치 갱신 코드가 없음!
def predict(x, 모델):
    """학습 때 표준화했으니, 예측할 때도 반드시 같은 m, s 로 표준화해서 넣어야 합니다.
    ★ 04 에서 배운 그 원칙입니다 — test 에 train 의 기준을 그대로 적용."""
    W, b, V, c, m, s = 모델

    z = (np.asarray(x, dtype=float) - m) / s

    # 앞에서 순전파()는 y_hat, A 두 값을 반환
    # predict()는 최종 예측값인 y_hat만 필요(학습이 아닌 예측만 하기 때문)
    # _ : 파이썬에서 받기는 하지만 이후에 사용하지 않을 값을 표시할 때 쓰는 변수명
    y_hat, _ = 순전파(z.reshape(-1, 1), W, b, V, c)

    # ★ 문법 ★ .ravel() = 세로 표를 평평한 1차원 배열로
    return y_hat.ravel()


