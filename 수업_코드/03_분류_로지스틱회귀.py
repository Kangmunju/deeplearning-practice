# 4. 확률용 손실 — 맞으면 벌 작게, 확신하고 틀리면 벌 크게
# =====================================================================
# 회귀의 MSE(오차제곱평균)는 확률 문제에는 잘 맞지 않음
# 확률에는 확률용 자를 사용

# 정답이 고장(1)인데 '고장 확률 0.99' -> 벌점 아주 작음(거의 맞힘)
# 정답이 고장(1)인데 '고장 확률 0.01' -> 벌점 아주 큼(확신하고 틀림)
# 정답이 정상(0)이면 반대로

# 이러한 벌점을 만드는 함수가 -log(p)

print("\n[4] 정답이 '고장'일 때, 내가 말한 고장 확률에 따른 벌점")
for p in [0.99, 0.7, 0.5, 0.1, 0.01]:
    # np.log(x) : 'e'를 몇 제곱해야 x가 되는가, p가 0에 가까울수록 폭발하는 벌점 계산기
    print(f"p={p:<5} → 벌점 {-np.log(p):.3f}")
# [4] 정답이 '고장'일 때, 내가 말한 고장 확률에 따른 벌점
# p=0.99  → 벌점 0.010 (거의 0)
# p=0.7   → 벌점 0.357
# p=0.5   → 벌점 0.693 (반반은 중간 벌)
# p=0.1   → 벌점 2.303
# p=0.01  → 벌점 4.605 (자신있게 틀리는 것을 크게 벌함)


def 손실(Z, y, w, b):
    # np.clip(값, 최소, 최대) : 범위 밖이면 잘라냄
    #                         p가 딱 0이면 log(0)이 무한대라 살짝 안으로 들어감
    p = np.clip(확률(Z, w, b), 1e-12, 1 - 1e-12)
    return -np.mean(y * np.log(p) + (1 - y) * np.log(1 - p))

