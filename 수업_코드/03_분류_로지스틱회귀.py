# 01, 02는 '숫자(공정온도)'를 맞혔음 -> 회귀
# 이번에는 '둘 중 하나(고장 1 / 정상 0)'를 맞힐 것 -> 분류

# 바뀌는 것은 두 가지 뿐이고 걷는 방법(경사하강)은 그대로
# 1) 직선 값을 0~1 사이의 '확률'로 ㅏ꿈(sigmoid라는 S자 함수)
# 2) 손실을 '확률용 자'로 바꿈(맞으면 벌 작게, 확신하고 틀리면 벌 크게)

# '정확도는 98%인데 쓸모없는 모델'이 왜 생기는 지 직접 겪어볼 것

import os
import numpy as np
import pandas as pd

DATA = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "수업용_데이터"
)  # data/수업용데이터/
df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i.csv"), encoding="utf-8-sig")


# =====================================================================
# 1. 문제 정의 — 분류란 무엇인가, 그리고 이 데이터의 함정
# =====================================================================
# 분류 = 맞히려는 답이 ;숫자'가 아니라 '종류'인 문제
#       '고장이냐 정상이냐', '양품이냐 불량이냐'
# 종류가 두 가지면 '이진 분류', 세 가지 이상이면 '다중 분류'

# 회귀와 분류의 차이점
# 회귀 : 308.8도 처럼 숫자를 말함
# 분류 : 고장처럼 어느 쪽 인지를 고름
# 현장에서는 '몇 도'인지 보다 '지금 중단해야 하는 상황인가'가 더 자주 필요한 질문

특징이름 = ["공기온도", "회전수", "토크", "공구마모"]
X = df[특징이름].values.astype(float)  # 입력은 02 와 똑같은 센서 4개
y = df["고장여부"].values.astype(
    float
)  # 정답만 바뀜: 고장 1.0 / 정상 0.0 (계산용으로 실수형)

print(
    "[1] 고장 개수:", int(y.sum()), "/ 전체", len(y), f"→ 고장 비율 {y.mean():.1%}"
)  # {:.1%} = 백분율로 소수 1자리
# 불균형 : 한쪽 편이 압도적으로 많은 상태
# 여기서는 고장 4%, 정상 96%
# 고장이 4%뿐이라 '무조건 정상'이라고만 답해도 정확도 96%가 나옴에 주의!
# 그래서 이 파일 끝에서 '정확도 말고 무엇을 보아야 하나'를 배울 것
# 제조 데이터는 거의 다 불균형인 것을 명심!

print(
    "고장 난 설비의 평균 공구마모 :",
    round(df[df.고장여부 == 1]["공구마모"].mean(), 1),
    "/ 정상 설비:",
    round(df[df.고장여부 == 0]["공구마모"].mean(), 1),
)
print(
    "고장 난 설비의 평균 토크 :",
    round(df[df.고장여부 == 1]["토크"].mean(), 1),
    "/ 정상 설비:",
    round(df[df.고장여부 == 0]["토크"].mean(), 1),
)
# [1] 고장 개수: 8 / 전체 200 → 고장 비율 4.0%
#     고장 난 설비의 평균 공구마모: 223.9 / 정상 설비: 112.9
#     고장 난 설비의 평균 토크    : 46.1 / 정상 설비: 40.6

# df[df.고장여부 == 1] : 고장난 행 만. 그 행들의 공구마모 평균.
# 고장 난 설비는 공구마모가 두 배(224 vs 113), 토크도 큼. 이 차이를 모델이 스스로 배우게 만들 것

# =====================================================================
# 2. 나누기 + 표준화 — 02 와 똑같이 (단, 고장이 양쪽에 골고루 들어가게)
# =====================================================================
# 고장이 8대 뿐이라 그냥 무작위로 나누면 시험용에 고장이 0대일 수 있음
# 채점 자체가 되지 않는 상황
# 그래서 고장 설비와 정상 설비를 따로 70대30으로 나눈 뒤 합침 -> 사이킷런에서는 stratify

rng = np.random.RandomState(3)  # 무작위 고정 (02 와 같은 이유)

# np.where(조건)[0] : 조건이 참인 행 번호 목록, 고장 8대 번호를 섞음
고장idx = rng.permutation(np.where(y == 1)[0])

# 정상 192대 번호를 섞음
정상idx = rng.permutation(np.where(y == 0)[0])  # 정상 192대 번호를 섞음

# np.concatenate() : 두 목록을 이어 붙이기
tr = np.concatenate([고장idx[:6], 정상idx[:134]])

# 시험: 고장 2 + 정상 58 = 60
te = np.concatenate([고장idx[6:], 정상idx[134:]])

X_train, X_test, y_train, y_test = (
    X[tr],
    X[te],
    y[tr],
    y[te],
)  # 번호로 행 골라내기 (02 2번)
print(
    "\n[2] 학습용",
    len(tr),
    "대 (고장",
    int(y_train.sum()),
    ") / 시험용",
    len(te),
    "대 (고장",
    int(y_test.sum()),
    ")",
)
# [2] 학습용 140 대 (고장 6 ) / 시험용 60 대 (고장 2 )

mu, sd = X_train.mean(axis=0), X_train.std(axis=0)
Z_train = (X_train - mu) / sd
Z_test = (X_test - mu) / sd

# 표준화는 학습용 통계로만(02의 규칙 그대로)

# 분류에서도 표준화를 하는 이유
# 걷는 방법이 같기 때문에 이유도 동일
# 회전수 1500이 있으면 학습률 하나로 걸을 수 없음


# =====================================================================
# 3. 직선값을 확률로 — sigmoid
# =====================================================================
# 02의 직선값(Z @ w + b)은 -50도 되고 +300도 됨 -> 그러나 고장확률이 300%인 것은 불가능
# 어떤 수든 0~1 사이로 눌러주는 S자 함수를 하나 통과시켜 주어야 함


# np.exp(x) : e의 x제곱(아주 빨리 커지는 함수)
def sigmoid(z):
    return 1 / (1 + np.exp(-z))


print("\n[3] sigmoid 맛보기 — 아무 수나 0~1 로")
for z in [-5, -2, 0, 2, 5]:
    print(f"sigmoid({z:+d}) = {sigmoid(z):.3f}")  # {:+d} = 부호 붙인 정수
# [3] sigmoid 맛보기 — 아무 수나 0~1 로
# sigmoid(-5) = 0.007
# sigmoid(-2) = 0.119
# sigmoid(+0) = 0.500
# sigmoid(+2) = 0.881
# sigmoid(+5) = 0.993

# 음수면 0쪽, 0이면 0.5, 양수면 1쪽
# 아무리 큰 수를 넣어도 1을 넘기지 못하고, 아무리 작아도 0 이하로 내려가지 않음

# sigmoid(시그모이드) : 아무 숫자나 0~1 사이 확률로 눌러주는 S자 함수

# 로지스틱회귀 : 선형모델(직선) + sigmoid
#              이름에 회귀가 들어있지만 '분류'임에 주의!
# 직선으로 점수를 매기고 -> sigmoid로 확률로 변환 -> 임계값이 넘으면 고장
# 선형 모델을 그대로 사용하기 때문에 어느 센서(w)가 고장에 영향을 주는지를 여전히 읽을 수 있음


def 확률(Z, w, b):
    return sigmoid(
        Z @ w + b
    )  # 설비마다 '고장일 확률' 하나씩. 02 의 예측() 에 sigmoid 만 씌운 것


# =====================================================================
# 4. 확률용 손실 — 맞으면 벌 작게, 확신하고 틀리면 벌 크게
# =====================================================================
# 회귀의 MSE(오차제곱평균)는 확률 문제에는 잘 맞지 않음
# 확률에는 확률용 자를 사용

# 정답이 고장(1)인데 '고장 확률 0.99' -> 벌점 아주 작음(거의 맞힘)
# 정답이 고장(1)인데 '고장 확률 0.01' -> 벌점 아주 큼(확신하고 틀림)
# 정답이 정상(0)이면 반대로

# 이러한 벌점을 만드는 함수가 -log(p)

print("\n[4] 정답이 '고장'일 때, 내가 말한 고장 확률에 따른 벌점")
for p in [0.99, 0.7, 0.5, 0.1, 0.01]:
    # np.log(x) : 'e'를 몇 제곱해야 x가 되는가, p가 0에 가까울수록 폭발하는 벌점 계산기
    print(f"p={p:<5} → 벌점 {-np.log(p):.3f}")
# [4] 정답이 '고장'일 때, 내가 말한 고장 확률에 따른 벌점
# p=0.99  → 벌점 0.010 (거의 0)
# p=0.7   → 벌점 0.357
# p=0.5   → 벌점 0.693 (반반은 중간 벌)
# p=0.1   → 벌점 2.303
# p=0.01  → 벌점 4.605 (자신있게 틀리는 것을 크게 벌함)


def 손실(Z, y, w, b):
    # np.clip(값, 최소, 최대) : 범위 밖이면 잘라냄
    #                         p가 딱 0이면 log(0)이 무한대라 살짝 안으로 들어감
    # 정답 y가 1이면 (1-y)=0이기 때문에 뒷 항이 사라져 -log(p)만 남음
    # 정답 y가 0이면 y=0이기 때문에 앞 항이 사라져 -log(1-p)만 남음 -> 위 표 그대로
    p = np.clip(확률(Z, w, b), 1e-12, 1 - 1e-12)
    return -np.mean(y * np.log(p) + (1 - y) * np.log(1 - p))


# 로그 손실(log loss) : 위 벌점을 설비 전체에 대해 평균 낸 것(분류용 손실함수)
# 파이토치에서는 이진 교차 엔트로피라고 부름


# =====================================================================
# 5. 학습 — 경사하강 그대로 (01·02 와 한 글자도 안 다름)
# =====================================================================
# 손실 함수만 바뀌었지 살짝 밟아보고 내리막으로 한 걸음은 동일
# 함수 이름까지 그대로
# 01에서 '선형회귀엔 공식이 있다'고 했는데 로지스틱 회귀는 공식이 없음
# 걷는 것만이 유일한 방법이기 때문에 경사하강을 손으로 배운 것

h = 0.0001


def 기울기_밟아보기(Z, y, w, b):  # 02 4번와 동일 (편미분 5번 = 그래디언트)
    gw = np.zeros(len(w))
    for j in range(len(w)):
        w1, w2 = w.copy(), w.copy()
        w1[j] += h
        w2[j] -= h
        gw[j] = (손실(Z, y, w1, b) - 손실(Z, y, w2, b)) / (2 * h)
    gb = (손실(Z, y, w, b + h) - 손실(Z, y, w, b - h)) / (2 * h)
    return gw, gb


def 학습(Z, y, lr=0.5, epochs=2000, 보여주기=True):
    w = np.zeros(Z.shape[1])
    b = 0.0
    for epoch in range(epochs):
        gw, gb = 기울기_밟아보기(Z, y, w, b)
        w = w - lr * gw
        b = b - lr * gb
        if (
            보여주기 and epoch % 400 == 0
        ):  # 400 바퀴마다 손실 출력. % = 나머지, 400 으로 나눠 떨어질 때만
            print(f"epoch {epoch:4d} 손실 {손실(Z, y, w, b):.4f}")
    return w, b


# [5] 학습 (손실이 줄어드는 걸 보세요)
# epoch    0 손실 0.5933
# epoch  400 손실 0.1180
# epoch  800 손실 0.1161
# epoch 1200 손실 0.1158
# epoch 1600 손실 0.1157


# 로그 손실은 MSE보다 언덕이 완만해서 보폭을 키우고 오래 걸어야 바닥에 닿을 수 있음
# lr을 0.1로 두면 2000바퀴로 부족, 5.0으로 올리면 해결

print("\n[5] 학습 (손실이 줄어드는 걸 보세요)")
w, b = 학습(Z_train, y_train)
print("표준화 눈금 가중치:")
for 이름, wi in sorted(zip(특징이름, w), key=lambda t: -abs(t[1])):
    print(
        f"{이름:6s} {wi:+.3f} {'클수록 고장 확률 ↑' if wi > 0 else '클수록 고장 확률 ↓'}"
    )
# 표준화 눈금 가중치:
# 공구마모   +2.367 클수록 고장 확률 ↑
# 회전수    +0.566 클수록 고장 확률 ↑
# 공기온도   -0.427 클수록 고장 확률 ↓
# 토크     +0.239 클수록 고장 확률 ↑

# 공구마모가 압도적(+2.4) -> 마모가 심할수록 고장
# 위에서 본 관찰(224vs 113)과 같음

# 나머지 셋은 학습용에 고장이 6대 뿐이라 값이 흔들림
# 데이터가 적은 상황에서는 가중치 해석에 주의!


# =====================================================================
# 6. 확률 → 판정, 그리고 채점
# =====================================================================
# 모델이 내놓는 건 '확률'
# 그러나 현장에서는 확률보다는 상황에 대한 판단이 필요
# 선을 하나 그어 잘라내야 함

# 임계값 : 확률을 고장/정상으로 자르는 선 -> 일단 상식대로 0.5로 시작
# 판정 : 확률에 임계값을 적용해 낸 최종 답 -> 0 또는 1

p_test = 확률(Z_test, w, b)  # 시험용 60대의 고장 확률
판정 = (p_test >= 0.5).astype(int)

print("\n[6] 시험용 60대 중 확률이 높은 순 8대")
# np.argsor() : 작은 순으로 정렬했을 때의 번호 앞에 -를 붙여 큰 순
순위 = np.argsort(-p_test)

print("고장확률 / 판정 / 실제")
for i in 순위[:8]:
    print(f"{p_test[i]:.3f} / {판정[i]} / {int(y_test[i])}")
# 고장확률 / 판정 / 실제
# 0.528 / 1 / 1
# 0.485 / 0 / 0
# 0.365 / 0 / 0
# 0.249 / 0 / 0
# 0.232 / 0 / 1
# 0.216 / 0 / 0
# 0.209 / 0 / 0
# 0.145 / 0 / 0

# 1등 (0.528)은 진짜 고장임을 캐치
# 5등 (0.232) 또한 진짜 고장인데 0.5 아래라 정상 판정이 됨 -> 답을 놓침

# 정확도 : 판정이 실제와 같은 비율 (맞힌 대수 / 전체 대수)
정확도 = np.mean(
    판정 == y_test
)  # 판정 == y_test 는 True/False 60개, 그 평균 = True 의 비율
print(f"\n정확도: {정확도:.3f}")
# 정확도: 0.983

# 함정이 재등장
# 98.3%는 그냥 보면 높아보이지만 실제 고장 중 단 1대만을 잡은 것 -> 절반이나 놓침


# =====================================================================
# 7. 정확도의 함정 — 네 칸으로 나눠 봐야 보인다
# =====================================================================
# 정확도는 몇 개 맞혔나 하나만 셈
# 어떻게 틀렸냐는 보지 않음
# 따라서 4칸으로 쪼갬

# 혼동행렬 : 맞고 틀림을 '어떻게' 틀렸는지까지 4칸으로 센 표
# TP : 고장을 고장이라고 함 -> 잘 잡음
# FN : 고장을 정상이라고 함 -> 놓침 -> 제조에서 가장 위험(ex. 설비 멈춤, 리콜 등)
# FP : 정상을 고장이라고 함 -> 허위 경보 -> 재검사 필요
# TN : 정상을 정상이라고함 -> 잘 통과


def 네칸(y, 판정):
    TP = int(((y == 1) & (판정 == 1)).sum())
    FN = int(((y == 1) & (판정 == 0)).sum())
    FP = int(((y == 0) & (판정 == 1)).sum())
    TN = int(((y == 0) & (판정 == 0)).sum())  # .sum() 으로 True 개수 세기
    return TP, FN, FP, TN


TP, FN, FP, TN = 네칸(y_test, 판정)
print("\n[7] 혼동행렬 (임계값 0.5)")
print(f"    고장 {int(y_test.sum())}대 중  잡음(TP) {TP}  놓침(FN) {FN}")
print(f"    정상 {int((y_test == 0).sum())}대 중 통과(TN) {TN}  헛경보(FP) {FP}")
# [7] 혼동행렬 (임계값 0.5)
#     고장 2대 중  잡음(TP) 1  놓침(FN) 1
#     정상 58대 중 통과(TN) 58  헛경보(FP) 0

# 재현율 : 실제 고장 중 잡아낸 비율
#         TP / (TP+FN)
