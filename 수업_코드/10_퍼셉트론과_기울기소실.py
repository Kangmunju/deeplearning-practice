# 8. ReLU 가 해결 — 곱해도 1 은 안 줄어든다  (+ 실습)
# =====================================================================
# 범인은 'sigmoid 의 지역 기울기가 항상 1 보다 작다'였습니다.
# 그럼 지역 기울기가 1 인 활성화를 쓰면? 곱해도 안 줄어들죠. 그게 ReLU 입니다.
#   relu(z)  = max(0, z)
#   relu'(z) = 1 (z>0), 0 (z<=0)
# 양수 쪽 도함수가 딱 1 이에요. 1 은 아무리 곱해도 1 입니다.

def relu(z):
    return max(0.0, z)


def relu도함수(z):
    return 1.0 if z > 0 else 0.0


def 앞층기울기(활성화도함수, 층수=10):
    """값 하나를 층수만큼 통과(순전파)시키고, 역전파로 1층까지 기울기를 곱해 옴"""
    a = 0.7
    z목록 = []
    for _ in range(층수):
        z = 1.0 * a + 0.0
        z목록.append(z)
        # 순전파 활성화는 도함수와 짝을 맞춰 갈아 끼웁니다
        a = sigmoid(z) if 활성화도함수 is sigmoid도함수 else relu(z)
    grad = 1.0
    for 층 in range(층수 - 1, -1, -1):                 # 뒤 → 앞
        grad = grad * 1.0 * 활성화도함수(z목록[층])      # W(=1) · 활성화'
    return grad


