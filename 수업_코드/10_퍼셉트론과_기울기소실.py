# 2. 학습 규칙 — 틀리면 정답 쪽으로 민다
# =====================================================================
# 학습이란 결국 '틀린 만큼 고치기'입니다. 퍼셉트론의 규칙은 놀랄 만큼 단순해요.
#   예측이 맞았으면 → 아무것도 안 한다
#   예측이 틀렸으면 → 가중치를 정답 쪽으로 조금 민다
#
#   w ← w + lr · (정답 - 예측) · x
#   b ← b + lr · (정답 - 예측)
#
# 오차(정답 - 예측)가 이 규칙의 핵심입니다. 셋 중 하나예요.
#   정답 1, 예측 0 → 오차 +1 → w 를 x 쪽으로 키운다 (z 를 올려 1 이 나오게)
#   정답 0, 예측 1 → 오차 -1 → w 를 x 쪽으로 줄인다 (z 를 내려 0 이 나오게)
#   정답 = 예측    → 오차  0 → 아무 변화 없음 (곱하면 0 이라 그대로)
# 방향(+1/-1)과 크기(입력 x)를 오차 하나가 동시에 정해 줍니다.

def 학습(X, Y, lr=0.1, 에폭=20, seed=0):
    """★ 용어 ★ 에폭(epoch) = 전체 데이터를 한 바퀴 도는 것. 09 에서 쓴 그 말입니다."""
    random.seed(seed)                                       # 시드 고정 → 매번 같은 결과
    w = [random.uniform(-1, 1), random.uniform(-1, 1)]      # 가중치 무작위 시작
    b = random.uniform(-1, 1)                               # 편향도 무작위 시작
    for _ in range(에폭):                                    # ★ 문법 ★ _ = 안 쓰는 변수 (00 §0)
        for x, 정답 in zip(X, Y):
            오차 = 정답 - 예측(x, w, b)                       # +1, -1, 또는 0
            w[0] += lr * 오차 * x[0]                         # 틀린 만큼, x 쪽으로 민다
            w[1] += lr * 오차 * x[1]
            b += lr * 오차                                   # 편향은 입력 없이 오차만큼
    return w, b


def 채점(X, Y, w, b):
    """학습된 w, b 로 네 입력을 다 맞히는지 세어 준다"""
    예측들 = [예측(x, w, b) for x in X]
    return 예측들, sum(p == t for p, t in zip(예측들, Y))
    # ★ 문법 ★ sum(True/False 목록) = True 개수. 파이썬에서 True 는 1, False 는 0 입니다


# ★ 용어 ★ 논리 게이트 = 퍼셉트론의 실력을 재는 고전 시험지.
#          입력 두 개(각각 0 또는 1)를 받아 정해진 규칙대로 0/1 을 냅니다.
입력 = [[0, 0], [0, 1], [1, 0], [1, 1]]     # 네 가지 입력 조합
AND = [0, 0, 0, 1]      # 둘 다 1 일 때만 1  (그리고)
OR = [0, 1, 1, 1]       # 하나라도 1 이면 1  (또는)
XOR = [0, 1, 1, 0]      # 서로 다를 때만 1   (같으면 0, 다르면 1)


def 게이트학습(이름, 정답들):
    w, b = 학습(입력, 정답들)
    예측들, 맞은 = 채점(입력, 정답들, w, b)
    print(f"[2] {이름} 게이트 학습 결과")
    print(f"    학습된 w = {[round(v,4) for v in w]}   b = {round(b,4)}")
    for x, 정답, p in zip(입력, 정답들, 예측들):
        표시 = "O" if p == 정답 else "X 틀림"
        print(f"      입력 {x} -> 예측 {p} (정답 {정답})  {표시}")
    print(f"    맞은 개수: {맞은}/4")
    return 맞은


