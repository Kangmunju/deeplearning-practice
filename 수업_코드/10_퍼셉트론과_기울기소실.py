# =====================================================================
# ★ 용어 ★ 퍼셉트론(perceptron) = 1958년에 나온, 뉴런 딱 하나짜리 기계.
#          신경망의 가장 단순한 조상입니다.
#
# 입력 몇 개를 받아 0 또는 1, 딱 한 가지를 답합니다. 하는 일은 두 단계뿐이에요.
#   ① 가중합    : z = w1·x1 + w2·x2 + b
#   ② 계단 활성화: z 가 0 이상이면 1, 아니면 0
#
#      w1
#   x1 ●────╲
#             ╲
#              ●──  z = w1·x1 + w2·x2 + b ──[ 계단 ]── 0 또는 1
#             ╱        (가중합)                (활성화)
#   x2 ●────╱
#      w2
#              ↑ b (편향, 입력 없이 늘 더해지는 값)
#
# ★ 08 과 비교하세요 ★
#   1단계 가중합은 08 의 뉴런과 완전히 똑같습니다 (z = W·x + b).
#   다른 건 2단계 활성화뿐이에요.
#     08 의 뉴런 : sigmoid — S자로 부드럽게 0~1
#     퍼셉트론    : 계단   — 0 아니면 1, 중간이 없음

def 계단(z):
    """계단 활성화. 문턱(0)을 넘으면 1, 못 넘으면 0. S자가 아니라 딱 끊김."""
    return 1 if z >= 0 else 0


def 예측(x, w, b):
    z = w[0] * x[0] + w[1] * x[1] + b      # ① 가중합
    return 계단(z)                          # ② 계단 활성화


