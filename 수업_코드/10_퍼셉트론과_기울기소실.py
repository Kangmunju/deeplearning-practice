#  [전반부 · 퍼셉트론]
#    퍼셉트론 = 뉴런 하나 = 가중합 + 계단 활성화로 0/1 을 답하는 기계
#      예측 : z = w1·x1 + w2·x2 + b,  출력 = 1 (z≥0) / 0 (z<0)
#      학습 : w ← w + lr·(정답-예측)·x,  b ← b + lr·(정답-예측)   ← 틀린 만큼 민다
#    직선 하나로 갈리는 문제(AND·OR·NAND)는 스스로 학습해 4/4
#    직선으로 못 가르는 XOR 은 2/4 — 4/4 는 어떤 직선으로도 원리상 불가능
#    → 08 의 'U자를 못 그리는 직선'과 같은 벽. 회귀판과 분류판일 뿐
#
#  [후반부 · 기울기 소실]
#    역전파는 층마다 지역 기울기(W·σ')를 곱해 뒤→앞으로 간다
#    sigmoid 의 σ' = a(1-a) ≤ 0.25  (등호는 z=0, a=0.5 일 때만)
#    1 보다 작은 수를 층 수만큼 곱하면 앞층 기울기가 0 으로 사라진다
#      0.25^5 ≈ 0.001,  0.25^10 ≈ 0.0000009,  20층 sigmoid ≈ 1e-13
#      실측 10층: 뒤층 0.2247 / 앞층 0.0000003 = 696,553 분의 1
#    처방: ReLU (relu'=1 이라 곱해도 안 줄어듦) → 10층이든 20층이든 앞층 기울기 1.0
#          그밖에 Xavier·He 초기화, 배치정규화, 잔차연결
#
#  [오늘의 대칭 — 이 두 줄이 오늘의 전부입니다]
#    층을 안 쌓으면  → XOR 도 못 푼다          (전반부)
#    층을 쌓기만 하면 → 앞층이 학습을 못 한다    (후반부)
#    → 층을 쌓되, 기울기가 살아 앞층까지 가게 만들어야 한다
#
#    이 두 벽 사이에 신경망의 역사 40년이 들어 있습니다.
#    1969년 XOR 로 한 번 얼어붙었고, 층을 쌓아 풀었는데,
#    그 층을 깊게 못 쌓아서 2000년대까지 또 묶여 있었어요.
#    ReLU 같은 단순한 처방들이 나오면서 비로소 '딥'러닝이 됐습니다.
