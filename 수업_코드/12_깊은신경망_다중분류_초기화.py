#  [A부 · 깊은 신경망]
#    층 = [[W0,b0], [W1,b1], ...] 리스트로 두면 은닉층이 몇 개든 코드가 그대로
#    순전파 : A0=X, 각 층 Z = A@W+b, A = 활성화(Z). 마지막 층만 선형
#    역전파 : delta = 2(ŷ-y)/n 에서 출발
#             dW = A_입력ᵀ @ delta,  db = Σ delta
#             delta ← (delta @ Wᵀ) ⊙ σ'(a)        ← 한 층 앞으로
#    은닉2층 전체가 수치미분과 1e-10 수준으로 일치 → 일반화가 옳다는 증거
