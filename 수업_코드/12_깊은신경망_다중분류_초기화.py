# 11 에서 우리 MLP 는 '양품이냐 불량이냐'를 갈랐습니다. 둘 중 하나, 이진 분류였죠.
# 그런데 현장 판정이 늘 둘로만 갈리지는 않습니다.
# "이 제품, 양품이야? 경미 불량이야? 심각 불량이야?" — 이게 다중분류입니다.
#
# 오늘 손에 넣을 부품 셋, 그리고 놀라운 결말 하나.
#   1) softmax      : 여러 점수를 '합이 1인 확률분포'로 (sigmoid 의 여러 개 버전)
#   2) 원-핫        : 정답 '2' 를 [0,0,1] 처럼 클래스 수만큼의 자리로 편다
#   3) 교차엔트로피 : 다중분류의 손실 (BCE 의 여러 개 버전)
#   4) ★놀라운 결말★ 출력 기울기 = p - y. 11 의 그것 그대로!
#
# 즉 11 에서 배운 게 하나도 안 버려집니다. 전부 '여러 개로 편' 것뿐이에요.
#
#   입력          은닉(sigmoid)        출력 K개 → softmax
#   온도·압력 → ○ ○ ○ ○ ○ ○ → [점수0 점수1 점수2] → [p0 p1 p2] 합=1
#                                                     ↑ 가장 큰 자리가 예측

def softmax(Z):
    """p_k = e^(z_k) / Σ_j e^(z_j)
       ★ 첫 줄이 안전장치입니다 ★ 각 행의 최댓값을 빼도 결과는 같습니다 (분자·분모에서 상쇄).
       안 빼면 e^(큰 점수) 가 무한대로 터져요. 실무 코드에 반드시 들어가는 한 줄입니다."""
    Z = Z - Z.max(axis=1, keepdims=True)
    exp = np.exp(Z)
    return exp / exp.sum(axis=1, keepdims=True)


