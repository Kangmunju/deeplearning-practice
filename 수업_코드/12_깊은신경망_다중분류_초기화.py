#  [B부 · 다중분류 — 이진에서 배운 게 전부 '여러 개'로 늘었을 뿐]
#    출력 뉴런    1개        →  K개
#    마지막 변환  sigmoid    →  softmax  (p_k = e^z_k / Σe^z_j, 합=1)
#    정답 표현    0 또는 1   →  원-핫 [0,1,0]
#    손실        BCE        →  교차엔트로피 L = -Σ y·log p
#    출력 기울기  p - y      →  p - y     ★ 똑같음. 역전파 뒷부분 손댈 게 없다 ★
