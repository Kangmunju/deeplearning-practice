# =====================================================================
# 4. 예측과 학습 — 01 과 똑같고, w 가 숫자 하나에서 '숫자 4개'가 될 뿐
# =====================================================================
# 설비 한 대의 예측 = w1xz1 +w2xz2 + w3xz3 + w4xz4 + b
# 센서 값에 가중치를 곱해서 전부 더하기
# @(행렬곱) : '각 행에 대해 곱해서 더하기'를 한꺼번에 (140행 X 4열 -> 140개)
# for문으로 140번 반복해도 같은 답이 나오지만 행렬곱을 사용하는 것이 훨씬 빠름


def 예측(Z, w, b):
    return Z @ w + b


def 손실(Z, y, w, b):  # 01 과 완전히 같음: (실제 − 예측)² 의 평균 = MSE
    return np.mean((y - 예측(Z, w, b)) ** 2)


# 기울기(어느쪽이 내리막인지)는 01처럼 '살짝 밟아보기'
# 손잡이가 5개(w 4개 + b)이므로 5번 밟아볼 것
# 편미분 : 손잡이 여러 개 중 '하나만' 살짝 움직였을 때 손실이 변하는 정도
# 아래 for문 한 바퀴가 편미분 한 번에 해당

# 그래디언트 : 편미분 5개를 한 줄로 모은 것(gw 4개 + gb)
#            5개 손자이 각각의 내리막 방향표

h = 0.0001  # 가중치를 살짝 움직여볼 크기


def 기울기_밟아보기(Z, y, w, b):
    gw = np.zeros(len(w))
    for j in range(len(w)):  # j = 0,1,2,3 : j 번째 손잡이만 움직여 본다
        w_plus, w_minus = w.copy(), w.copy()
        w_plus[j] += h  # j 번째만 살짝 키우고
        w_minus[j] -= h  # j 번째만 살짝 줄여서
        gw[j] = (손실(Z, y, w_plus, b) - 손실(Z, y, w_minus, b)) / (
            2 * h
        )  # (오른쪽 손실 − 왼쪽 손실) ÷ 거리
    gb = (손실(Z, y, w, b + h) - 손실(Z, y, w, b - h)) / (2 * h)  # b 도 한 번
    return gw, gb


def 학습(Z, y, lr=0.1, epochs=500):
    w = np.zeros(Z.shape[1])  # Z.shape[1] = 열 수 = 4. 가중치 4개를 0 에서 출발
    b = 0.0
    for _ in range(epochs):  # 500 바퀴 (학습 횟수)
        gw, gb = 기울기_밟아보기(Z, y, w, b)
        w = w - lr * gw  # 경사 하강 4개가 한꺼번에 내리막 쪽으로 보폭 lr만큼
        b = b - lr * gb
    return w, b


w, b = 학습(Z_train, y_train)  # '학습용'으로만 배움
print("\n[4] 학습 완료 — 표준화 눈금의 가중치")
for 이름, wi in zip(특징이름, w):
    # zip() : 두 줄을 나란히 짝지어 돌기
    #         (공기온도, w[0]), (회전수, w[1]) ...
    print(
        f"    {이름:6s} w = {wi:+.3f}"
    )  # {:+.3f} = 부호 붙여 소수 3자리 (00 미리보기 ①)
print(f"    절편 b = {b:.3f}")

# [4] 학습 완료 — 표준화 눈금의 가중치
#     공기온도   w = +1.791
#     회전수    w = -0.026
#     토크     w = -0.109
#     공구마모   w = -0.061
#     절편 b = 310.296

# 절편 310 : 모든 센서가 '평균값'일 때의 예측 공정온도
#           표준화 했기 때문에 z=0이라서 이런 값이 나옴
# 공기온도 w=+-1.791 : 공기온도가 표준편차 1개마늠 오르면 공정온도가 1.791 오름
#                    나머지는 거의 0.


# =====================================================================
# 5. 채점 — 학습용 점수와 시험용 점수를 '나란히'
# =====================================================================
def MSE(y, yhat):  # 손실과 같은 식. 채점용으로 이름만 따로
    return np.mean((y - yhat) ** 2)


def R2(y, yhat):  # 01 9번의 R². 1 에 가까울수록 좋음, 0 = 평균만 말하는 수준
    return 1 - np.sum((y - yhat) ** 2) / np.sum((y - y.mean()) ** 2)


tr_pred = 예측(Z_train, w, b)  # 학습용
te_pred = 예측(Z_test, w, b)  # 시험용
print("\n[5] 채점")
print(
    f"    학습용(train)  R² {R2(y_train, tr_pred):.4f}   손실 {MSE(y_train, tr_pred):.3f}"
)
print(
    f"    시험용(test)   R² {R2(y_test, te_pred):.4f}   손실 {MSE(y_test, te_pred):.3f}"
)
print("""
    읽는 법 — 두 점수를 '같이' 봐야 합니다:
      둘이 비슷하고 둘 다 좋음        → 건강. 규칙을 배운 것
      학습용만 좋고 시험용이 뚝 떨어짐  → 과적합. 답안지를 외운 것
      둘 다 나쁨                     → 과소적합. 모델이 너무 단순하거나 센서가 부족
    어림 기준: R² 차이가 0.05 안이면 정상, 0.10 넘으면 의심. (법칙은 아니고 경보선)
""")
print("    시험용 앞 6대: 예측 vs 실제")
for p, t in zip(te_pred[:6], y_test[:6]):
    print(f"      예측 {p:7.2f}   실제 {t:7.2f}   (차이 {t - p:+.2f})")

