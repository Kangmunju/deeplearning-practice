# 열마다 (값 − 그 열 평균) ÷ 그 열 표준편차. numpy 가 열 맞춰 알아서 해 줍니다
Z_train = (X_train - mu) / sd
# print("Z_train ", Z_train)

# 시험용 또한 학습용의 mu, sd로 변환
Z_test = (X_test - mu) / sd
# print("Z_test ", Z_test)

