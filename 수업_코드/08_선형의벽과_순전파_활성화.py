# 2. 해법 — 뉴런을 층으로 쌓는다 (MLP)
# =====================================================================
# 직선 하나는 못 꺾입니다. 그럼 U자를 어떻게 그릴까요?
# 발상: '살짝 휘는 조각'을 여러 개 만들어 겹쳐 더하면, 그 합이 U자처럼 굽은 모양이 될 수 있다.
#
#   직선 하나 :  ─────            (한 방향, 못 꺾임)
#   뉴런 여럿 :  ＼         ／     (각자 다르게 휜 조각을)
#   합치면    :     ＼＿／         → U자 같은 굽은 모양도 표현 가능
#
# ★ 용어 ★ 뉴런 = 그 '휘는 조각' 하나를 만드는 계산 단위.
# ★ 용어 ★ MLP(Multi-Layer Perceptron, 다층 퍼셉트론) = 뉴런을 여러 개 한 줄(층)로 세우고,
#          그 층을 여러 겹 쌓은 구조. 4단원 내내 만들 물건입니다.
#
# 뉴런 하나가 하는 일은 딱 두 단계입니다.
#   ① 가중합   : z = W·x + b      <- 이거, 02 의 직선 w·x+b 와 완전히 같은 모양입니다
#   ② 활성화   : a = g(z)         <- 이 g 가 값을 '휘게' 만드는 장본인
#
#                    W (가중치)
#                       ＼
#   입력 x ────────●────── z = W·x + b ──[ g ]── a = g(z) → 출력
#                       ／        (가중합)         (활성화)
#                    b (편향)
#
# 1단계까지는 직선과 같습니다. 새로 생긴 건 2단계 활성화 g 하나뿐이에요.
# 이 g 가 있고 없고가 아래 §4 에서 결정적 차이를 만듭니다.


def sigmoid(z):
    """★ 용어 ★ 시그모이드 = 어떤 값이든 0~1 사이로 'S자'로 눌러 주는 함수.
    식은 이거 하나뿐입니다.  sigmoid(z) = 1 / (1 + e^(-z))
    e 는 자연상수(약 2.718), e^(-z) 가 math.exp(-z) 입니다.
    03 로지스틱 회귀에서 이미 쓴 그 함수예요. 거기선 출력에 씌웠고, 여기선 은닉층에 씁니다."""
    return 1 / (1 + math.exp(-z))


def relu(z):
    """★ 용어 ★ ReLU(Rectified Linear Unit) = 음수는 0 으로 자르고, 양수는 그대로 통과.
    이름은 거창한데 하는 일은 '음수 자르기' 하나입니다.  relu(z) = max(0, z)"""
    return max(0.0, z)


