# 1. 선형의 벽 — 02 의 직선을 U자 데이터에 대 본다
# =====================================================================
# 제조 현장의 실제 감각 그대로인 데이터입니다.
#   온도가 너무 낮으면 재료가 덜 녹아서 불량, 너무 높으면 타서 불량.
#   딱 중간(25도 근처)이 불량이 가장 적습니다.
#
#     불량
#      9 |●                                    ●      <- 양 끝(저온·고온)에서 불량 많음
#        |  ＼                              ／
#      5 |     ●                        ●
#        |        ＼                 ／
#      2 |           ●           ●
#      1 |                ● (바닥)                     <- 가운데가 최선
#        +-----------------------------→ 온도
#           10   15   20   25   30   35   40
#
# 이게 U자(아래로 볼록) 패턴입니다. 직선 한 개로는 이 골짜기를 못 그립니다.
# 그런데 정말 못 그리는지, 02 의 도구로 직접 확인해 봅시다.

온도 = [10, 15, 20, 25, 30, 35, 40]
불량 = [9, 5, 2, 1, 2, 5, 9]


def 평균(값들):
    return sum(값들) / len(값들)


def 예측하기(xs, w, b):
    """각 x 마다 ŷ = w·x + b. 02 에서 한 것과 완전히 같습니다"""
    return [w * x + b for x in xs]  # ★ 문법 ★ 리스트 컴프리헨션 (00 §0 ③)


# 가장 잘 맞는 직선을 공식으로 단번에 구합니다.
# 02 에서는 경사하강으로 '걸어서' 찾았죠. 걸어가도 답은 같으니 여기선 빠른 공식을 씁니다.
# (이 공식 자체가 궁금하면 02 를 보세요. 오늘의 주제는 '이 직선이 얼마나 못 맞히나' 입니다.)
x_bar, y_bar = 평균(온도), 평균(불량)
w = sum((x - x_bar) * (y - y_bar) for x, y in zip(온도, 불량)) / sum(
    (x - x_bar) ** 2 for x in 온도
)
b = y_bar - w * x_bar
# ★ 문법 ★ zip(a, b) = 두 리스트를 짝지어 (a0,b0), (a1,b1) ... 로 돌려줍니다. 02 에서도 썼습니다


def R2(xs, ys, w, b):
    """★ 용어 ★ R²(설명력) = 이 직선이 데이터를 얼마나 설명하나. 02 에서 배운 그 점수입니다.
    1 에 가까우면 잘 맞음. 0 이면 '그냥 평균 찍기와 다를 바 없음'."""
    y_bar = 평균(ys)
    preds = 예측하기(xs, w, b)
    SSE = sum((y - p) ** 2 for y, p in zip(ys, preds))  # 직선이 못 맞힌 오차
    SST = sum((y - y_bar) ** 2 for y in ys)  # 그냥 평균으로 찍었을 때의 오차
    return 1 - SSE / SST


print("=" * 60)
print("[1] U자 데이터에 02 의 직선을 맞춰 보면")
print(f"    기울기 w = {w:.4f}")
print(f"    절편  b = {b:.4f}   (불량의 평균 = {y_bar:.4f})")
print(f"    R2(설명력) = {R2(온도, 불량, w, b):.4f}")
print()
print("    온도별 실제 불량 vs 직선 예측")
for t, y in zip(온도, 불량):
    print(
        f"      온도 {t:3d}도   실제 {y}   직선 예측 {w * t + b:6.2f}   오차 {y - (w * t + b):+6.2f}"
    )

