print("[2] 활성화 함수 두 개 — 값을 넣어 보면")
print("        z      sigmoid(z)    relu(z)")
for z in [-3, -1, 0, 1, 3]:
    print(f"      {z:4d}      {sigmoid(z):8.4f}   {relu(z):7.1f}")

