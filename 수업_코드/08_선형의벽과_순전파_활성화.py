# |         |    ●●
# |     0.0 |●●●●___________________             <- 큰 음수는 0 에 붙음
# |         +-----------------------→ z
# |          -3    -1   0    1    3
# |
# |   가운데는 비스듬한 직선처럼 보이는데, 양 끝으로 갈수록 눕습니다.
# |   이 휘어짐이 곡선의 씨앗입니다.
