# 오늘은 식을 쓰고 '맞는지 대조'만 합니다. 미분을 극한으로 유도하지 않습니다.

# 시그모이드 : S자 모양이므로 가운데는 가파르고 양 끝은 완만함
#            위치에 따라 기울기가 달라짐
# ReLU : 음수 구간에서는 출력이 계속 0이므로 기울기가 0
#        양수 구간에서는 입력이 1 증가하면 출력도 1 증가하므로 기울기가 1
# 활성화 함수의 출력값을 구하는 것과 그 지점에서의 기울기를 구하는 것은 서로 다른 계산!


def sigmoid_도함수(z):
    """sigmoid'(z) = sigmoid(z) · (1 - sigmoid(z))
    아주 예쁜 성질입니다. a = sigmoid(z) 라고 두면 도함수가 a·(1-a).
    즉 sigmoid 값만 알면 도함수가 바로 나옵니다. e 를 다시 계산할 필요가 없어요."""
    a = sigmoid(z)
    return a * (1 - a)


def relu_도함수(z):
    """relu'(z) = 1 (z > 0), 0 (z <= 0)
    꺾은선이라 도함수도 간단합니다. 양수 구간은 45도(기울기 1), 음수 구간은 바닥(기울기 0).
    z=0 딱 그 점은 수학적으로 애매하지만, 실무에선 그냥 0 으로 둡니다."""
    return 1.0 if z > 0 else 0.0  # ★ 문법 ★ 한 줄 if (00 §0 ⑤)


def 수치미분(f, z, h=1e-6):
    """★ 용어 ★ 수치미분 = 아주 작은 h 만큼 양옆으로 움직여 실제 기울기를 근사로 재는 것.
    기울기 ≈ ( f(z+h) - f(z-h) ) / (2h)
    우리가 쓴 도함수 식이 맞는지 채점하는 용도입니다. 09 에서도 또 씁니다."""
    return (f(z + h) - f(z - h)) / (2 * h)


