W_eff = V1 * W1 + V2 * W2  # = 4.0·0.3 + (-3.0)·(-0.2) = 1.8
b_eff = V1 * b1 + V2 * b2 + c  # = 4.0·(-6.0) + (-3.0)·5.0 + 1.0 = -38.0

