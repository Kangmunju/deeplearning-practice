# 3. 순전파 — 손으로 한 번, 코드로 한 번
# =====================================================================
# 이번 파트 또한 아직 학습 전
# 가중치를 조정하지 않고 미리 정해 둔 숫자로 계산 과정만 확인
#
# ★ 아키텍처 ★ 08·09 두 파일 내내 쓸 아주 작은 신경망입니다. 계속 이 기호를 씁니다.
#
#                       은닉층 (활성화 g 있음)
#                   ┌──────────────────┐
#                   │   ● 뉴런1          │
#        W1,b1    ╱ │     a1 = g(z1)    │ ╲  V1
#   입력 x ●────╱   │                    │   ╲───● 출력 ŷ = V1·a1 + V2·a2 + c
#                ╲  │   ● 뉴런2           │   ╱  V2      (여긴 활성화 없이 선형)
#        W2,b2    ╲ │     a2 = g(z2)    │ ╱
#                   └──────────────────┘
#
# 뉴런 1과 뉴런 2가 서로에게 값을 전달하는 것이 아님
# 같은 온도 x를 각각 받아 계산하는 것
# 두 결과를 마지막 출력층에서 합침
#
#   • 입력  : 온도 x (숫자 하나)
#   • 은닉층: 뉴런 2개. 각자 가중합 + 활성화 g.  <- 여기가 '휘는' 부분
#   • 출력  : 은닉층 두 값을 가중합. 활성화 없이 그냥 선형
#
#   은닉 뉴런1 : z1 = W1·x + b1,  a1 = g(z1)
#   은닉 뉴런2 : z2 = W2·x + b2,  a2 = g(z2)
#   출력      : ŷ = V1·a1 + V2·a2 + c
#
# ★ 용어 ★ 순전파(forward) = 입력 x 가 왼쪽에서 출발해 화살표를 타고 출력 ŷ 까지
#          '앞으로 흘러가는' 계산 전부. 순서는 딱 이겁니다: x → (z1,z2) → (a1,a2) → ŷ
#
# 가중치는 아무거나 정해 둡니다. ★ 아직 학습한 게 아닙니다 ★ — 학습은 09 에서 합니다.
# 오늘은 '계산이 어떻게 흐르나'만 봅니다.
W1, b1 = 0.3, -6.0  # 은닉 뉴런1
W2, b2 = -0.2, 5.0  # 은닉 뉴런2
V1, V2, c = 4.0, -3.0, 1.0  # 출력층


def 순전파(x, 활성화):
    """x 하나가 들어와 ŷ 하나가 나오기까지. 위 그림 그대로 앞으로 흐릅니다.
    ★ 문법 ★ 활성화를 인자로 받습니다. 파이썬에서는 함수도 값처럼 넘길 수 있어요.
             이렇게 해 두면 §6 에서 sigmoid 와 relu 를 갈아 끼우기만 하면 됩니다."""
    z1 = W1 * x + b1  # 뉴런1 가중합
    z2 = W2 * x + b2  # 뉴런2 가중합
    a1 = 활성화(z1)  # 뉴런1 활성화
    a2 = 활성화(z2)  # 뉴런2 활성화
    y_hat = V1 * a1 + V2 * a2 + c  # 출력 (활성화 없이 선형)
    return y_hat, z1, z2, a1, a2  # 중간값도 같이 돌려줘서 눈으로 확인


