#  [오늘의 결론 세 줄]
#    1) 직선은 U자를 못 그린다 — R²=0 으로 '선형의 벽'을 숫자로 봤다
#    2) 뉴런(가중합 + 활성화)을 층으로 쌓은 게 MLP. 순전파는 x → ŷ 로 앞으로 흐르는 계산
