#
#  [기억할 순전파 식 — 09 까지 계속 씁니다]
#    z1 = W1·x + b1,   z2 = W2·x + b2      (은닉층 가중합)
#    a1 = g(z1),       a2 = g(z2)          (은닉층 활성화)
#    ŷ  = V1·a1 + V2·a2 + c                (출력, 선형)
#
#  [활성화 두 개와 그 도함수 — 09 의 부품]
#    sigmoid(z) = 1/(1+e^(-z))   →  sigmoid'(z) = a·(1-a)   (a = sigmoid(z))
#    relu(z)    = max(0, z)      →  relu'(z)    = 1 (z>0), 0 (z<=0)
#
#  [3단원과의 연결]
#    02 선형회귀     → 가중합 z = W·x + b 가 그 식 그대로
