#   3단계  ŷ  = 4.0 x a1 + (-3.0) x a2 + 1.0 = ?
# (a2 는 계산기 없이도 나옵니다. z2 가 정확히 0 이고 sigmoid(0)=0.5 니까요.)

print("=" * 60)
