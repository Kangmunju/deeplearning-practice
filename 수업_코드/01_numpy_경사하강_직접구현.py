# 9. 써먹기 — 새 공기온도의 공정온도 예측, 그리고 점수
# =====================================================================
print("\n[9] 예측")
for 새온도 in [298.0, 300.0, 303.0]:
    print(f"    공기온도 {새온도} → 예측 공정온도 {예측(새온도, w_gd, b_gd):.2f}")


# R2(설명력) : 얼마나 잘 맞나를 0~1 점수로
#             1이면 완벽, 0이면 그냥 평균으로 찍기와 같은 수준
# 직선이 정답의 흩어짐을 몇 % 설명하냐로 읽음


def R2(x, y, w, b):
    못맞힌것 = np.sum((y - 예측(x, w, b)) ** 2)  # 직선이 못 맞힌 만큼
    평균으로찍기 = np.sum((y - y.mean()) ** 2)  # 그냥 평균으로 답했을 때 틀린 만큼
    return 1 - 못맞힌것 / 평균으로찍기


r2 = R2(x, y, w_gd, b_gd)
print(
    f"    R² = {r2:.4f}  ← 공정온도의 흩어짐 중 약 {r2 * 100:.0f}% 를 공기온도 하나로 설명"
)

# 이 0.7989는 본 문제로 채점한 점수
# 학습에 쓴 200대 그대로 다시 채점
# 이 점수가 얼마나 쉽게 부풀려지는지 확인
# 설비를 딱 2개만 주고 학습시킬 것

print("\n[9-1] 설비 2대만 주고 배우게 하면 R² 는 몇 점일까")
x2, y2 = x[:2], y[:2]  # 앞의 2대만
w2 = (y2[1] - y2[0]) / (x2[1] - x2[0])  # 두 점을 잇는 직선의 기울기
b2 = y2[0] - w2 * x2[0]  # 그 직선의 절편
예측2 = 예측(x2, w2, b2)
print(
    f"    배운 2대로 채점: R² = {1 - np.sum((y2 - 예측2) ** 2) / np.sum((y2 - y2.mean()) ** 2):.4f}  ← 만점"
)

print(
    f"    같은 직선으로 200대 전부 채점: R² = {R2(x, y, w2, b2):.4f}  ← 200대로 배운 0.7989 보다 한참 아래"
)
print(
    f"    참고: 2대로 얻은 직선은 w={w2:.3f}, b={b2:.1f} / 200대로 얻은 직선은 w={w_gd:.3f}, b={b_gd:.1f}"
)
# [9-1] 설비 2대만 주고 배우게 하면 R² 는 몇 점일까
