#     같은 직선으로 200대 전부 채점: R² = 0.6241  ← 200대로 배운 0.7989 보다 한참 아래
#     참고: 2대로 얻은 직선은 w=1.182, b=-43.8 / 200대로 얻은 직선은 w=0.984, b=14.8

