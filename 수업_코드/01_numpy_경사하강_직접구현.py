import os
import numpy as np
import pandas as pd

DATA = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "수업용_데이터"
)  # data/수업용_데이터/
df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i.csv"), encoding="utf-8-sig")

x = df["공기온도"].values.astype(
    float
)  # 입력: 설비 200대의 공기온도. astype(float) = 전부 실수형으로 (정수 섞임 방지)
