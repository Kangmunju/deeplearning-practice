# 설비 200 대 / 공기온도 295.9 ~ 306.1 / 공정온도 304.4 ~ 316.9
# 앞 5대  공기온도: [302.1 299.9 299.9 298.8 300.2]
# 앞 5대  공정온도: [313.2 310.6 310.9 308.8 311. ]

# 눈으로 보면 공정온도는 공기온도보다 애략 10도 정도 높음
# 그 '대략'을 정확한 숫자로 찾는 것이 오늘의 목표


# =====================================================================
# 1. 예측은 직선 하나 — 숫자 두 개로 결정된다
# =====================================================================
# 예측 공정온도 = w * 공기온도 + b
# w = 공기온도가 1 오를 때 공정온도가 얼마나 오르는가(기울기), 가중치
# b = 그냥 더해 주는 값(절편), 보정값

# 선형 모델 : 입력에 숫자(w)를 곱하고 숫자(b)를 더해서 답을 내는 모델
#            그래프로 그리면 직선이 됨
# 가장 단순하지만 어느 입력이 얼마나 영향을 주는 지(w) 읽을 수 있어서 현장에서 자주 사용

# 선형 회귀 : '선형 모델'로 '숫자'를 맞히는 것
# 회귀 : 맞히려는 답이 '숫자'인 문제 ex) 공정온도 308.8처럼 연속된 값


def 예측(x, w, b):
    return w * x + b  # x 가 배열이면 200개가 한꺼번에 계산됩니다 (numpy 의 장점)


print("\n[1] 일단 감으로 w=1, b=10 을 넣어 봅니다 ('공정온도 = 공기온도 + 10')")
print("    예측 (앞 5대):", 예측(x, 1.0, 10.0)[:5])
print("    실제 (앞 5대):", y[:5])
# [1] 일단 감으로 w=1, b=10 을 넣어 봅니다 ('공정온도 = 공기온도 + 10')
#     예측 (앞 5대): [312.1 309.9 309.9 308.8 310.2]
#     실제 (앞 5대): [313.2 310.6 310.9 308.8 311. ]


# =====================================================================
# 2. 손실 — 틀린 정도를 점수 하나로 (작을수록 좋음)
# =====================================================================
# 방법 : (실제 - 예측)을 200대 각각 구함 -> 제곱 -> 평균 구하기
# 제곱하는 이유 1) -3 오차와 +3 오차가 더해져 상쇄되는 것을 방지
#             2) 큰 오차는 더 크게 벌주기 위해
# 손실 : 얼마나 틀렸냐를 나타내는 점수 중 하나(작을수록 좋음)
# MSE(평균제곱오차) : 오늘 사용할 손실, '틀린 정도를 제곱해서 평균'낸 것
#                   회귀에서 가장 흔함


def 손실(x, y, w, b):
    틀린정도 = y - 예측(x, w, b)  # 설비마다 (실제 − 예측). 200개
    return np.mean(틀린정도**2)  # 제곱해서 평균. ** 2 = 제곱


print("\n[2] 여러 직선의 손실 점수")
for w, b in [(1.0, 10.0), (1.0, 9.0), (1.0, 11.0), (0.0, 310.0)]:
    print(
        f"    w={w}, b={b:<5} → 손실 {손실(x, y, w, b):.4f}"
    )  # {b:<5} = 5칸 왼쪽 정렬 (00 미리보기 ①)
# [2] 여러 직선의 손실 점수
#     w=1.0, b=10.0  → 손실 0.8941
#     w=1.0, b=9.0   → 손실 1.8281
#     w=1.0, b=11.0  → 손실 1.9601
#     w=0.0, b=310.0 → 손실 4.4784


# =====================================================================
# 3. 어느 쪽으로 고칠까 — 살짝 바꿔 보고 손실을 다시 잰다
# =====================================================================
# 안개 낀 언덕에서 내려갈 때 하는 일 : 왼발 오른발로 땅을 밟아보고 낮은 쪽으로 감
# 손잡이 하나(b)를 아주 조금 키우거나 줄여가며 손실이 어느 쪽에서 작아지는지 확인
# w는 1.0으로 고정

print("\n[3] b 를 살짝 밟아보기 (w=1.0 고정, 지금 b=9.0 이라고 치고)")
print(f"    b=8.9 → 손실 {손실(x, y, 1.0, 8.9):.4f}")
print(f"    b=9.0 → 손실 {손실(x, y, 1.0, 9.0):.4f}   ← 지금 자리")
print(f"    b=9.1 → 손실 {손실(x, y, 1.0, 9.1):.4f}")
# b를 키우면 (9.1) 손실이 줄고, b를 줄이면 (8.9)로 손실이 는다 -> b를 키우는 쪽이 내리막

# 이 밟아보기를 숫자 하나로 요약한 게 기울기
# 기울기 = (오른쪽 손실 - 왼쪽 손실) / (오른쪽과 왼쪽 사이 거리)
# 양수(+) -> 오른쪽이 오르막 -> 손잡이를 줄여라
# 음수(-) -> 오른쪽이 내리막 - 손잡이를 키워라
# 0 근처 -> 양쪽이 평평 = 바닥 = 도착
#
# 미분 : '손잡이를 아주 조금 돌리면 손실이 얼마나, 어느 쪽으로 변하나'를 숫자 하나로 만든 것
#        방금 우리가 한 밟아보기가 바로 그것
#        공식이 아니라 '살짝 밀어 보고 재기'로 이해하면 충분함

# [3] b 를 살짝 밟아보기 (w=1.0 고정, 지금 b=9.0 이라고 치고)
#     b=8.9 → 손실 2.0315
#     b=9.0 → 손실 1.8281   ← 지금 자리
#     b=9.1 → 손실 1.6447

# 편미분 = '손잡이가 여러개(w, b)일 때 나머지는 그대로 두고 '하나만' 돌려본 미분
#         b만 돌린 것이 b의 편미분, w만 돌린 것이 w이 편미분 -> 손잡이의 기울기

# 그래디언트 : 그 편미분들을 (w방향, b방향) 한 묶음으로 모은 것
#            어느 쪽이 오르막인지 가리키는 화살표

# 손잡이가 2개든 200개든, 각각 어느 쪽으로 돌려야 손실이 줄어드는 지 파악하기 위해 필요

# h = 학습률
h = 0.0001  # 아주 살짝만 밟는다 (크게 밟으면 지금 자리가 아닌 엉뚱한 곳을 재게 됨)


def 기울기_밟아보기(x, y, w, b):
    gw = (손실(x, y, w + h, b) - 손실(x, y, w - h, b)) / (
        2 * h
    )  # w 만 ±h 밀어 본 기울기 (w 의 편미분)
    gb = (손실(x, y, w, b + h) - 손실(x, y, w, b - h)) / (
        2 * h
    )  # b 만 ±h 밀어 본 기울기 (b 의 편미분)
    return gw, gb  # 둘을 묶어 돌려줌 = 그래디언트


gw, gb = 기울기_밟아보기(x, y, 1.0, 9.0)
print(f"\n    w=1.0, b=9.0 에서  b 방향 기울기 = {gb:.3f} (음수 → b 를 키워라)")
print(f"                       w 방향 기울기 = {gw:.3f} (음수 → w 도 키워라)")
# w=1.0, b=9.0 에서  b 방향 기울기 = -1.934 (음수 → b 를 키워라)
#                    w 방향 기울기 = -580.548 (음수 → w 도 키워라)

# w 방향 기울기가 b보다 300배 쯤 큼
# 공기온도가 300근처의 큰 숫자라 w를 조금만 건드려도 예측이 흔들림
# 이러한 '민감함'이 큰 문제를 일으킴

# =====================================================================
# 4. 한 걸음 내려가기 — 규칙은 딱 한 줄
# =====================================================================
# 새 w = 지금 w - 학습률 * 기울기   (b도 동일)
# 기울기가 +면 줄여야 하고 -면 키워야 하기 때문에 (지금 w)에서 (학습률*기울기)를 빼는 것

# 경사하강 : 기울기(오르막 방향)의 '반대'로 조금씩 걸어 손실이 가장 낮은 곳을 찾는 방법
#           이름 그대로 경사(기울기)를 따라 하강

# 학습률(lr) : 한 걸음의 크기(보폭) <- 우리가 정하는 값
#             기울기가 -600처럼 큰 경우 그대로 식에 대입해버리면 너무 멀리 뜀
#             작은 수를 곱해 조심조심 걸을 것
# 손실이 가장 작은 w, b가 '가장 잘맞는 직선'인데 그걸 한 번에 아는 공식이 없다는 문제가 대부분
# 직접 걸어서 찾아가는 방법을 익혀두어야 함

lr = 0.00001
w, b = 1.0, 9.0
print("\n[4] 한 걸음 (lr=0.00001)")
print(f"    이전: w={w:.5f}, b={b:.5f}, 손실 {손실(x, y, w, b):.4f}")
w = w - lr * gw
b = b - lr * gb
print(
    f"    이후: w={w:.5f}, b={b:.5f}, 손실 {손실(x, y, w, b):.4f}   ← 줄었죠? 이걸 반복하면 됩니다"
)
# [4] 한 걸음 (lr=0.00001)
#     이전: w=1.00000, b=9.00000, 손실 1.8281
#     이후: w=1.00581, b=9.00002, 손실 1.4961   ← 줄었죠? 이걸 반복하면 됩니다

# 손실이 줄어드는 것을 계속 반복(같은 계산을 다시 해서 또 움직이는 것)
# 한 번이 한 걸음
# 이 학습이라는 것은 이 한 걸음을 여러번 반복하는 것
# 그런데 보폭이 현재 설정한 lr처럼 매우 작으면 바닥까지 몇만 걸음이 걸림
# 그렇다고 보폭을 엄청 크게 키우면 너무 크게 뜀

# =====================================================================
# 5. 걸음이 튕기는 문제 — 표준화 ( 이걸 빼면 실패합니다)
# =====================================================================
# 공기 온도가 300 근처의 큰 숫자라 w 방향 기울기가 너무 커서 보폭을 조금만 키워도 튕겨 나가게 됨
# 일부러 실패해 볼 것

w, b = 1.0, 9.0
with np.errstate(over="ignore", invalid="ignore"):
    for _ in range(20):
        gw, gb = 기울기_밟아보기(x, y, w, b)
        w, b = w - 0.001 * gw, b - 0.001 * gb
print(
    "\n[5] 보폭을 0.001 로 키워 20걸음 → 손실:", 손실(x, y, w, b), "← 숫자가 폭발(발산)"
)

# 발산 : 걸음이 너무 커서 골짜기를 넘어 반대편, 다시 그 반대편, ... 점점 튕겨 나가 손실이 무한대로
# 해결 -> 입력을 '평균=0', '퍼짐=1' 크기로 변경
# z = (x - 평균) / 표준편차 -> 300 근처 숫자가 -2~+3 사이의 숫자가 됨
# 정보는 그대로 두고 눈금만 바꾼 것

# 표준화 : 값에서 평균을 빼고 표준편차로 나눠 어떤 데이터든 비슷한 크기(대략 -3~+3)로 맞추는 것
# 숫자가 크면 걸음이 튕기고(발산), 나중에 여러 센서를 쓸 때 단위가 달라 공평하지 않게 됨
# 경사하강 전에 거의 항상 이 과정을 거칠 것

m = x.mean()  # 평균
s = x.std()  # 표준편차 (퍼진 정도)
z = (x - m) / s
print(f"    표준화: 평균 {m:.2f}, 표준편차 {s:.2f}")
print(f"    x 앞 3개: {x[:3]}  →  z 앞 3개: {z[:3].round(3)}")
# [5] 보폭을 0.001 로 키워 20걸음 → 손실: 3.7917438348264583e+31 ← 숫자가 폭발(발산)
#     표준화: 평균 300.24, 표준편차 1.91
#     x 앞 3개: [302.1 299.9 299.9]  →  z 앞 3개: [ 0.972 -0.178 -0.178]

# 평균을 빼고 표준편차로 나눈 숫자로 만들어 줌
# 평균이면 0, 평균보다 한 칸 위면 1이라는 새 눈금으로 바꾼 것


# =====================================================================
# 6. 경사하강 완성 — 한 걸음을 반복하면 바닥에 닿는다
# =====================================================================
# 학습(fit) : 데이터를 보고 w, b를 찾는 일
#            아래 함수가 하는 일이며 사이킷런의 .fit()도 동일한 역할을 함
# 에폭(epoch) : 데이터 전체를 한 번 훑고 w, b를 한 번 고친 것(300에폭 = 300걸음)


def 학습(z, y, lr=0.1, epochs=300, 보여주기=True):
    w, b = 0.0, 0.0  # 아무 데서나 출발해도 됩니다 (여기선 0)
    for epoch in range(epochs):  # 한 바퀴 = 한 걸음
        gw, gb = 기울기_밟아보기(z, y, w, b)  # ① 어느 쪽이 내리막?
        w = w - lr * gw  # ② 그쪽으로 한 걸음
        b = b - lr * gb
        if 보여주기 and epoch in (0, 1, 2, 5, 10, 30, 100, 299):
            print(
                f"    epoch {epoch:3d}  w={w:7.3f}  b={b:8.3f}  손실 {손실(z, y, w, b):10.4f}"
            )  # 자릿수 지정은 00 미리보기 ①
    return w, b


print("\n[6] 경사하강 (표준화한 z 로, lr=0.1)")
w_z, b_z = 학습(z, y)
# [6] 경사하강 (표준화한 z 로, lr=0.1)
#     epoch   0  w=  0.376  b=  62.041  손실 61589.5233
#     epoch   1  w=  0.678  b= 111.675  손실 39417.6161
#     epoch   2  w=  0.919  b= 151.381  손실 25227.5954
#     epoch   5  w=  1.389  b= 228.888  손실  6613.9210
#     epoch  10  w=  1.721  b= 283.561  손실   710.9606
#     epoch  30  w=  1.880  b= 309.900  손실     0.9865
#     epoch 100  w=  1.882  b= 310.207  손실     0.8921
#     epoch 299  w=  1.882  b= 310.208  손실     0.8921

# 출발점이 w=0, b=0이라 처음 손실이 6만처럼 크게 나오는 것이 정상
# 손실이 처음에는 확 줄었다가 어느 순간 변하지 않음 = 바닥 = 도착

# z 눈금에서 찾은 직선을 원래 온도 눈금으로 되돌림
# 결과만 사용할 것
w_gd = w_z / s
b_gd = b_z - w_z * m / s
print(f"\n    결과: 공정온도 ≈ {w_gd:.4f} × 공기온도 + {b_gd:.4f}")
print(
    f"    손실: {손실(x, y, w_gd, b_gd):.4f}  (감으로 넣은 (1, 10) 은 0.8941 → 0.8921. 감이 꽤 좋았던 셈이죠)"
)
# 결과: 공정온도 ≈ 0.9840 × 공기온도 + 14.7799
#     손실: 0.8921  (감으로 넣은 (1, 10) 은 0.8941 → 0.8921. 감이 꽤 좋았던 셈이죠)

# 그러나 센서가 4개, 10개가 되면 감으로는 절대 찾지 못함

# =====================================================================
# 7. 학습률(보폭) 실험 — 너무 크면? 너무 작으면?
# =====================================================================
print("\n[7] 보폭(lr)을 바꿔 300걸음 후 손실")
for lr in [0.001, 0.01, 0.1, 1.05]:
    w_t, b_t = 학습(z, y, lr=lr, 보여주기=False)
    L = 손실(z, y, w_t, b_t)
    if np.isnan(L) or L > 1e6:  # np.isnan = "숫자가 아님(폭발)" 인가
        판정 = "발산 (튕겨 나감)"
    elif L > 1.0:
        판정 = "굼벵이 (300걸음으론 아직 멀었음)"
    else:
        판정 = "좋음 (바닥)"
    print(f"    lr={lr:<6} → 손실 {L:>14.4f}  {판정}")
# [7] 보폭(lr)을 바꿔 300걸음 후 손실
#     lr=0.001  → 손실     28950.6776  굼벵이 (300걸음으론 아직 멀었음)
#     lr=0.01   → 손실         1.4156  굼벵이 (300걸음으론 아직 멀었음)
#     lr=0.1    → 손실         0.8921  좋음 (바닥)
#     lr=1.05   → 손실 22894577967880109817856.0000  발산 (튕겨 나감)

# 결론
# 너무 작으면(0.001) 300걸음으로는 못 내려옴 -> 걸음 수를 훨씬 늘려야 함 -> 시간 낭비
# 너무 크면(1.05) 튕겨 나감 -> 발산 -> 아예 답을 얻지 못함
# 적당하면(0.1) 금방 바닥에 도달
