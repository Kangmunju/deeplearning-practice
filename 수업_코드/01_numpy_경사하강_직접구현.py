# =====================================================================
# 8. 정말 맞게 찾았나 — 공식과 대조
# =====================================================================
# 선형회귀는 한 방에 답을 주는 공식이 있음
# 통계 시간의 최소제곱
# 입력이 여러개인 경우에도 사용할 수 있는 공식이 존재
# 걸어서 온 값과 공식 값이 동일하면 걷기가 제대로 됐다는 증거

w_공식 = np.sum((x - x.mean()) * (y - y.mean())) / np.sum((x - x.mean()) ** 2)
b_공식 = y.mean() - w_공식 * x.mean()
print("\n[8] 대조")
print(f"    걸어서   w={w_gd:.4f}  b={b_gd:.4f}")
print(f"    공식으로 w={w_공식:.4f}  b={b_공식:.4f}")
print(
    "    같은가? ", abs(w_gd - w_공식) < 1e-3 and abs(b_gd - b_공식) < 1e-3
)  # 소수 셋째 자리까지 같으면 True
# [8] 대조
#     걸어서   w=0.9840  b=14.7799
#     공식으로 w=0.9840  b=14.7799
#     같은가?  True

# 굳이 걷는 법을 배운 이유
# 선형회귀는 공식이 있으나 분류(로지스틱)부터는 공식이 없음
# 그런 문제에서는 오직 '걷기'만 통함
# 답을 아는 문제로 걷는 법을 익혀두어야 답을 모르는 문제에서도 같은 걸음으로 갈 수 있는 것

