# TODO: 여기에 코드를 쓰세요
def gradient_descent(lr=0.1, epochs=300):
    w = 0
    b = 0
    for epoch in range(epochs):
        gw = (L(w + h, b) - L(w - h, b)) / (2 * h)
        gb = (L(w, b + h) - L(w, b - h)) / (2 * h)
        # 손잡이 = 손잡이 - lr * 기울기
        w = w - lr * gw
        b = b - lr * gb
    return w, b


