# B6. 표준화한 z 를 쓰는 손실 함수를 따로 만드세요. 이름은 L(w, b) 로 하세요.
#     w=0, b=0 자리에서 w 방향과 b 방향의 기울기를 구해 출력하세요.
#       기울기 = (오른쪽 손실 - 왼쪽 손실) / (오른쪽과 왼쪽 사이 거리)
#       살짝 미는 폭 h 는 0.0001 로 하세요.
#
# [나와야 하는 출력]
#     w 방향 기울기: -7.729
#     b 방향 기울기: -25.49
#
# [답하기] 둘 다 음수입니다. 손잡이를 어느 쪽으로 돌려야 하나요?
#          b 쪽이 3배 이상 급합니다. 왜 그럴까요?
# ---------------------------------------------------------------------


# TODO: 여기에 코드를 쓰세요
def L(w, b):
    predict = w * z + b
    error = y - predict
    return np.mean(error**2)


h = 0.0001
# 기울기를 확인하기 위해 앞뒤로 살짝 움직이는 폭

w = 0
b = 0

gw = (L(w + h, b) - L(w - h, b)) / (2 * h)
# w 방향의 기울기
# w를 +h, -h만큼 움직였을 때의 손실 차이를 이용

gb = (L(w, b + h) - L(w, b - h)) / (2 * h)
# b 방향의 기울기
# b를 +h, -h만큼 움직였을 때의 손실 차이를 이용

print("w 방향 기울기: ", round(gw, 3))
print("b 방향 기울기: ", round(gb, 3))

# gw와 gb 둘 다 음수이기 때문에 오른쪽(+방향)으로 돌려야 손실 감소.

