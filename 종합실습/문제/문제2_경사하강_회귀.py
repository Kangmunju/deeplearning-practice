# [2-3] 직선이 놓친 것
#   [2-1] 모델의 잔차(실제 - 예측)를 회전수 구간별로 평균 내 보세요.
#   구간: 1100~1300, 1300~1400, 1400~1500, 1500~1600, 1600~1800, 1800~2000, 2000~3000
#
#   ★ 설명 ★  잔차의 부호가 구간에 따라 어떤 '모양'을 그리나요? 그 모양이 뜻하는 건?
#
#   이제 입력을 [회전수, 1/회전수] 두 개로 바꿔 다시 학습하세요. (둘 다 표준화, lr 0.1, 2000 epochs)
#   확인: R² 가 0.766 → 0.848 로 오릅니다.
#   ★ 설명 ★  모델은 여전히 '선형회귀'입니다. 그런데 어떻게 곡선을 맞혔나요?
#             1/회전수 를 떠올릴 물리적 근거는? (힌트: 모터 출력 = 토크 × 회전 속도)
#             08 의 '선형의 벽' 과 무슨 관계인가요?
# ---------------------------------------------------------------------
print("\n[2-3] 직선이 놓친 것")

잔차 = y - yhat
구간 = [1100, 1300, 1400, 1500, 1600, 1800, 2000, 3000]

잔차표 = pd.DataFrame({"회전수": x, "잔차": 잔차})
잔차표["구간"] = pd.cut(잔차표["회전수"], bins=구간, right=False)

print(
    f"구간별 평균 잔차\n{잔차표.groupby('구간', observed=True)['잔차'].mean().round(4)}"
)

# 잔차는 낮은 회전수에서 양수, 중간에서 음수, 높은 회전수에서 다시 양수
# U자 형태로 나타나므로 직선이 실제 데이터의 곡선 관계를 충분히 표현하지 못함

X2 = np.column_stack((x, 1 / x))
X2_평균 = X2.mean(axis=0)
X2_표준편차 = X2.std(axis=0)
Z2 = (X2 - X2_평균) / X2_표준편차

w2, b2 = 학습(Z2, y, lr=0.1, epochs=2000)
yhat2 = 예측(Z2, w2, b2)

print(f"회전수 하나 R² {R2(y, yhat):.4f}")
print(f"회전수 + 1/회전수 R² {R2(y, yhat2):.4f}")

# 회전수의 역수를 새로운 특징으로 추가했으므로 원래 회전수에 대해서는 곡선 표현이 가능
# 가중치에 대해서는 여전히 선형이므로 선형회귀에 해당
# 모터 출력 = 토크 × 회전 속도이므로 출력이 일정하면 토크는 회전수에 반비례
# 08의 선형의 벽처럼 직선만으로는 복잡한 관계를 표현하기 어려움
# 하지만 비선형 특징을 직접 추가하면 선형 모델로도 곡선 관계를 학습할 수 있음


