# =====================================================================
#  문제 2 — 토크를 맞혀라. 경사하강을 손으로  (01 · 02)
# =====================================================================
#  [상황]
#    토크 센서가 비쌉니다. 회전수 센서는 쌉니다.
#    "회전수만 보고 토크를 어림할 수 있으면 토크 센서를 줄일 수 있지 않을까?"
#    수업 때는 공정온도를 맞혔죠. 오늘은 토크입니다. 같은 걸음, 다른 문제.
#
#  [파일]  데이터/11_설비센서_ai4i_전체.csv  (10,000행)
#
#  [쓰는 것]  numpy, pandas 만.  ★ sklearn 금지 ★ (대조용 np.polyfit, np.linalg.lstsq 는 허용)
#
#  [공통 조건]  — 이걸 지켜야 확인값과 맞습니다
#    - 손실은 MSE (오차 제곱의 평균)
#    - 가중치·절편은 전부 0 에서 출발
#    - 표준화: (x - 평균) / 표준편차, 표준편차는 numpy 기본(.std())
# =====================================================================

import os
import numpy as np
import pandas as pd

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "데이터")

df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i_전체.csv"), encoding="utf-8-sig")


# 수업 01, 02의 예측, 손실, 학습, R2 함수를 다변수에도 사용하도록 작성
def 예측(Z, w, b):
    return Z @ w + b


def 손실(y, yhat):
    return np.mean((y - yhat) ** 2)


def R2(y, yhat):
    return 1 - np.sum((y - yhat) ** 2) / np.sum((y - y.mean()) ** 2)


def 학습(Z, y, lr=0.1, epochs=500):
    w = np.zeros(Z.shape[1])
    b = 0.0

    for _ in range(epochs):
        오차 = 예측(Z, w, b) - y
        gw = 2 * (Z.T @ 오차) / len(y)
        gb = 2 * 오차.mean()

        w = w - lr * gw
        b = b - lr * gb

    return w, b


# ---------------------------------------------------------------------
# [2-1] 회전수 하나로 토크   (10,000행 전부 사용, 나누지 않음)
#   경사하강으로 학습하세요. 입력은 표준화. lr 0.1, 500 epochs.
#   확인값: 표준화 눈금에서 w ≈ -8.72, b ≈ 39.99, 마지막 손실 ≈ 23.29
#
#   그다음, 학습한 w, b 를 '원래 눈금'으로 되돌려서
#       토크 ≈ (   ) × 회전수 + (   )
#   꼴로 찍으세요.  ★ 공식은 직접 유도하세요 ★ (표준화 식을 예측 식에 대입하면 나옵니다)
#   확인: np.polyfit 으로 구한 직선과 소수 셋째 자리까지 같아야 합니다.  (-0.0487, 114.86)
#
#   ★ 설명 ★  "회전수가 100 rpm 오르면 토크는 몇 Nm 바뀐다" 를 한 문장으로.
#   ★ 설명 ★  이 모델의 R² 와 [문제1 1-4 (c)] 의 상관계수 사이에 어떤 관계가 있나요? 숫자로 확인하세요.
# ---------------------------------------------------------------------
print("[2-1] 회전수 하나로 토크 예측")

x = df["회전수"].values.astype(float)
y = df["토크"].values.astype(float)

평균 = x.mean()
표준편차 = x.std()
z = ((x - 평균) / 표준편차).reshape(-1, 1)

w, b = 학습(z, y, lr=0.1, epochs=500)
yhat = 예측(z, w, b)

print(f"표준화 가중치 w {w[0]:.4f}")
print(f"절편 b {b:.4f}")
print(f"마지막 손실 {손실(y, yhat):.4f}")

# y = w * ((x - 평균) / 표준편차) + b
#   = (w / 표준편차) * x + (b - w * 평균 / 표준편차)
원래_w = w[0] / 표준편차
원래_b = b - w[0] * 평균 / 표준편차

print(f"원래 눈금: 토크 ≈ {원래_w:.4f} × 회전수 + {원래_b:.4f}")

대조_w, 대조_b = np.polyfit(x, y, 1)
print(f"polyfit 결과: w {대조_w:.4f}, b {대조_b:.4f}")

상관계수 = df[["회전수", "토크"]].corr().loc["회전수", "토크"]
print(f"R² {R2(y, yhat):.4f}")
print(f"상관계수 {상관계수:.4f}")
print(f"상관계수 제곱 {상관계수**2:.4f}")

# 회전수가 100rpm 증가하면 토크는 평균적으로 약 4.87Nm 감소
# 단순 선형회귀에서 절편이 있을 때 R²는 피어슨 상관계수의 제곱과 같음
# 상관계수 약 -0.8750의 제곱은 약 0.7657로 모델의 R²와 같음


# ---------------------------------------------------------------------
# [2-2] 학습률 실험
#   ★ 먼저 예측 ★  lr 을 0.001 / 0.01 / 0.1 / 0.5 / 0.9 / 1.0 / 1.1 로 바꿔
#                  50 epochs 만 걸으면, 각각 손실이 어떻게 될까요? (줄어듦 / 바닥 / 튕김 / 발산)
#   그다음 실제로 돌려 표로 찍으세요.
#   확인: 0.1~0.9 는 같은 바닥(≈23.29), 1.0 은 바닥에 못 감, 1.1 은 10의 11제곱 대로 발산.
#
#   ★ 설명 ★  0.5 에서 어떤 특별한 일이 일어나는지, 첫 몇 걸음의 w 를 찍어 보고 설명하세요.
#             (힌트: 표준화된 입력 하나면 기울기가 2 × (w - 정답 w) 꼴입니다)
# ---------------------------------------------------------------------

# ★ 먼저 예측 ★
# lr 0.001: 너무 작아서 손실이 천천히 줄어듦
# lr 0.01 : 손실이 줄지만 50번으로는 바닥에 도달하지 못함
# lr 0.1  : 손실이 빠르게 줄어 바닥에 도달
# lr 0.5  : 한 번에 최적 가중치에 도달
# lr 0.9  : 바닥을 지나며 튕기지만 결국 수렴
# lr 1.0  : 계속 튕겨 바닥에 도달하지 못함
# lr 1.1  : 튕기는 폭이 커지면서 발산

print("\n[2-2] 학습률 실험")
print(f"{'lr':<8} {'손실':>18}")

for lr in [0.001, 0.01, 0.1, 0.5, 0.9, 1.0, 1.1]:
    w_lr, b_lr = 학습(z, y, lr=lr, epochs=50)
    mse = 손실(y, 예측(z, w_lr, b_lr))
    print(f"{lr:<8} {mse:>18.4f}")

print("\nlr=0.5 첫 5걸음의 w")

w_05 = np.zeros(1)
b_05 = 0.0

for epoch in range(5):
    오차 = 예측(z, w_05, b_05) - y
    gw = 2 * (z.T @ 오차) / len(y)
    gb = 2 * 오차.mean()

    w_05 = w_05 - 0.5 * gw
    b_05 = b_05 - 0.5 * gb

    print(f"epoch {epoch + 1} w {w_05[0]:.4f}, b {b_05:.4f}")

# 표준화된 입력은 평균 0, 분산 1이므로 w의 기울기는 2 × (w - 최적 w)
# lr=0.5이면 w_new = w - 0.5 × 2 × (w - 최적 w) = 최적 w
# 따라서 첫 번째 걸음에 최적 가중치에 도달하고 이후 변하지 않음


