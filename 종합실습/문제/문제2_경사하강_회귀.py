# [2-5] 과적합을 '만들어' 보기
#   [2-4] 의 입력 4개에 '아무 의미 없는 잡음 열' 20개를 붙입니다.
#     잡음 = np.random.RandomState(1).randn(10000, 20)
#   train 을 앞에서부터 10 / 30 / 100 / 1000 / 7000 개만 써서 학습하고 (lr 0.05, 3000 epochs)
#   train R² 와 test R² 를 나란히 찍으세요.  ★ 표준화 기준은 매번 '그때 쓴 train' 으로 ★
#
#   ★ 먼저 예측 ★  n=10 일 때 train R² 는? test R² 는?
#   확인: n=10 → train 1.000 / test 0.3 근처,  n=7000 → 둘 다 0.766
#
#   ★ 설명 ★  모델도 특징도 그대로인데 '데이터 양'만으로 과적합이 생기고 사라졌습니다. 왜?
# ---------------------------------------------------------------------

# ★ 먼저 예측 ★
# n=10이면 특징 24개에 비해 데이터가 적어서 train R²는 1에 가까울 것
# 우연한 잡음까지 외우게 되어 test R²는 약 0.3으로 낮아질 것

print("\n[2-5] 과적합 실험")

잡음 = np.random.RandomState(1).randn(10000, 20)
X_잡음 = np.column_stack((X, 잡음))

# [2-4]와 같은 순서로 나누기
X_잡음_train = X_잡음[train_idx]
X_잡음_test = X_잡음[test_idx]

print(f"{'train 수':<10} {'train R²':>12} {'test R²':>12}")

for n in [10, 30, 100, 1000, 7000]:
    X_n = X_잡음_train[:n]
    y_n = y_train[:n]

    # 매번 현재 학습 데이터의 평균과 표준편차로 표준화
    mu_n = X_n.mean(axis=0)
    sd_n = X_n.std(axis=0)

    Z_n = (X_n - mu_n) / sd_n
    Z_n_test = (X_잡음_test - mu_n) / sd_n

    w_n, b_n = 학습(Z_n, y_n, lr=0.05, epochs=3000)

    train_r2 = R2(y_n, 예측(Z_n, w_n, b_n))
    test_r2 = R2(y_test, 예측(Z_n_test, w_n, b_n))

    print(f"{n:<10} {train_r2:>12.4f} {test_r2:>12.4f}")

# 데이터가 적으면 특징 24개로 적은 학습 데이터를 거의 완벽하게 외울 수 있음
# 하지만 잡음에서 우연히 나타난 관계까지 학습하므로 새로운 데이터에서는 성능이 낮아짐
# 데이터가 많아지면 우연한 잡음의 영향이 줄고 실제 회전수와 토크의 관계를 학습
# 따라서 모델과 특징이 같아도 학습 데이터 양에 따라 과적합 정도가 달라짐


