# [2-4] 센서 네 개 + train/test
#   입력: 회전수, 공기온도, 공정온도, 공구마모 (이 순서)   정답: 토크
#   나누기: np.random.RandomState(0).permutation 으로 섞고, 앞 7,000 = train, 뒤 3,000 = test
#   학습: lr 0.1, 500 epochs
#
#   ★ 먼저 예측 ★  네 가중치 중 어느 게 가장 클까요? 나머지는? (1-4 의 상관표를 근거로)
#   확인값: 회전수 ≈ -8.758, 나머지 셋은 전부 |0.05| 미만, b ≈ 40.007
#           train R² ≈ 0.7656, test R² ≈ 0.7656
#   대조: np.linalg.lstsq 로 구한 최소제곱 해와 같은지 확인하세요.
#
#   ★ 설명 ★  train R² 와 test R² 가 거의 같습니다. 왜 이번엔 과적합이 안 보일까요?
#   ★ 설명 ★  -8.758 은 '회전수 1 rpm 당 -8.758 Nm' 인가요? 아니라면 뭔가요?
# ---------------------------------------------------------------------

# ★ 먼저 예측 ★
# 회전수는 토크와 약 -0.875의 강한 음의 상관관계이므로 음수 가중치의 절댓값이 가장 클 것
# 나머지 공기온도, 공정온도, 공구마모는 상관관계가 약해 가중치가 0에 가까울 것

print("\n[2-4] 센서 네 개 + train/test")

특징 = ["회전수", "공기온도", "공정온도", "공구마모"]
X = df[특징].values.astype(float)

순서 = np.random.RandomState(0).permutation(len(X))
train_idx = 순서[:7000]
test_idx = 순서[7000:]

X_train = X[train_idx]
X_test = X[test_idx]
y_train = y[train_idx]
y_test = y[test_idx]

# 표준화 기준은 train에서만 계산하고 test에도 동일하게 적용
mu = X_train.mean(axis=0)
sd = X_train.std(axis=0)

Z_train = (X_train - mu) / sd
Z_test = (X_test - mu) / sd

w4, b4 = 학습(Z_train, y_train, lr=0.1, epochs=500)

print("표준화 가중치")
for 이름, wi in zip(특징, w4):
    print(f"{이름} {wi:.4f}")

print(f"절편 b {b4:.4f}")

train_pred = 예측(Z_train, w4, b4)
test_pred = 예측(Z_test, w4, b4)

print(f"train R² {R2(y_train, train_pred):.4f}")
print(f"test R² {R2(y_test, test_pred):.4f}")

# 최소제곱 해와 비교하기 위해 절편에 해당하는 1 열 추가
Z_절편 = np.column_stack((Z_train, np.ones(len(Z_train))))
최소제곱해 = np.linalg.lstsq(Z_절편, y_train, rcond=None)[0]

print(f"경사하강 가중치 {w4}")
print(f"최소제곱 가중치 {최소제곱해[:-1]}")
print(f"경사하강 절편 {b4:.4f}")
print(f"최소제곱 절편 {최소제곱해[-1]:.4f}")

# 학습 데이터가 7000개로 충분하고 가중치는 4개뿐이므로 과적합 위험이 낮음
# train과 test가 같은 분포에서 무작위로 나뉘어 성능도 비슷하게 나타남
# -8.758은 회전수가 1rpm 증가할 때가 아니라 표준편차 1개만큼 증가할 때
# 다른 센서가 같다면 토크 예측값이 약 8.758Nm 감소한다는 의미


