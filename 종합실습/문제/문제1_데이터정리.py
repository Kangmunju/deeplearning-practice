print("\n[1-3] 데이터 정제")

clean = df.copy()

# 중복 행: 동일한 기록이므로 하나만 남김
clean = clean.drop_duplicates().copy()

# 센서 먹통: 회전수 0은 정상적인 측정값이 아니므로 결측으로 변경
clean.loc[clean["회전수"] == 0, "회전수"] = float("nan")

# 단위 오류: 섭씨로 기록된 공기온도를 켈빈으로 변환
clean.loc[clean["공기온도"] < 100, "공기온도"] += 273.15
clean["공기온도"] = clean["공기온도"].round(1)

# 결측: 이상값을 처리한 후 각 열의 중앙값으로 대체
for col in ["공기온도", "회전수", "토크"]:
    중앙값 = clean[col].median()
    clean[col] = clean[col].fillna(중앙값)
    print(f"{col} 중앙값 {중앙값}")

print(f"정제 후 모양 {clean.shape}")
print(f"남은 결측 {int(clean.isna().sum().sum())}")
print(f"공기온도 범위 {clean['공기온도'].min()} ~ {clean['공기온도'].max()}")
print(f"회전수 최솟값 {clean['회전수'].min()}")

# 자기 채점: 설비ID를 기준으로 정렬한 뒤 원본과 비교
원본 = pd.read_csv(
    os.path.join(DATA, "11_설비센서_ai4i_전체.csv"), encoding="utf-8-sig"
)

비교_clean = clean.set_index("설비ID").sort_index()
비교_원본 = 원본.set_index("설비ID").sort_index()

차이 = 비교_clean.ne(비교_원본)

# 섭씨를 켈빈으로 환산할 때 발생하는 반올림 차이는 제외
단위오류_ID = df.loc[단위오류, "설비ID"]
차이.loc[단위오류_ID, "공기온도"] = False

print(f"원본과 다른 칸 수 {int(차이.sum().sum())}")
print(f"열별 다른 칸 수 {차이.sum()}")

