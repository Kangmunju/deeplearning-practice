#     여러분이 고친 표와 원본을 설비ID 로 맞춰 놓고, 값이 다른 칸이 몇 개인지 세 보세요.
#     여러분이 '메운' 칸 수와 같아야 합니다 (71칸). 그보다 많으면 어딘가 잘못 고친 겁니다.
#     (힌트: 순서가 섞여 있으니 설비ID 로 정렬하거나 인덱스로 맞춰야 합니다)
