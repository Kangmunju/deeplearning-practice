# =====================================================================
#  문제 7 — 직선 하나의 한계, 그리고 깊이의 대가  (10)
# =====================================================================
#  [쓰는 것]  표준 math, random 만. (numpy 없이)
#  [퍼셉트론 규칙]  10 에서 배운 그대로 — 계단 활성화(z ≥ 0 이면 1),
#                  틀리면 w += lr × 오차 × x,  b += lr × 오차
#                  시작값 random.uniform(-1, 1), random.seed(0), lr 0.1, 50 에폭
#  입력 네 개: (0,0) (0,1) (1,0) (1,1)
# =====================================================================

import math
import random

입력 = [(0, 0), (0, 1), (1, 0), (1, 1)]


def 계단(z):
    if z >= 0:
        return 1
    return 0


def 예측(x, w, b):
    z = w[0] * x[0] + w[1] * x[1] + b
    return 계단(z)


def 학습(정답):
    random.seed(0)

    w = [random.uniform(-1, 1), random.uniform(-1, 1)]
    b = random.uniform(-1, 1)

    for epoch in range(50):
        for x, y in zip(입력, 정답):
            yhat = 예측(x, w, b)
            오차 = y - yhat

            if 오차 != 0:
                w[0] += 0.1 * 오차 * x[0]
                w[1] += 0.1 * 오차 * x[1]
                b += 0.1 * 오차

    return w, b


