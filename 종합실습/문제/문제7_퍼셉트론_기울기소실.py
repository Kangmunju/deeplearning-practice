# ★ 먼저 예측 ★
# XNOR는 (0,0), (1,1)이 1이고 (0,1), (1,0)이 0
# 두 종류의 점이 대각선으로 배치되어 직선 하나로 나눌 수 없음
# 따라서 XNOR만 단일 퍼셉트론으로 학습할 수 없을 것으로 예상

print("[7-1] 네 게이트")

게이트 = {
    "NAND": [1, 1, 1, 0],
    "AND NOT": [0, 0, 1, 0],
    "XNOR": [1, 0, 0, 1],
    "항상 1": [1, 1, 1, 1],
}

for 이름, 정답 in 게이트.items():
    w, b = 학습(정답)

    결과 = []
    for x in 입력:
        결과.append(예측(x, w, b))

    맞힌수 = 0
    for p, y in zip(결과, 정답):
        if p == y:
            맞힌수 += 1

    print(f"{이름}: {맞힌수}/4")
    print(f"  예측 {결과}")
    print(f"  w {[round(v, 4) for v in w]}, b {b:.4f}")

# NAND, AND NOT, 항상 1은 4/4로 학습 가능
# XNOR는 직선 하나로 분리할 수 없어 완전히 학습하지 못함
# 이 초기값과 학습 순서에서는 XNOR가 1/4로 나옴


