print("\n[7-2] 퍼셉트론 조립으로 XNOR")

# XNOR = (x1 AND x2) OR (NOT x1 AND NOT x2)
#      = AND의 출력 OR NOR의 출력

AND_w, AND_b = 학습([0, 0, 0, 1])
NOR_w, NOR_b = 학습([1, 0, 0, 0])
OR_w, OR_b = 학습([0, 1, 1, 1])

XNOR_정답 = [1, 0, 0, 1]
맞힌수 = 0

for x, y in zip(입력, XNOR_정답):
    # 첫 층: AND와 NOR
    and값 = 예측(x, AND_w, AND_b)
    nor값 = 예측(x, NOR_w, NOR_b)

    # 두 번째 층: OR
    첫층 = (and값, nor값)
    최종 = 예측(첫층, OR_w, OR_b)

    if 최종 == y:
        맞힌수 += 1

    print(f"입력 {x} → 첫 층 {첫층} → 최종 {최종} / 정답 {y}")

print(f"XNOR 정확도 {맞힌수}/4")

# 첫 층에서 네 점은 다음과 같이 변환됨
# (0,0) → (0,1) : 정답 1
# (0,1) → (0,0) : 정답 0
# (1,0) → (0,0) : 정답 0
# (1,1) → (1,0) : 정답 1
