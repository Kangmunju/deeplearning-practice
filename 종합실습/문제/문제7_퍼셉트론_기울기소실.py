# ★ 먼저 예측 ★
# 20층에서는 ReLU > tanh > sigmoid 순서로 기울기가 클 것으로 예상
# ReLU는 양수 구간의 미분값이 1이라 기울기가 유지됨
# tanh는 1보다 작은 값이 곱해지고 sigmoid는 최대 0.25만 곱해짐

print("\n[7-4] 사슬 실험")


def sigmoid(z):
    return 1 / (1 + math.exp(-z))


def 사슬(함수, 층수, 시작값):
    a = 시작값
    기울기 = 1.0
    w = 1.0

    for i in range(층수):
        z = w * a

        if 함수 == "sigmoid":
            a = sigmoid(z)
            지역기울기 = w * a * (1 - a)

        elif 함수 == "tanh":
            a = math.tanh(z)
            지역기울기 = w * (1 - a**2)

        else:
            a = max(0, z)

            if z > 0:
                지역기울기 = w
            else:
                지역기울기 = 0

        기울기 *= 지역기울기

    return a, 기울기


print(f"{'층수':<8} {'sigmoid':>14} {'tanh':>14} {'ReLU':>14}")

for 층수 in [1, 5, 10, 20]:
    _, sigmoid기울기 = 사슬("sigmoid", 층수, 0.5)
    _, tanh기울기 = 사슬("tanh", 층수, 0.5)
    _, relu기울기 = 사슬("ReLU", 층수, 0.5)

    print(f"{층수:<8} {sigmoid기울기:>14.3e} {tanh기울기:>14.3e} {relu기울기:>14.3e}")

print("\nReLU 시작값 -0.5 실험")

끝값, 기울기 = 사슬("ReLU", 10, -0.5)

print(f"끝값 {끝값}")
print(f"기울기 {기울기}")

# 시작값이 -0.5이면 첫 층의 ReLU 출력은 0
# 음수 구간의 ReLU 미분값도 0이므로 전체 기울기는 0
# 이후 층에서도 출력이 0으로 유지됨
# 이를 죽은 ReLU(Dying ReLU) 문제라고 함

