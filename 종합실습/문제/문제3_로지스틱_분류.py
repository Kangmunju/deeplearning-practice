import os
import numpy as np
import pandas as pd

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "데이터")

df = pd.read_csv(os.path.join(DATA, "11_설비센서_ai4i_전체.csv"), encoding="utf-8-sig")

특징 = ["공기온도", "공정온도", "회전수", "토크", "공구마모"]
X = df[특징].values.astype(float)
y = df["고장여부"].values.astype(float)


# ---------------------------------------------------------------------
# [3-1] 고장 비율을 지키며 나누기 (손으로)
#   rng = np.random.RandomState(0) 를 '하나' 만들고,
#   고장 행 번호를 먼저 섞고 → 그다음 정상 행 번호를 섞어서 (같은 rng 로, 이 순서로)
#   각각 앞 70% (int 로 버림) 를 train, 나머지를 test 로 합치세요.
#   확인값: train 6,999 (고장 237) / test 3,001 (고장 102)
#
#   ★ 먼저 예측 ★  "무조건 정상이라고만 답하는" 게으른 모델의 test 정확도는?  계산해서 확인하세요.
# ---------------------------------------------------------------------

# ★ 먼저 예측 ★
# test 3001대 중 고장 102대를 제외한 2899대는 정상
# 무조건 정상이라고 예측하면 정확도는 2899 / 3001 ≈ 0.9660

print("[3-1] 고장 비율을 지키며 나누기")

rng = np.random.RandomState(0)

고장idx = rng.permutation(np.where(y == 1)[0])
정상idx = rng.permutation(np.where(y == 0)[0])

고장수 = int(len(고장idx) * 0.7)
정상수 = int(len(정상idx) * 0.7)

train_idx = np.concatenate([고장idx[:고장수], 정상idx[:정상수]])
test_idx = np.concatenate([고장idx[고장수:], 정상idx[정상수:]])

X_train = X[train_idx]
X_test = X[test_idx]
y_train = y[train_idx]
y_test = y[test_idx]

print(f"train {len(y_train)}대 (고장 {int(y_train.sum())})")
print(f"test {len(y_test)}대 (고장 {int(y_test.sum())})")

게으른판정 = np.zeros_like(y_test)
print(f"무조건 정상 정확도 {np.mean(게으른판정 == y_test):.4f}")

# 표준화 기준은 train에서만 계산
mu = X_train.mean(axis=0)
sd = X_train.std(axis=0)

Z_train = (X_train - mu) / sd
Z_test = (X_test - mu) / sd


# ---------------------------------------------------------------------
# [3-2] 로지스틱 회귀를 손으로
#   sigmoid, 로그손실, 경사하강 학습을 직접 만드세요.
#   ★ 기울기 공식은 외운 걸 쓰지 말고, 03 에서 본 '(p - y)' 가 어디서 나왔는지 떠올리며 쓰세요.
#
#   확인값: train 로그손실 ≈ 0.0957 / test ≈ 0.0973
#           가중치 크기 순서: 토크(+2.72) > 회전수(+2.05) > 공기온도(+1.50) > 공정온도(-1.08) > 공구마모(+0.80)
#   임계값 0.5 로 판정해서 정확도, 잡음/놓침/헛경보, 재현율, 정밀도를 찍으세요.
#   확인값: 정확도 0.9703 / 잡음 21 놓침 81 헛경보 8 / 재현율 0.206
#
#   ★ 설명 ★  정확도 97% 입니다. 정비팀장에게 "97% 맞힙니다" 라고 보고하면 어떤 일이 생길까요?
#   ★ 설명 ★  토크와 회전수 가중치가 둘 다 '+' 입니다. 그런데 문제 2 에서 둘은 반대로 움직였죠(상관 -0.87).
#             둘 다 + 라는 게 이상한가요? (힌트: 전력 = 토크 × 회전수)
# ---------------------------------------------------------------------


def sigmoid(z):
    return 1 / (1 + np.exp(-z))


def 확률(Z, w, b):
    return sigmoid(Z @ w + b)


def 손실(y, p):
    p = np.clip(p, 1e-12, 1 - 1e-12)
    return -np.mean(y * np.log(p) + (1 - y) * np.log(1 - p))


def 학습(Z, y, lr=0.5, epochs=2000):
    w = np.zeros(Z.shape[1])
    b = 0.0

    for epoch in range(epochs):
        p = 확률(Z, w, b)
        오차 = p - y

        # BCE를 sigmoid 입력값에 대해 미분하면 p-y
        # 따라서 가중치 기울기는 Z.T @ (p-y) / 데이터 수
        gw = Z.T @ 오차 / len(y)
        gb = 오차.mean()

        w = w - lr * gw
        b = b - lr * gb

    return w, b


def 네칸(y, 판정):
    TP = int(((y == 1) & (판정 == 1)).sum())
    FN = int(((y == 1) & (판정 == 0)).sum())
    FP = int(((y == 0) & (판정 == 1)).sum())
    TN = int(((y == 0) & (판정 == 0)).sum())
    return TP, FN, FP, TN


def 평가(y, p, 임계값):
    판정 = (p >= 임계값).astype(int)
    TP, FN, FP, TN = 네칸(y, 판정)

    재현율 = 0
    정밀도 = 0
    F1 = 0

    if TP + FN > 0:
        재현율 = TP / (TP + FN)

    if TP + FP > 0:
        정밀도 = TP / (TP + FP)

    if 재현율 + 정밀도 > 0:
        F1 = 2 * 재현율 * 정밀도 / (재현율 + 정밀도)

    return TP, FN, FP, TN, 재현율, 정밀도, F1


print("\n[3-2] 로지스틱 회귀 학습")

w, b = 학습(Z_train, y_train)

P_train = 확률(Z_train, w, b)
P_test = 확률(Z_test, w, b)

print(f"train 로그손실 {손실(y_train, P_train):.4f}")
print(f"test 로그손실 {손실(y_test, P_test):.4f}")

print("가중치")
for 이름, wi in zip(특징, w):
    print(f"{이름} {wi:+.4f}")

TP, FN, FP, TN, 재현율, 정밀도, F1 = 평가(y_test, P_test, 0.5)

정확도 = (TP + TN) / len(y_test)

print(f"정확도 {정확도:.4f}")
print(f"잡음 {TP} / 놓침 {FN} / 헛경보 {FP} / 정상통과 {TN}")
print(f"재현율 {재현율:.4f}")
print(f"정밀도 {정밀도:.4f}")

# 정확도는 약 97%지만 실제 고장 102대 중 21대만 발견하고 81대를 놓침
# 정확도만 보고하면 정비팀장이 모델의 고장 탐지 능력을 과대평가할 수 있음
# 고장이 드문 불균형 데이터에서는 정확도보다 재현율과 놓침 수를 함께 확인해야 함

# 토크와 회전수의 상관계수가 음수여도 두 가중치가 양수인 것은 이상하지 않음
# 상관계수는 두 센서 사이의 관계이고 가중치는 다른 센서가 같을 때 고장 확률에 미치는 영향
# 전력은 토크와 회전수의 곱이므로 둘 다 커지면 전력 부담이 증가해 고장 위험이 높아질 수 있음


