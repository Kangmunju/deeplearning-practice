#    - 입력: 공기온도, 공정온도, 회전수, 토크, 공구마모   정답: 고장여부
#    - 가중치 0 에서 출발, lr 0.5, 2000 epochs, 표준화는 train 기준
#    - 손실은 로그손실(BCE)
