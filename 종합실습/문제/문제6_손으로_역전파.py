# =====================================================================
#  문제 6 — 종이와 연필로 역전파  (08 · 09)
# =====================================================================
#  ★ 이 문제는 [6-1] [6-2] 를 '반드시 종이에 먼저' 푸세요. 계산기는 써도 됩니다. ★
#  ★ 종이 답을 주석에 적은 다음에 코드로 확인하세요. ★
#
#  [망]  입력 2 → 은닉 2 (sigmoid) → 출력 1 (활성화 없음), 손실 L = (ŷ - y)², 샘플 하나
#
#      x  = [1.0, 2.0]          y = 1.0
#      W  = [[ 0.5, -0.5],      W[i][j] = 입력 i 에서 은닉 j 로 가는 가중치
#            [ 0.2,  0.1]]
#      b  = [0.0, 0.0]          (은닉 편향)
#      V  = [1.0, -1.0]         (은닉 → 출력)
#      c  = 0.5                 (출력 편향)
#
#  [쓰는 것]  numpy 만. 파라미터는 W 4 + b 2 + V 2 + c 1 = 11개.
# =====================================================================

import numpy as np

x = np.array([1.0, 2.0])
y = 1.0

W = np.array([[0.5, -0.5], [0.2, 0.1]])
b = np.array([0.0, 0.0])
V = np.array([1.0, -1.0])
c = 0.5


def sigmoid(z):
    return 1 / (1 + np.exp(-z))


# ---------------------------------------------------------------------
# [6-1] 순전파 (종이)
#   z(2개), a(2개), ŷ, L 을 구하세요.
#   확인: ŷ ≈ 0.785 근처, L ≈ 0.046
# ---------------------------------------------------------------------
# 종이 답:
#   z = xW + b = [0.9, -0.3]
#   a = sigmoid(z) = [0.710950, 0.425557]
#   ŷ = aV + c = 0.710950 - 0.425557 + 0.5 = 0.785392
#   L = (ŷ - y)² = (0.785392 - 1)² = 0.046057

print("[6-1] 순전파")

z = x @ W + b
a = sigmoid(z)
yhat = a @ V + c
L = (yhat - y) ** 2

print(f"z = {z}")
print(f"a = {a.round(6)}")
print(f"ŷ = {yhat:.6f}")
print(f"L = {L:.6f}")


# ---------------------------------------------------------------------
# [6-2] 역전파 (종이)
#   11개 기울기를 전부 구하세요. 출력에서 시작해 거꾸로.
#   순서: dŷ → dV, dc → da → dz → dW, db
#   ★ 설명 ★  dW 의 둘째 행이 첫째 행의 몇 배인가요? 왜 그런가요?
#   ★ 설명 ★  dz 두 개의 부호가 서로 반대입니다. 왜 그런가요?
# ---------------------------------------------------------------------
# 종이 답:
#   dŷ = 2(ŷ - y) = -0.429216
#
#   dV = dŷ × a = [-0.305151, -0.182656]
#   dc = dŷ = -0.429216
#
#   da = dŷ × V = [-0.429216, 0.429216]
#
#   dz = da × a(1-a) = [-0.088204, 0.104925]
#
#   dW = x.T × dz = [[-0.088204, 0.104925],
#                    [-0.176408, 0.209851]]
#   db = dz = [-0.088204, 0.104925]
#
# ★ 설명 ★
# dW의 둘째 행은 첫째 행의 2배
# dW[i][j] = x[i] × dz[j] 이고 x[1]=2, x[0]=1이기 때문
#
# dz 두 개의 부호가 반대인 이유는 V=[1,-1]이기 때문
# sigmoid 미분값 a(1-a)는 양수이므로 da의 부호가 그대로 전달됨

print("\n[6-2] 역전파")

dy = 2 * (yhat - y)

dV = dy * a
dc = dy

da = dy * V
dz = da * a * (1 - a)

dW = np.outer(x, dz)
db = dz.copy()

print(f"dŷ = {dy:.6f}")
print(f"dV = {dV.round(6)}")
print(f"dc = {dc:.6f}")
print(f"da = {da.round(6)}")
print(f"dz = {dz.round(6)}")
print(f"dW =\n{dW.round(6)}")
print(f"db = {db.round(6)}")


# ---------------------------------------------------------------------
# [6-3] 코드로 채점
#   순전파·역전파를 코드로 짜서 종이 답과 비교하고,
#   11개 전부를 수치미분 ((L(θ+h) - L(θ-h)) / 2h, h=1e-5) 과 대조하세요.
#   확인: 최대 차이가 1e-8 보다 작아야 합니다.
# ---------------------------------------------------------------------
print("\n[6-3] 수치미분으로 채점")

# 파라미터 11개를 하나의 배열로 합치기
# 순서: W 4개, b 2개, V 2개, c 1개
theta = np.concatenate((W.flatten(), b, V, [c]))

# 역전파로 계산한 기울기도 같은 순서로 합치기
역전파기울기 = np.concatenate((dW.flatten(), db, dV, [dc]))


def 손실계산(theta):
    W = theta[:4].reshape(2, 2)
    b = theta[4:6]
    V = theta[6:8]
    c = theta[8]

    z = x @ W + b
    a = sigmoid(z)
    yhat = a @ V + c

    return (yhat - y) ** 2


# theta에는 실제로 W 4 + b 2 + V 2 + c 1 = 9개가 들어감
# 문제 설명의 '11개'는 합계가 잘못 적힌 것으로, 실제 파라미터는 9개

h = 1e-5
수치기울기 = np.zeros(len(theta))

for i in range(len(theta)):
    plus = theta.copy()
    minus = theta.copy()

    plus[i] += h
    minus[i] -= h

    수치기울기[i] = (손실계산(plus) - 손실계산(minus)) / (2 * h)

print(f"{'파라미터':<12} {'역전파':>14} {'수치미분':>14} {'차이':>14}")

이름들 = ["W00", "W01", "W10", "W11", "b0", "b1", "V0", "V1", "c"]

for i in range(len(theta)):
    차이 = abs(역전파기울기[i] - 수치기울기[i])
    print(
        f"{이름들[i]:<12} {역전파기울기[i]:>14.8f} {수치기울기[i]:>14.8f} {차이:>14.2e}"
    )

최대차이 = np.max(np.abs(역전파기울기 - 수치기울기))

print(f"최대 차이 {최대차이:.2e}")
print(f"1e-8 미만 여부 {최대차이 < 1e-8}")

# 역전파는 미분 공식을 이용해 기울기를 계산
# 수치미분은 파라미터를 조금씩 바꿔 손실 변화로 기울기를 근사
# 두 결과의 차이가 매우 작으면 역전파 계산이 올바르다고 판단


# ---------------------------------------------------------------------
# [6-4] 한 걸음
#   lr 0.1 로 11개를 한 번 갱신하고 손실을 다시 재세요.
#   확인: 0.0461 → 0.0135 근처
# ---------------------------------------------------------------------
print("\n[6-4] 한 걸음 갱신")

lr = 0.1

W_new = W - lr * dW
b_new = b - lr * db
V_new = V - lr * dV
c_new = c - lr * dc

z_new = x @ W_new + b_new
a_new = sigmoid(z_new)
yhat_new = a_new @ V_new + c_new
L_new = (yhat_new - y) ** 2

print(f"갱신 전 손실 {L:.6f}")
print(f"갱신 후 손실 {L_new:.6f}")

# 기울기의 반대 방향으로 파라미터를 갱신해 손실이 감소
# 0.046057 → 약 0.013480


# ---------------------------------------------------------------------
# [6-5] 활성화를 빼면
#   은닉층의 sigmoid 를 뺀 망은 '직선 하나' (ŷ = x·w + b) 와 같습니다.
#   ★ 종이로 ★  그 직선의 w (2개) 와 b 를 W, b, V, c 로 표현하고 숫자를 구하세요.
#   코드로: 아무 입력 5개를 넣어 '활성화 없는 망' 과 '그 직선' 의 출력이 같은지 확인하세요.
#   ★ 설명 ★  그럼 은닉층을 10개 쌓으면 달라지나요? 08 의 U자 데이터와 연결해서.
# ---------------------------------------------------------------------

# ★ 종이 답 ★
# ŷ = (xW + b)V + c
#   = x(WV) + (bV + c)
#
# 직선의 w = WV
#           = [0.5×1 + (-0.5)×(-1), 0.2×1 + 0.1×(-1)]
#           = [1.0, 0.1]
#
# 직선의 b = bV + c = 0.5
# 따라서 ŷ = 1.0×x1 + 0.1×x2 + 0.5

print("\n[6-5] 활성화 없는 망")

직선w = W @ V
직선b = b @ V + c

print(f"직선 가중치 {직선w}")
print(f"직선 절편 {직선b:.4f}")

입력5개 = np.array([[1.0, 2.0], [2.0, 3.0], [0.0, 1.0], [-1.0, 2.0], [3.0, -2.0]])

망출력 = (입력5개 @ W + b) @ V + c
직선출력 = 입력5개 @ 직선w + 직선b

print(f"활성화 없는 망 {망출력}")
print(f"직선 하나 {직선출력}")
print(f"두 출력 일치 여부 {np.allclose(망출력, 직선출력)}")

# 활성화 함수가 없다면 여러 선형변환을 합쳐도 결국 하나의 선형변환
# 따라서 은닉층을 10개 쌓아도 직선이라는 한계를 벗어나지 못함
# 08의 U자 데이터처럼 곡선 관계를 학습하려면 비선형 활성화 함수가 필요


# ---------------------------------------------------------------------
# [6-6] 표준화를 안 하면
#   입력을 원래 눈금 그대로 x = [300.0, 1400.0] (공기온도, 회전수) 로 넣었다고 합시다. (W, b 는 그대로)
#   z, a, 그리고 a(1-a) 를 구하세요.
#   ★ 설명 ★  [6-2] 의 사슬에서 a(1-a) 가 어디에 곱해졌나요? 이 값이면 dW 는 어떻게 되나요?
#             09 에서 "표준화를 안 하면 학습이 아예 안 된다" 고 한 이유를 이 숫자로 설명하세요.
# ---------------------------------------------------------------------
print("\n[6-6] 표준화하지 않은 입력")

원래x = np.array([300.0, 1400.0])

원래z = 원래x @ W + b
원래a = sigmoid(원래z)
sigmoid미분 = 원래a * (1 - 원래a)

print(f"z = {원래z}")
print(f"a = {원래a}")
print(f"a(1-a) = {sigmoid미분}")

# z = [430, -10]
# a ≈ [1.0, 0.0000454]
# a(1-a) ≈ [0, 0.0000454]
#
# [6-2]에서 dz = da × a(1-a) 부분에 sigmoid 미분값이 곱해짐
# 첫 번째 은닉 뉴런은 sigmoid가 1에 포화되어 기울기가 거의 0
# 두 번째 은닉 뉴런도 기울기가 매우 작아짐
# dW = x.T × dz이므로 입력값이 커도 포화된 뉴런은 가중치 갱신이 어려움
# 따라서 표준화하지 않으면 sigmoid가 포화되어 기울기 소실과 학습 정체가 발생할 수 있음


